"""Сверка слоёв: различить свою правку и чужую поломку.

Найти разницу — полдела. Важнее сказать, чем она объясняется: правка бухгалтера
это решение человека, а расхождение «отправили одно, приняли другое» — поломка
канала, и разговор с 1С будет совсем другим.
"""
from app.services.accounting_reconciliation import (
    СверкаСмены, СостояниеСлоя, _выводы, сумма_документов,
)


def слой(сумма: float, документов: int = 1, есть: bool = True, примечание: str = ""):
    return СостояниеСлоя(есть=есть, документов=документов, сумма=сумма,
                         примечание=примечание)


def сверка(**поля) -> СверкаСмены:
    основа = dict(
        shift_key="см-1",
        факт=слой(1000.0),
        отправлено=слой(1000.0),
        в_бухгалтерии=слой(1000.0, примечание="принято 1 из 1"),
        правок=0, сумма_правок=0.0,
    )
    основа.update(поля)
    с = СверкаСмены(**основа)
    с.выводы = _выводы(с)
    return с


def вывод(с: СверкаСмены, слои: str) -> dict:
    return next(в for в in с.выводы if в["Слои"] == слои)


def test_итог_считается_по_строкам_а_не_по_шапке():
    """У части видов «СуммаДокумента» нет вовсе — итог молча выходил бы нулём."""
    n, всего, по_видам = сумма_документов([
        {"Тип": "purchase", "СуммаДокумента": 999,
         "Товары": [{"Сумма": 300.0}, {"Сумма": 200.5}]},
        {"Тип": "retail_sale_sidegoods", "Товары": [{"Сумма": 100.0}]},
    ])
    assert n == 2 and всего == 600.5
    assert по_видам["purchase"] == 500.5


def test_без_правок_суммы_обязаны_совпасть():
    с = сверка()
    assert с.сошлось
    assert "ровно то, что продали" in вывод(с, "L2 → L3")["Что"]


def test_разница_объяснённая_правками():
    """Отправили на сотню меньше, и ровно на сотню правок — это порядок."""
    с = сверка(отправлено=слой(900.0), правок=1, сумма_правок=-100.0)
    в = вывод(с, "L2 → L3")
    assert в["ok"] is True
    assert "это наши правки" in в["Что"]
    assert "сходится до копейки" in в["Почему"]


def test_разница_больше_правок_это_потеря():
    """Правок на сотню, а разница на двести — сотня потерялась молча."""
    с = сверка(отправлено=слой(800.0), правок=1, сумма_правок=-100.0)
    в = вывод(с, "L2 → L3")
    assert в["ok"] is False
    assert "правками не объясняется" in в["Что"]
    assert "потеряли молча" in в["Почему"]


def test_округление_не_считается_расхождением():
    с = сверка(отправлено=слой(1000.004))
    assert вывод(с, "L2 → L3")["ok"] is True


def test_бухгалтерия_приняла_не_всё():
    """Отправили три документа, приняли два — это поломка канала, не решение."""
    с = сверка(
        отправлено=слой(1000.0, документов=3),
        в_бухгалтерии=слой(1000.0, документов=2, примечание="принято 2 из 3"),
    )
    в = вывод(с, "L3 → L4")
    assert в["ok"] is False
    assert "не легло документов: 1" in в["Что"]
    assert "поломка канала" in в["Почему"]


def test_ещё_не_отправляли():
    с = сверка(отправлено=слой(1000.0, есть=False, примечание="пакета в очереди нет"),
               в_бухгалтерии=СостояниеСлоя())
    в = вывод(с, "L3 → L4")
    assert в["ok"] is True and "ещё не отправляли" in в["Что"]


def test_отправили_но_ответа_нет():
    с = сверка(в_бухгалтерии=СостояниеСлоя(примечание="Ответа от 1С ещё не было"))
    в = вывод(с, "L3 → L4")
    assert в["ok"] is False and "пока не приняла" in в["Что"]


def test_факт_не_собрался_дальше_не_идём():
    с = сверка(факт=СостояниеСлоя(примечание="нет точной ТТК"))
    assert len(с.выводы) == 1
    assert с.выводы[0]["ok"] is False
    assert "нет точной ТТК" in с.выводы[0]["Почему"]
