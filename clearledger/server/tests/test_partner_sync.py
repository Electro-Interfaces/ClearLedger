# -*- coding: utf-8 -*-
"""Отпечаток справочника контрагентов — от состава, а не от истории поставок."""
from app.services.partner_sync import (ПОЛЯ_ДОГОВОРА, ПОЛЯ_ПОСТАВЩИКА, _отпечаток)


def _поставщик(**правки):
    основа = {"id": "u1", "name": "СИНТЕЗ", "name_full": 'ООО "СИНТЕЗ"',
              "inn": "7801265121", "kpp": "780101001", "role": "supplier",
              "comment": "", "archived": False}
    основа.update(правки)
    return основа


def test_история_поставок_не_двигает_отпечаток():
    """Иначе справочник уезжал бы на станцию после каждой накладной."""
    было = [_поставщик()]
    стало = [_поставщик(docs_1c=17, amount_1c=254_000.0, last_1c="2026-08-30")]
    assert _отпечаток(было, ПОЛЯ_ПОСТАВЩИКА) == _отпечаток(стало, ПОЛЯ_ПОСТАВЩИКА)


def test_новый_поставщик_двигает_отпечаток():
    """Норд-Лайн заведён в центре — станция обязана получить его следующим тактом."""
    было = [_поставщик()]
    стало = было + [_поставщик(id="u2", name="НОРД-ЛАЙН ООО", inn="7804572748")]
    assert _отпечаток(было, ПОЛЯ_ПОСТАВЩИКА) != _отпечаток(стало, ПОЛЯ_ПОСТАВЩИКА)


def test_переименование_договора_двигает_отпечаток():
    договор = {"id": "d1", "partner_id": "u1", "name": "Основной договор",
               "number": "", "signed_on": "2026-01-09", "org_uuid": "o1"}
    другой = dict(договор, name="Договор поставки №346/АЛН/ЭДО/25")
    assert _отпечаток([договор], ПОЛЯ_ДОГОВОРА) != _отпечаток([другой], ПОЛЯ_ДОГОВОРА)
