"""Остаток без штрихкода не должен теряться при приёме в центр.

Строки без кода — это списание сырья общепита, они почти всегда минусовые.
Пока их отбрасывали, центр видел остаток станции 208 равным 13 883 при
реальных 8 611: витрина показывала товар, которого нет.
"""
from app.services.edge_stock import разложить_по_штрихкодам


def test_остаток_без_штрихкода_ложится_на_карточку():
    строки = [
        {"item_uuid": "u-багет", "barcode": "2200000090430",
         "name": "Багет", "place": "208", "quantity": 2460},
        # Та же карточка, но строка без кода: минус от списания по рецептуре.
        {"item_uuid": "u-багет", "barcode": "",
         "name": "Багет", "place": "208", "quantity": -480},
    ]
    карта, потери = разложить_по_штрихкодам(строки, 208)

    assert потери == []
    # Нетто карточки — 1980, а не 2460: минус обязан доехать.
    assert карта[("208", "2200000090430")] == 1980


def test_места_не_смешиваются():
    строки = [
        {"item_uuid": "u-1", "barcode": "4601", "place": "208", "quantity": 10},
        {"item_uuid": "u-1", "barcode": "4601", "place": "20800002", "quantity": 7},
        {"item_uuid": "u-1", "barcode": "", "place": "208", "quantity": -3},
    ]
    карта, потери = разложить_по_штрихкодам(строки, 208)

    assert потери == []
    # Минус зала не должен уехать на склад: товар на полке и в подсобке разный.
    assert карта[("208", "4601")] == 7
    assert карта[("20800002", "4601")] == 7


def test_карточка_без_единого_кода_попадает_в_потери():
    строки = [
        {"item_uuid": "u-сырьё", "barcode": "", "name": "Сахар",
         "place": "208", "quantity": -360},
    ]
    карта, потери = разложить_по_штрихкодам(строки, 208)

    # Пристроить некуда — но и молчать нельзя: строка обязана быть названа.
    assert карта == {}
    assert len(потери) == 1
    assert "Сахар" in потери[0]


def test_несколько_штрихкодов_одной_карточки_суммируются():
    строки = [
        {"item_uuid": "u-драже", "barcode": "460376", "place": "208", "quantity": 18},
        {"item_uuid": "u-драже", "barcode": "461027", "place": "208", "quantity": 8},
    ]
    карта, _ = разложить_по_штрихкодам(строки, 208)

    # Разрез по кодам сохраняется: у карточки восемь штрихкодов бывает.
    assert карта[("208", "460376")] == 18
    assert карта[("208", "461027")] == 8
