"""Время пространства: окна доставки, тишина и часовые пояса.

Проверяется арифметика, которая ошибается тихо. Сдвинутое на час окно не падает
и не пишет в лог — оно просто доставляет напоминание не тогда, и заметить это
можно только по жалобе «мне ночью пришло» или по молчанию, которого никто не
ждал.

Без БД: расчёты чистые, гонять ради них контейнер незачем.
"""
from datetime import date, datetime, time, timezone

import pytest

from app.services import space_time as st

MSK = "Europe/Moscow"          # UTC+3
VVO = "Asia/Vladivostok"       # UTC+10


def utc(y, m, d, h, mi=0):
    return datetime(y, m, d, h, mi, tzinfo=timezone.utc)


# ── Пояс не роняет регламент ────────────────────────────────────────────────

def test_кривой_пояс_возвращается_к_умолчанию():
    # Планировщик, падающий на опечатке в настройке одного человека, перестаёт
    # доставлять всё и всем.
    assert st.zone("Moscow").key == st.DEFAULT_TZ
    assert st.zone(None).key == st.DEFAULT_TZ
    assert st.zone("").key == st.DEFAULT_TZ


def test_местная_дата_расходится_на_сутки():
    # 28 августа 23:00 UTC: в Москве уже 29-е, во Владивостоке — тоже 29-е,
    # а сервер по UTC считал бы 28-е и не показал взятое в день.
    момент = utc(2026, 8, 28, 23)
    assert st.local_date(момент, MSK) == date(2026, 8, 29)
    assert st.local_date(момент, VVO) == date(2026, 8, 29)
    assert st.local_date(момент, "UTC") == date(2026, 8, 28)


# ── Тишина ──────────────────────────────────────────────────────────────────

def test_в_окне_и_вне_окна():
    # Пятница, 12:00 МСК — рабочее время; 3:00 — нет.
    assert st.in_window(utc(2026, 8, 28, 9), MSK) is True
    assert st.in_window(utc(2026, 8, 28, 0), MSK) is False


def test_конец_окна_не_включается():
    # 18:00 — конец рабочего дня, а не последняя его минута.
    assert st.in_window(utc(2026, 8, 28, 15), MSK) is False   # 18:00 МСК
    assert st.in_window(utc(2026, 8, 28, 14, 59), MSK) is True


def test_выходной_это_тишина():
    # Суббота, полдень по Москве.
    assert st.in_window(utc(2026, 8, 29, 9), MSK) is False


def test_владивосток_живёт_по_своему_окну():
    # 2:00 UTC — 12:00 во Владивостоке (рабочее) и 5:00 в Москве (тишина).
    момент = utc(2026, 8, 28, 2)
    assert st.in_window(момент, VVO) is True
    assert st.in_window(момент, MSK) is False


def test_окно_задом_наперёд_не_запирает_человека_навсегда():
    # Настройка «с 18:00 до 9:00» — опечатка, а не ночная смена. Молча угадывать
    # хуже, чем вернуться к умолчанию: иначе человек не получит ничего никогда.
    assert st.in_window(utc(2026, 8, 28, 9), MSK,
                        time(18, 0), time(9, 0)) is True


# ── Сдвиг, а не пропуск ─────────────────────────────────────────────────────

def test_ночное_сдвигается_на_утро():
    # 3:00 МСК пятницы → 9:00 той же пятницы. Напоминание не теряется от того,
    # что сработало ночью.
    когда = st.next_window(utc(2026, 8, 28, 0), MSK)
    assert когда == datetime(2026, 8, 28, 6, tzinfo=timezone.utc)  # 9:00 МСК


def test_вечернее_сдвигается_на_следующее_утро():
    # 20:00 пятницы → понедельник, потому что суббота и воскресенье — тишина.
    когда = st.next_window(utc(2026, 8, 28, 17), MSK)
    assert st.local_date(когда, MSK) == date(2026, 8, 31)


def test_в_окне_сдвига_нет():
    момент = utc(2026, 8, 28, 9)
    assert st.next_window(момент, MSK) == момент


# ── Окна сводки ─────────────────────────────────────────────────────────────

def test_два_окна_утро_и_середина():
    окна = st.digest_slots(date(2026, 8, 28), MSK)
    assert len(окна) == 2
    assert окна[0] == datetime(2026, 8, 28, 6, tzinfo=timezone.utc)          # 9:00
    assert окна[1] == datetime(2026, 8, 28, 10, 30, tzinfo=timezone.utc)     # 13:30


def test_окна_считаются_от_рабочего_дня_человека():
    # Кто работает с шести, у того «после обеда» наступает раньше.
    окна = st.digest_slots(date(2026, 8, 28), MSK, time(6, 0), time(15, 0))
    assert окна[0] == datetime(2026, 8, 28, 3, tzinfo=timezone.utc)          # 6:00
    assert окна[1] == datetime(2026, 8, 28, 7, 30, tzinfo=timezone.utc)      # 10:30


def test_ключ_сводки_держится_до_следующего_окна():
    # Пока окно то же — сводка та же и правится, а не пишется заново.
    первое = st.slot_for(utc(2026, 8, 28, 6, 30), MSK)     # 9:30 МСК
    ещё_первое = st.slot_for(utc(2026, 8, 28, 9), MSK)     # 12:00 МСК
    второе = st.slot_for(utc(2026, 8, 28, 11), MSK)        # 14:00 МСК
    assert первое == ещё_первое
    assert второе is not None and второе > первое


def test_в_тишине_окна_нет():
    assert st.slot_for(utc(2026, 8, 28, 0), MSK) is None     # ночь
    assert st.slot_for(utc(2026, 8, 29, 9), MSK) is None     # суббота


def test_до_первого_окна_сводки_нет():
    # Рабочее время начинается в 9:00, и «слот» до него не наступил.
    assert st.in_window(utc(2026, 8, 28, 5, 30), MSK) is False
    assert st.slot_for(utc(2026, 8, 28, 5, 30), MSK) is None


# ── Срок жизни push ─────────────────────────────────────────────────────────

def test_push_живёт_до_конца_рабочего_дня():
    # 12:00 МСК, конец в 18:00 — шесть часов.
    assert st.push_ttl(utc(2026, 8, 28, 9), MSK) == 6 * 3600


def test_push_не_бывает_нулевым():
    # После конца дня — до конца завтрашнего, но никогда не «мгновенно»:
    # доставка по дороге не должна протухать быстрее, чем идёт.
    assert st.push_ttl(utc(2026, 8, 28, 15), MSK) >= 300


@pytest.mark.parametrize("часы", list(range(0, 24)))
def test_окно_всегда_находится(часы):
    # Свойство, а не пример: у доставки обязано быть будущее время в любой час
    # суток, иначе напоминание теряется молча.
    момент = utc(2026, 8, 28, часы)
    assert st.next_window(момент, MSK) >= момент
