# -*- coding: utf-8 -*-
"""Автопризнание заявок на карточки: решение по одной заявке (04.10.2026).

Случаи взяты из 173 заявок, разобранных человеком за 40 дней до 04.10.2026:
привязка по GTIN, отделение вкуса от карточки «в ассортименте» (18 из 18 человек
делал так), новая карточка в группе станции, спорное — человеку.
"""
import inspect

from app.services import item_draft_auto as auto
from app.services.item_draft_auto import Держатель, решить

ПЕРСИК = "4600494600524"


def test_штрихкод_годен():
    assert auto.штрихкод_годен(ПЕРСИК)
    assert auto.штрихкод_годен("46227751")            # EAN-8
    assert not auto.штрихкод_годен("4600494600525")   # контрольная цифра
    assert not auto.штрихкод_годен("2000000000352")   # RCN: код магазина на «2»
    assert not auto.штрихкод_годен("8564")            # внутренний номер станции
    assert not auto.штрихкод_годен("4600494600524#")  # мусор сканера


def test_ассортимент():
    for имя in ("Чай холодный в ассорт. бут. 0,5 л.", "Мармелад Фрут-Телла в асс. 150 гр.",
                "Печенье Акульчев купелька асср.225 гр.", "Жев. конф. Фрут-Телла  Ассорти 41 гр."):
        assert auto.ассортимент(имя), имя
    assert not auto.ассортимент("Чай холодный Липтон Персик 0,5 л.")


def test_привязка_по_gtin_у_одной_карточки():
    р = решить("Cигареты LD Compact 100 S Breezy", ["46223715"],
               [Держатель(7, "Сигареты LD Autograph COMPACT 100 S BREEZY", 3)], None, None)
    assert р.действие == "link" and р.item_id == 7


def test_вкус_отделяется_от_ассортимента_без_остатка():
    р = решить("Чай холодный Липтон Персик 0,5 л.", [ПЕРСИК],
               [Держатель(5, "Чай холодный в ассорт. бут. 0,5 л.", 0)], 41, None)
    assert р.действие == "split" and р.передать_от == 5 and р.group_id == 41


def test_вкус_с_остатком_у_ассортимента_человеку():
    """Остаток не переезжает между карточками: так на 208 повис Ирис Меллер −1."""
    р = решить("Ирис Меллер с шоколадом 38 гр.", ["46040145"],
               [Держатель(9, "Жев.конф. Ирис Меллер в ассорт. 38 гр.", 1)], 41, None)
    assert р.действие == "human"


def test_новая_карточка_в_группе_станции_важнее_угадки():
    р = решить("Канистра д/ГСМ 10 л.", ["4680295011477"], [], 12, 99)
    assert р.действие == "create" and р.group_id == 12
    assert решить("Канистра д/ГСМ 10 л.", ["4680295011477"], [], None, 99).group_id == 99


def test_спорное_человеку():
    assert решить("X", [], [], 1, 1).действие == "human"                       # без штрихкода
    assert решить("X", ["2000000000352"], [], 1, 1).действие == "human"        # код на «2»
    assert решить("X", [ПЕРСИК], [Держатель(1, "A", 0), Держатель(2, "B", 0)], 1, 1).действие == "human"
    assert решить("X", [ПЕРСИК], [], None, None).действие == "human"           # нет группы


def test_признание_идёт_ручной_цепочкой():
    """Та же функция и те же задания станциям, что ручная ручка; отказа нет."""
    тело = inspect.getsource(auto.разобрать_заявку)
    assert "edge_nsi.resolve_item_draft" in тело and "_queue_nsi_delta" in тело
    assert "await db.commit()" in тело
    assert '"reject"' not in inspect.getsource(auto)


def test_похожее_название_не_держит_заявку():
    """Задержанная заявка без товароведа висит; дубль сливается потом штатно."""
    р = решить("Мин.вода Святой Источник негаз. 1,5 л.", ["4603934000793"], [], 7, None,
               ["Вода Святой Источник негазированная 1,5 л."])
    assert р.действие == "create" and "проверить, не дубль" in р.почему
    assert auto.похожи("Кофе Carte Noire 95 гр.", "Кофе Carte Noire растворимый 95 гр.")
    assert not auto.похожи("Канистра д/ГСМ 10 л.", "Канистра д/ГСМ 20 л.")
