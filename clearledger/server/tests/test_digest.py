"""Сводка окна: что говорим, чего не повторяем и что выбрасываем.

Проверяется отбор поводов — место, где ошибка не падает, а портит доверие к
напоминаниям: продублированная строка внутри одного сообщения читается как сбой,
а предупреждение «успейте до 17:00», доставленное в 17:30, прямо врёт.

Без БД: `select_new` и `compose` — чистые.
"""
from datetime import datetime, timedelta, timezone

from app.services.digest import Line, compose, select_new

СЕЙЧАС = datetime(2026, 8, 31, 9, 0, tzinfo=timezone.utc)


def строка(key: str, text: str = "повод", **kw) -> Line:
    return Line(key=key, text=text, **kw)


def test_новое_говорится():
    новые = select_new([], [строка("a"), строка("b")], СЕЙЧАС)
    assert [l.key for l in новые] == ["a", "b"]


def test_сказанное_не_повторяется():
    # Повод живёт, пока его не закрыли, и регламент приносит его каждый тик.
    # Без этого отсева сводка дублировала бы строки внутри себя.
    новые = select_new([("a", "повод")], [строка("a"), строка("b")], СЕЙЧАС)
    assert [l.key for l in новые] == ["b"]


def test_повтор_внутри_пачки_гасится():
    # Одну и ту же визу приносят два прохода: основному согласующему и ему же
    # как заместителю другого человека.
    новые = select_new([], [строка("a"), строка("a", "он же")], СЕЙЧАС)
    assert len(новые) == 1


def test_истёкшее_выбрасывается():
    # Предупреждение «успейте до 17:00» после 17:00 не просто бесполезно — оно
    # врёт: работа уже ушла наверх.
    просрочено = строка("warn", expires_at=СЕЙЧАС - timedelta(minutes=1))
    живое = строка("warn2", expires_at=СЕЙЧАС + timedelta(hours=1))
    новые = select_new([], [просрочено, живое], СЕЙЧАС)
    assert [l.key for l in новые] == ["warn2"]


def test_ровно_в_срок_уже_поздно():
    # Граница закрытая: в момент дедлайна эскалация уже случилась.
    новые = select_new([], [строка("w", expires_at=СЕЙЧАС)], СЕЙЧАС)
    assert новые == []


def test_бессрочное_живёт():
    новые = select_new([], [строка("a", expires_at=None)], СЕЙЧАС)
    assert len(новые) == 1


def test_текст_называет_окно_и_перечисляет_поводы():
    # Заголовок нужен, чтобы человек видел: это одно сообщение за утро, а не
    # первое из десяти.
    слот = datetime(2026, 8, 31, 6, 0, tzinfo=timezone.utc)  # 9:00 МСК
    текст = compose(слот, "Europe/Moscow", [("a", "Виза: «Договор»"), ("b", "Просрочено: №7")])
    assert текст.splitlines() == [
        "Сводка на 09:00",
        "• Виза: «Договор»",
        "• Просрочено: №7",
    ]


def test_окно_называется_в_поясе_человека():
    слот = datetime(2026, 8, 31, 6, 0, tzinfo=timezone.utc)
    assert compose(слот, "Asia/Vladivostok", []).startswith("Сводка на 16:00")
