"""Отбракованная источником зарядка не попадает в учёт.

Витрина АСУиМ метит часть сессий колонкой «подозрительная». Решение МАГа
27.08.2026: такие зарядки не показывать вообще, но и не терять — они идут в
журнал разбора `charge_rejected`, а не в `charge_sessions`.

Проверяется маппер: именно он решает судьбу строки, и ошибка здесь тихая —
отбракованные молча поедут в выручку.
"""
from app.services.asuim_normalize import map_payments, map_sessions
from app.services.charge_sessions_normalize import is_meter_error

ROW = {
    "id_сессии": "7739", "номер_станции": "623", "регион": "Красноярский край",
    "тип_коннектора": "GBT/AC", "дата_начала": "2025-09-01 05:57:56",
    "дата_окончания": "2025-09-01 10:28:41", "энергия_квтч": 29.86,
    "стоимость_руб": 415.05, "цена_тарифа": 13.9,
    "статус": "CompleteError", "результат": "Зарядная сессия завершена",
}


def test_suspicious_flag_survives_mapping():
    """Признак доезжает до загрузчика — иначе развилка не сработает."""
    clean = map_sessions([{**ROW, "подозрительная": 0}])[0]
    dirty = map_sessions([{**ROW, "подозрительная": 1}])[0]

    assert clean["suspicious"] is False
    assert dirty["suspicious"] is True


def test_missing_flag_means_clean():
    """Старые выгрузки колонки не несут — их строки в учёт идут как обычно."""
    row = map_sessions([ROW])[0]

    assert row["suspicious"] is False


def test_status_wins_over_result_text():
    """Исход берётся из «статуса».

    В графах «результат» и «описание_результата» у всех 153 246 строк витрины
    стоит одна и та же фраза «Зарядная сессия завершена», об исходе она не говорит
    ничего. Раньше в базу уезжала именно она — у 19 729 сессий исход неизвестен.
    """
    assert map_sessions([ROW])[0]["result"] == "CompleteError"


def test_row_is_kept_for_analysis():
    """Строка источника сохраняется целиком: разбор отбракованного — работа
    редкая, а ходить за подробностями обратно в выгрузку неоткуда."""
    row = map_sessions([{**ROW, "подозрительная": 1}])[0]

    assert row["raw"]["номер_станции"] == "623"
    assert row["raw"]["статус"] == "CompleteError"
    # Пустые графы в журнал не тащим — витрина отдаёт их десятками.
    assert "название_станции" not in row["raw"]


def test_payment_keeps_its_session_and_row():
    """У платежа связь с зарядкой — единственная: своей станции у него нет.

    По ней и решается, отбраковывать ли его вместе с сессией.
    """
    pay = map_payments([{
        "id_платежа": "157105", "id_сессии": "177562", "дата": "2026-08-22 19:03:07",
        "сумма_руб.": 94.5, "сумма_холда_руб.": 173.88, "сумма_возврата_руб": 79.38,
        "тип_операции": "Оплата картой за зарядку", "статус": 2,
    }])[0]

    assert pay["session_ext_id"] == "177562"
    assert pay["amount"] == 94.5
    assert pay["raw"]["сумма_холда_руб."] == 173.88


def test_meter_error_catches_impossible_energy():
    """Тысячи кВт·ч за секунды — брак счётчика, а не рекордная зарядка.

    Живые строки пилота: ЭЗС 584 «Овчинникова» 03.07.2026 (10 341 кВт·ч за
    11 секунд, 226 468 ₽ при платеже 1007 ₽) и ЭЗС 549 09.03.2026
    (12 788,7 кВт·ч за 0,2 мин).
    """
    assert is_meter_error(10341.0, 0.18) is True
    assert is_meter_error(12788.7, 0.2) is True
    assert is_meter_error(1805.3, 6.8) is True      # 15 900 кВт — тоже невозможно
    assert is_meter_error(150.1, 0) is True         # мгновенная: столько не отпустить


def test_real_charges_survive():
    """Границу держат две живые группы, которые терять нельзя.

    Долгие зарядки грузового транспорта (200 кВт·ч за 2,7 часа) и короткие
    сессии с завышенной мощностью — у последних врёт длительность, а энергия
    правдоподобна и платёж совпадает с суммой сессии рубль в рубль.
    """
    assert is_meter_error(200.7, 45.9) is False     # 262 кВт — в пределах 350
    assert is_meter_error(200.0, 160.3) is False
    assert is_meter_error(45.8, 2.77) is False      # 991 кВт, но энергия реальная
    assert is_meter_error(2.5, 0.15) is False       # 9 секунд, 2,5 кВт·ч
    assert is_meter_error(0, 0) is False
    assert is_meter_error(None, None) is False
