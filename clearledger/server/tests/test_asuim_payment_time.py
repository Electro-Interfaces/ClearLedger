"""Время платежа из витрины АСУиМ: UTC на входе, московское в пространстве.

Сессии витрина отдаёт парой колонок («дата_начала» по Москве и «дата_начала_utc»),
а платежи — одной графой «дата», и она в UTC. Пока это не учитывалось, платёж
выглядел прошедшим за три часа ДО своей зарядки, а ночные платежи попадали во
вчерашние сутки: выручка дня по платежам не сходилась с выручкой по сессиям
(разбор 18.09.2026 на живых данных).
"""
from datetime import datetime

from app.services.asuim_normalize import map_payments, map_sessions


def test_платёж_приводится_к_московскому_времени():
    строки = [{
        "id_платежа": "п-1",
        "id_сессии": "89292",
        "дата": datetime(2026, 5, 2, 18, 15, 38),   # UTC, как отдаёт витрина
        "сумма_руб.": 44.70,
    }]
    [платёж] = map_payments(строки)
    assert платёж["paid_at"] == datetime(2026, 5, 2, 21, 15, 38)


def test_платёж_совпадает_с_окончанием_своей_сессии():
    # Та самая пара из живой выгрузки: зарядка кончилась в 21:15:37 по Москве,
    # платёж витрина записала как 18:15:38 по UTC. После приведения это одна и та
    # же минута, а не разрыв в три часа.
    [сессия] = map_sessions([{
        "id_сессии": "89292",
        "номер_станции": "365",
        "дата_начала": datetime(2026, 5, 2, 21, 4, 50),
        "дата_окончания": datetime(2026, 5, 2, 21, 15, 37),
        "энергия_квтч": 3.0,
    }])
    [платёж] = map_payments([{
        "id_платежа": "п-1", "id_сессии": "89292",
        "дата": datetime(2026, 5, 2, 18, 15, 38), "сумма_руб.": 44.70,
    }])
    разрыв = (платёж["paid_at"] - сессия["finished_at"]).total_seconds()
    assert 0 <= разрыв < 120, f"платёж разъехался с сессией на {разрыв} с"


def test_пустая_дата_остаётся_пустой():
    # Платёж без даты бывает у возвратов: подставлять ему «сейчас плюс три часа»
    # нельзя — пустота честнее выдуманного момента.
    [платёж] = map_payments([{"id_платежа": "п-2", "дата": None}])
    assert платёж["paid_at"] is None
