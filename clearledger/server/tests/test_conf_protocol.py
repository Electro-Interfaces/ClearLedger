"""Черновик протокола конференции: решения, поручения, исполнитель и срок."""
from datetime import date

from app.services.conf_protocol import черновик, текстом

СРЕДА = date(2026, 10, 14)
ЛЮДИ = [("u1", "Марков Антон Александрович"), ("u2", "Никанорова Нонна Александровна")]


def test_решение_и_поручение_с_исполнителем_и_сроком():
    отрезки = [
        {"start": 10, "text": "Решили перенести монтаж на ноябрь."},
        {"start": 42, "text": "Антону подготовить смету до пятницы. Погода хорошая сегодня."},
        {"start": 90, "text": "Нонна Александровна, отправьте договор к 20.10."},
    ]
    п = черновик(отрезки, ЛЮДИ, СРЕДА)
    assert [x["kind"] for x in п] == ["decision", "task", "task"]
    assert п[1]["assignee_id"] == "u1" and п[1]["due"] == "2026-10-16" and п[1]["at"] == 42
    assert п[2]["assignee_id"] == "u2" and п[2]["due"] == "2026-10-20"


def test_двое_названы_исполнитель_пуст():
    п = черновик([{"start": 0, "text": "Маркову и Никаноровой нужно созвониться завтра."}],
                 ЛЮДИ, СРЕДА)
    assert п[0]["assignee_id"] is None and п[0]["due"] == "2026-10-15"


def test_болтовня_не_попадает_и_повтор_один_раз():
    п = черновик([{"start": 0, "text": "Всем добрый день, слышно хорошо?"},
                  {"start": 5, "text": "Надо проверить зарядку на Русском."},
                  {"start": 9, "text": "Надо проверить зарядку на Русском."}], ЛЮДИ, СРЕДА)
    assert len(п) == 1


def test_текстом():
    п = черновик([{"start": 0, "text": "Антону подготовить смету до пятницы."}], ЛЮДИ, СРЕДА)
    assert текстом(п, {"u1": "Марков А."}) == (
        "Поручения:\n1. Антону подготовить смету до пятницы. — Марков А., срок 16.10.2026")
