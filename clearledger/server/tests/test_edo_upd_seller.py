"""Продавец в УПД: у юрлица он в `НаимОрг`, у ИП — в `СвИП` → `ФИО`.

Накладные от ИП разбирались без продавца и оседали нераспознанными; после
того как приёмку закрыли обязательной проверкой основания, они перестали
загружаться вовсе.
"""
from app.services.edo_upd import parse_upd

ЮРЛИЦО = """<?xml version="1.0" encoding="windows-1251"?>
<Файл><Документ><СвСчФакт НомерСчФ="А-17" ДатаСчФ="01.08.2026">
  <СвПрод><ИдСв><СвЮЛУч НаимОрг="ООО Ромашка" ИННЮЛ="7801234567"/></ИдСв></СвПрод>
</СвСчФакт><ТаблСчФакт>
  <СведТов НаимТов="Кофе" КолТов="2" ЦенаТов="100" СтТовБезНДС="200"/>
</ТаблСчФакт></Документ></Файл>"""

ПРЕДПРИНИМАТЕЛЬ = """<?xml version="1.0" encoding="windows-1251"?>
<Файл><Документ><СвСчФакт НомерСчФ="7" ДатаСчФ="01.08.2026">
  <СвПрод><ИдСв><СвИП ИННФЛ="781234567890">
    <ФИО Фамилия="Морозов" Имя="Иван" Отчество="Петрович"/>
  </СвИП></ИдСв></СвПрод>
</СвСчФакт><ТаблСчФакт>
  <СведТов НаимТов="Булочка" КолТов="10" ЦенаТов="30" СтТовБезНДС="300"/>
</ТаблСчФакт></Документ></Файл>"""


def test_yurlico_chitaetsya_kak_i_ranshe():
    док = parse_upd(ЮРЛИЦО.encode("cp1251"))
    assert док["supplier"] == "ООО Ромашка"
    assert док["incoming_number"] == "А-17"


def test_ip_poluchaet_imya_iz_fio():
    док = parse_upd(ПРЕДПРИНИМАТЕЛЬ.encode("cp1251"))
    assert док["supplier"] == "ИП Морозов Иван Петрович"
    assert док["incoming_number"] == "7"
    assert len(док["lines"]) == 1
