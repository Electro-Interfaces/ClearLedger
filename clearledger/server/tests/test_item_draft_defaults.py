# -*- coding: utf-8 -*-
"""Признание черновика переносит умолчания группы в карточку.

15.09.2026 на 208 три пачки сигарет приехали в сеть без маркировки и без 18+:
товаровед выбрал группу «Табак / Сигареты», где всё нужное проставлено, а
признание её умолчаний не читало. Вниз дельта везёт эти поля ИЗ КАРТОЧКИ —
станция получила карточку такой же неполной, какой та была черновиком, и канал
в кассу выпускал по ней файл каждые десять минут.

Проверка по исходнику: таблицы `edge.item` и `edge.item_group` заводит
инициализатор базы пространства, а не `create_all`, — см. пояснение в
`test_item_draft_atomic.py`.
"""
import inspect

from app.services import edge_nsi


def _тело():
    исходник = inspect.getsource(edge_nsi.resolve_item_draft)
    return исходник[исходник.index('if action == "create":'):]


def test_умолчания_группы_читаются():
    тело = _тело()
    for поле in ("marked_default", "adult_default", "mark_group_default"):
        assert поле in тело, f"умолчание {поле} у группы не читается"
    assert "FROM edge.item_group" in тело


def test_умолчания_доезжают_до_карточки():
    """Читать мало — они обязаны попасть в INSERT, иначе карточка снова неполна."""
    тело = _тело()
    вставка = тело[тело.index("INSERT INTO edge.item"):]
    for колонка in ("marked", "adult_only", "mark_group", "sku_class"):
        assert колонка in вставка, f"колонка {колонка} не заполняется при признании"


def test_группа_чз_не_стирается_вместе_с_признаком():
    """У пяти групп сети группа ЧЗ заполнена, а `marked_default` — нет.

    Это осознанно: маркируется там не всё подряд. Выдумывать номер группы кассе
    нельзя (канон, п. 12), поэтому знание, однажды заведённое, стирать нельзя.
    """
    тело = _тело()
    assert '"mark_group": умолчания["чз"]' in тело, (
        "группа ЧЗ переносится не независимо от признака маркировки"
    )


def test_класс_выводится_из_пути_группы():
    """Пустой класс — невидимка: код кассы такой карточке не достанется никогда."""
    тело = _тело()
    хвост = тело[тело.index("путь ="):]
    assert "Блюдо" in хвост and "Сырьё" in хвост and "Сопутка" in хвост, (
        "класс не выводится из пути группы"
    )
