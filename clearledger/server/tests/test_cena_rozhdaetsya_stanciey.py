"""Цену задаём мы и грузим в кассу — обратно из кассы не читаем.

Направление одностороннее: цену назначает станция (или центр, если политика это
разрешает), файл тарифов везёт её В кассу. Механизма смены цены на самой кассе
нет, поэтому цифра оттуда — не факт о цене, а эхо нашей прошлой выгрузки либо
наследие прежнего владельца оборудования.

Пока снимок кассы переписывал цену, на только что подключённой станции мы
затягивали к себе чужой прайс: касса АЗС 8 в сентябре 2026 держала цены
Норд-Лайна, и 225 таких приехали «снимком станции» — при том, что администратор
ГИГ не назначил ни одной. В первой же накладной они подставились в «Продажу».
"""


def снимок(наша_цена: float | None, цена_в_кассе: float) -> dict:
    """Повторяет ветвление из edge_nsi: что снимок кассы делает с ценой."""
    итог = {"записей": 0, "нет_цены": 0, "расходится": 0}
    if наша_цена is None:
        итог["нет_цены"] = 1
    elif abs(наша_цена - цена_в_кассе) >= 0.005:
        итог["расходится"] = 1
    return итог


def test_цена_из_кассы_не_записывается_никогда():
    # Ни когда своей цены нет…
    assert снимок(None, 285.0)["записей"] == 0
    # …ни когда она есть и расходится.
    assert снимок(300.0, 285.0)["записей"] == 0


def test_отсутствие_цены_считается_и_видно():
    # Станция ещё не назначила цену — это факт для человека, а не повод писать.
    assert снимок(None, 285.0)["нет_цены"] == 1


def test_расхождение_считается_а_не_переписывает():
    # Касса говорит 285, у нас 300 — показываем расхождение, своё не трогаем.
    итог = снимок(300.0, 285.0)
    assert итог["расходится"] == 1 and итог["записей"] == 0


def test_совпадение_молчит():
    итог = снимок(285.0, 285.0)
    assert итог == {"записей": 0, "нет_цены": 0, "расходится": 0}
    # Копеечная разница расхождением не считается — иначе шум на каждом снимке.
    assert снимок(285.004, 285.0)["расходится"] == 0
