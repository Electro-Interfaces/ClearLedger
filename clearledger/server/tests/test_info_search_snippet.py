"""Выдача поиска по знанию показывает текст, а не разметку.

В сниппет попадает кусок статьи как есть, и человек видел «## Как войти» и
«**Профиль**» вместо фразы. Подсветка совпадения приходит отдельными метками
`<<…>>` из `ts_headline`, её трогать нельзя.
"""
from app.services.info_center import _чистый_сниппет


def test_заголовки_и_жирный_убираются():
    сырой = ("<<Профиль>> и PIN, сессия на 12 часов. ## Как войти "
             "На экране выберите себя в списке **профилей**")
    чистый = _чистый_сниппет(сырой)
    assert "##" not in чистый
    assert "**" not in чистый
    assert "Как войти На экране" in чистый


def test_подсветка_совпадения_остаётся():
    assert "<<Профиль>>" in _чистый_сниппет("слово <<Профиль>> в тексте")


def test_дефис_в_роли_тире_не_трогаем():
    # «Левая рельса - разделы» это тире, а не маркер списка: вычистив его,
    # мы превращали фразу в кашу.
    сырой = "Левая рельса - разделы, вторая полоса - пункты раздела"
    assert _чистый_сниппет(сырой) == сырой


def test_пустой_сниппет_не_ломает():
    assert _чистый_сниппет(None) == ""
    assert _чистый_сниппет("") == ""


def test_код_в_обратных_кавычках_читается_словом():
    assert _чистый_сниппет("ключ `company_id` в запросе") == "ключ company_id в запросе"
