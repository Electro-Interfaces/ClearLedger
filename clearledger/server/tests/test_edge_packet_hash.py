"""Хеш содержимого пакета: что считается «тем же пакетом», а что перевыгрузкой.

Центр различает два повтора по хешу: тот же UUID с тем же хешем — дубль
доставки (409 и всё), с другим — агент пересобрал данные, и такой пакет
откладывается в needs_review для разбора человеком.

Отличать их надо по содержимому. Время выгрузки и производный хеш конверта
меняются при каждой пересборке, и пока они входили в хеш, обычный повтор
объявлялся изменением: у чеков UUID считается от состава документов, поэтому
повторная отправка тех же чеков приходила с тем же UUID и «другим» хешем.
"""
from app.routers.edge_router import _raw_payload_hash


def _пакет(время: str, хеш: str, чеков: int = 1) -> dict:
    return {
        "ВерсияФормата": "2",
        "ВремяВыгрузки": время,
        "ХешПакета": хеш,
        "ИдентификаторПакета": "3f2a-один-и-тот-же",
        "Смена": {"КодАЗС": 208, "НомерСменыВнутр": 7071},
        "Документы": [{
            "Тип": "fiscal_receipts",
            "Чеки": [{"Номер": n, "Сумма": 100.0} for n in range(чеков)],
        }],
    }


def test_перевыгрузка_того_же_набора_не_считается_изменением():
    первый = _пакет("2026-08-09T15:30:00+03:00", "aaa111")
    повтор = _пакет("2026-08-09T15:35:48+03:00", "bbb222")

    assert _raw_payload_hash(первый) == _raw_payload_hash(повтор)


def test_изменённый_состав_остаётся_изменением():
    первый = _пакет("2026-08-09T15:30:00+03:00", "aaa111", чеков=1)
    исправленный = _пакет("2026-08-09T15:30:00+03:00", "aaa111", чеков=2)

    assert _raw_payload_hash(первый) != _raw_payload_hash(исправленный)


def _рецептуры(время: str, порядок: list[int]) -> dict:
    """Конверт формата 3: своё имя времени выгрузки и набор рецептур."""
    блюда = {1: {"dish": "Латте", "qty": 1}, 2: {"dish": "Американо", "qty": 2}}
    return {
        "ФорматПакета": 3,
        "ИдентификаторПакета": "24218d15-один-и-тот-же",
        "Выгружен": время,
        "ХешПакета": "bbb9d88b",
        "Документы": [], "НСИ": [],
        "recipe_bundle": {"bundle_id": "station-208",
                          "recipes": [блюда[n] for n in порядок]},
    }


def test_время_выгрузки_формата_3_не_считается_изменением():
    первый = _рецептуры("2026-08-04T13:14:46+03:00", [1, 2])
    повтор = _рецептуры("2026-08-10T15:32:35+03:00", [1, 2])

    assert _raw_payload_hash(первый) == _raw_payload_hash(повтор)


def test_перестановка_того_же_набора_не_считается_изменением():
    первый = _рецептуры("2026-08-04T13:14:46+03:00", [1, 2])
    переставленный = _рецептуры("2026-08-04T13:14:46+03:00", [2, 1])

    assert _raw_payload_hash(первый) == _raw_payload_hash(переставленный)


def test_другая_рецептура_остаётся_изменением():
    первый = _рецептуры("2026-08-04T13:14:46+03:00", [1, 2])
    другой = _рецептуры("2026-08-04T13:14:46+03:00", [1, 2])
    другой["recipe_bundle"]["recipes"][0]["qty"] = 3

    assert _raw_payload_hash(первый) != _raw_payload_hash(другой)


def test_правка_шапки_смены_остаётся_изменением():
    первый = _пакет("2026-08-09T15:30:00+03:00", "aaa111")
    другая_смена = _пакет("2026-08-09T15:30:00+03:00", "aaa111")
    другая_смена["Смена"]["НомерСменыВнутр"] = 7072

    assert _raw_payload_hash(первый) != _raw_payload_hash(другая_смена)
