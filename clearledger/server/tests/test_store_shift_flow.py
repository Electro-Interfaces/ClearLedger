"""Поток людей за смену: конверсия магазина считается честно или не считается."""
from app.services.goods_dashboard import _поток_смены

ЧЕКИ = {(208, 7100): 42, (208, 7101): 50}
ЗАПРАВКИ = {(208, 7100): 120, (208, 7101): 10}


def test_конверсия_смены_это_доля_заправок_с_покупкой():
    итог = _поток_смены("208", 7100, ЧЕКИ, ЗАПРАВКИ)
    assert итог == {"cheques": 42, "fuel_ops": 120, "conversion": 35.0}


def test_отставший_топливный_контур_не_даёт_конверсии_больше_ста():
    # Чеков больше, чем заправок: реализации ещё не приехали. Показать 500 %
    # хуже, чем не показать ничего.
    итог = _поток_смены("208", 7101, ЧЕКИ, ЗАПРАВКИ)
    assert итог["cheques"] == 50 and итог["conversion"] is None


def test_смена_без_внутреннего_номера_остаётся_прочерком():
    # Печатный номер строится из даты открытия и на смене через полночь
    # указывает на вчера — по нему поток считать нельзя. Ноль здесь читался бы
    # как «никто не купил».
    for номер in (None, 0, "В-7070"):
        итог = _поток_смены("208", номер, ЧЕКИ, ЗАПРАВКИ)
        assert итог == {"cheques": None, "fuel_ops": None, "conversion": None}


def test_смены_без_данных_потока_не_придумывают_нули():
    итог = _поток_смены("209", 5000, ЧЕКИ, ЗАПРАВКИ)
    assert итог == {"cheques": None, "fuel_ops": None, "conversion": None}
