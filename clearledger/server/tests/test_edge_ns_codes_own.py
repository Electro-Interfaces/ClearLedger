"""Наши закрепления кодов не должны гаснуть от снимка кассы.

Реестр кодов ведёт станция: до Дня X часть номеров закреплена нами и в
dba.Tariffs не попадает. Центр гасил всё, чего нет в разделе «Касса», и
11.08.2026 одним снимком снял 43 закрепления — ровно те, ради которых
реестр и заводился.
"""
from app.services.edge_nsi import коды_в_обороте


def test_наши_коды_считаются_занятыми():
    касса = [{"КодНС": 100, "ШтрихКод": "4601"}, {"КодНС": 101, "ШтрихКод": "4602"}]
    наши = [{"КодНС": 589, "ШтрихКод": "208001"}]

    assert коды_в_обороте(касса, наши) == [100, 101, 589]


def test_снимок_без_наших_кодов_не_ломается():
    касса = [{"КодНС": 100, "ШтрихКод": "4601"}]

    assert коды_в_обороте(касса, []) == [100]
    assert коды_в_обороте(касса, None) == [100]


def test_пустой_и_нечисловой_код_отбрасываются():
    строки = [{"КодНС": 0}, {"КодНС": None}, {"КодНС": "302"}, {"КодНС": 302}]

    assert коды_в_обороте(строки, []) == [302]
