"""Снимок цепочки со станции должен доехать до экрана центра.

Формат пакета — единственное, что здесь ломается молча: агент обновится, ключ
переименуется, и раздел «1С до перехода» будет показывать «снимка нет» вместо
ошибки. Поэтому разбор проверяется отдельно от базы.
"""
from app.services.edge_service import разобрать_снимок_цепочки


ПАКЕТ = {
    "Документы": [
        {"Вид": "chain_snapshot", "Снимок": {
            "снято": "2026-08-09T15:33:00+03:00",
            "касса_доступна": True, "касса_позиций": 816,
            "наш_позиций": 695, "наш_минусов": 43,
            "наши_минусы": [{"uuid": "u-1", "товар": "Багет", "деталь": "Торговый зал",
                             "наш": -12, "касса": 3}],
            "разошлись": [{"uuid": "u-1", "товар": "Багет", "наш": -12, "касса": 3}],
        }},
    ],
}


def test_снимок_и_детализация_доезжают():
    отчёт = разобрать_снимок_цепочки(ПАКЕТ)
    assert отчёт["available"]
    assert отчёт["snapshot"]["касса_позиций"] == 816
    assert отчёт["минусы"][0]["товар"] == "Багет"
    assert отчёт["разошлись"][0]["наш"] == -12


def test_пакет_другого_вида_не_считается_снимком():
    отчёт = разобрать_снимок_цепочки({"Документы": [{"Вид": "mrc_fact"}]})
    assert not отчёт["available"]
    assert отчёт["detail"]


def test_пустой_пакет_не_роняет_разбор():
    for пусто in (None, {}, {"Документы": None}, {"Документы": [{"Вид": "chain_snapshot"}]}):
        assert not разобрать_снимок_цепочки(пусто)["available"]
