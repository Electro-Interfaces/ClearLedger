"""Слияние карточек-тёзок не должно терять техкарту станции.

Техкарты разложены по станциям: у одного блюда своя карта на каждой АЗС, и
номер версии у них СОВПАДАЕТ (обе v1). Пока занятость версии проверялась по
паре «блюдо + версия», карта дубля не переезжала на канон и оставалась висеть
на удалённой карточке — станция теряла техкарту молча.
"""


def занято(recipes, dish_uuid, station_id, version, *, со_станцией: bool):
    """Повторяет проверку из ручки слияния — с ключом и без станции."""
    if со_станцией:
        ключи = {(r["dish"], r["station"], r["version"]) for r in recipes}
        return (dish_uuid, station_id, version) in ключи
    ключи = {(r["dish"], r["version"]) for r in recipes}
    return (dish_uuid, version) in ключи


КАНОН, ДУБЛЬ = "uuid-208", "uuid-8"
КАРТЫ = [
    {"dish": КАНОН, "station": 208, "version": 1, "lines": 5},
    {"dish": ДУБЛЬ, "station": 8, "version": 1, "lines": 3},
]


def test_без_станции_карта_дубля_не_переезжает():
    # Так было до починки: у канона «версия 1 занята», и карта станции 8
    # оставалась на удалённой карточке.
    assert занято(КАРТЫ, КАНОН, 8, 1, со_станцией=False) is True


def test_со_станцией_карта_дубля_переезжает():
    # У канона нет карты для станции 8 — значит перенос обязан состояться.
    assert занято(КАРТЫ, КАНОН, 8, 1, со_станцией=True) is False


def test_своя_станция_канона_остаётся_занятой():
    # Карту 208 подменять нельзя: она у канона своя и уже есть.
    assert занято(КАРТЫ, КАНОН, 208, 1, со_станцией=True) is True


def test_ключ_учитывает_версию_а_не_только_станцию():
    карты = КАРТЫ + [{"dish": КАНОН, "station": 8, "version": 2, "lines": 4}]
    # Вторая версия для той же станции занята, первая — нет.
    assert занято(карты, КАНОН, 8, 2, со_станцией=True) is True
    assert занято(карты, КАНОН, 8, 1, со_станцией=True) is False
