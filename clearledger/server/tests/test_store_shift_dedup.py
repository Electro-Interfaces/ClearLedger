"""Одна смена — одна выручка, сколько бы раз станция её ни присылала.

Агент пересобирает смену и шлёт заново. Приёмник помечает прежнюю запись
`superseded`, только если узнал её — а узнаёт по времени закрытия, которое
пересборка двигает на секунду (23:52:31 → 23:52:30). Обе записи остаются
`verified`, и выручка смены попадает в витрину дважды.

Обратная ошибка дороже: печатный номер смены строится из даты ОТКРЫТИЯ, и
смена 208, открытая 30.07 в 23:59 и закрытая 31.07, носит тот же номер
2082083007202601, что и смена за 30 июля. Ключ по печатному номеру склеил бы
две разные смены и стёр из отчёта выручку целого дня — 57 234 ₽.
"""
from datetime import datetime

from app.services.goods_dashboard import _prefer_edge_sales


class _Entry:
    """Минимальный двойник DataEntry: витрине нужны только эти поля."""

    def __init__(self, source, station, number, closed, revenue, *,
                 inner=None, revision=1, updated=datetime(2026, 8, 1)):
        self.source = source
        self.revision = revision
        self.updated_at = updated
        self.created_at = updated
        смена = {"КодАЗС": station, "ОСЭНомер": number, "Закрытие": closed}
        if inner is not None:
            смена["НомерСменыВнутр"] = inner
        self.meta = {"Смена": смена, "Итоги": {"СуммаПродаж": revenue}}


def _выручка(rows):
    return sum(r.meta["Итоги"]["СуммаПродаж"] for r in rows)


def test_копия_смены_со_сдвинутым_закрытием_не_удваивает_выручку():
    итог = _prefer_edge_sales([
        _Entry("edge", "208", "2082081507202601", "2026-07-15T23:52:31", 45621,
               inner="7046", revision=1, updated=datetime(2026, 8, 1)),
        _Entry("edge", "208", "2082081507202601", "2026-07-15T23:52:30", 45621,
               inner="7046", revision=2, updated=datetime(2026, 8, 2)),
    ])
    assert len(итог) == 1
    assert _выручка(итог) == 45621
    # Осталась последняя присланная: пересборка исправляет, а не портит.
    assert итог[0].revision == 2


def test_две_смены_с_одним_печатным_номером_остаются_обе():
    итог = _prefer_edge_sales([
        _Entry("edge", "208", "2082083007202601", "2026-07-30T23:43:47", 45534, inner="7061"),
        _Entry("edge", "208", "2082083007202601", "2026-07-31T23:47:25", 57234, inner="7062"),
    ])
    assert len(итог) == 2
    assert _выручка(итог) == 102768


def test_проекция_1с_без_внутреннего_номера_различается_днём():
    итог = _prefer_edge_sales([
        _Entry("oneC", "208", "2082082606202601", "2026-06-26T23:56:10", 40000),
        _Entry("oneC", "208", "2082082606202601", "2026-06-27T23:44:44", 38000),
    ])
    assert len(итог) == 2


def test_проекция_1с_той_же_смены_не_считается_второй_раз():
    итог = _prefer_edge_sales([
        _Entry("edge", "208", "2082083007202601", "2026-07-30T23:43:47", 45534, inner="7061"),
        _Entry("oneC", "208", "2082083007202601", "2026-07-30T23:43:47", 45534),
    ])
    assert [r.source for r in итог] == ["edge"]
