"""Станция документа ЦБ по складу: код или, если он не разобрался, имя.

Складское место кодируется «20800002» — восемь цифр подряд. Шаблон `_station`
берёт группы 1–6 цифр, не окружённые цифрами, и по такому коду не находит
НИЧЕГО: документ оставался без станции и отсеивался областью видимости.
За всю историю так терялось 960 движений и 288 пересчётов складского места 208.
"""
from types import SimpleNamespace

from app.services.store_documents import _station, _станция_склада


def test_код_складского_места_сам_по_себе_станцию_не_даёт():
    # Это и есть корень дефекта — фиксируем, чтобы правка не «улучшила» _station
    # молча и не сдвинула разбор всего остального.
    assert _station("20800002") is None
    assert _station("208") == 208


def test_станция_берётся_из_имени_когда_код_не_разобрался():
    склад = SimpleNamespace(warehouse_code="20800002", warehouse_name="АЗС №208, Склад")
    assert _станция_склада(склад) == 208


def test_код_имеет_приоритет_над_именем():
    зал = SimpleNamespace(warehouse_code="208", warehouse_name="АЗС №208, Торговый зал")
    assert _станция_склада(зал) == 208
    # Имя не должно перебивать разобранный код.
    странный = SimpleNamespace(warehouse_code="5", warehouse_name="АЗС №208, Склад")
    assert _станция_склада(странный) == 5


def test_без_кода_и_имени_станции_нет():
    пусто = SimpleNamespace(warehouse_code=None, warehouse_name=None)
    assert _станция_склада(пусто) is None
    буквы = SimpleNamespace(warehouse_code="", warehouse_name="Основной склад")
    assert _станция_склада(буквы) is None
