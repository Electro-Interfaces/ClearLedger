"""Граница между Ядром и службой процессов: она узкая, и такой должна остаться.

Ход работы по проекту ведёт не Ядро, а приложение «Поддержка»: там движок
маршрутов, редактор, эскалации и таймеры. Решение осознанное — второй движок
внутри Ядра писать незачем.

Цена такого решения зависит не от него самого, а от ШИРИНЫ ГРАНИЦЫ. Пока Ядро
видит службу процессов через несколько ручек одного фасада и общается глаголами,
заменить того, кто отвечает по ту сторону, — работа за фасадом: приложения не
меняются вовсе. Стоит адресу фасада разойтись по файлам, а прикладному коду
узнать про стадии и рёбра — и та же замена превращается в переписывание.

Этот тест сторожит именно ширину. Он не запрещает ходить к службе процессов — он
требует, чтобы ходили через одну дверь.
"""
from pathlib import Path

APP = Path(__file__).resolve().parents[1] / "app"

# Единственный файл, которому положено знать адрес фасада процессов. Здесь же
# живёт транспорт и здесь же собираются пути ручек.
FACADE_OWNER = "projects_process.py"

# Признак обращения к фасаду: путь его ручек. Ищем по строке, а не по импорту —
# обойти импорт легко, набрать адрес строкой ещё легче, и ловить надо второе.
FACADE_PATH = "api/v1/process"


def _sources():
    for path in APP.rglob("*.py"):
        if "__pycache__" in path.parts:
            continue
        yield path


def test_адрес_фасада_процессов_знает_один_файл():
    """Иначе замена службы процессов станет поиском строк по всему Ядру."""
    offenders = []
    for path in _sources():
        if path.name == FACADE_OWNER:
            continue
        text = path.read_text(encoding="utf-8")
        if FACADE_PATH in text:
            offenders.append(str(path.relative_to(APP)))
    assert not offenders, (
        "Адрес фасада процессов набран вне " + FACADE_OWNER + ": "
        + ", ".join(offenders)
        + ". Ходите через projects_process — иначе граница расширяется, и цена "
          "переноса движка растёт вместе с ней.")


def test_фасад_отдаёт_действия_глаголом():
    """Глагол устойчив, идентификатор ребра — нет.

    Графы маршрутов пересобирают: идентификаторы меняются, «Согласовано»
    остаётся. Проверяем, что дверь к действиям принимает именно глагол.
    """
    owner = (APP / "services" / FACADE_OWNER).read_text(encoding="utf-8")
    assert "async def send_verb(" in owner, (
        "Пропала единственная дверь к действиям фасада")
    assert '"verb"' in owner, (
        "Действие ушло без глагола — значит по идентификатору ребра")


def test_снимок_хода_не_становится_источником_отчётности():
    """Снимок отстаёт по устройству и годится только для показа.

    Он пишется при действиях и на сверке, но не при чтении, поэтому может
    отставать — и отдаётся честно помеченным. Если по нему начнут считать
    отчёты, отставание станет расхождением, которое придётся мирить.
    """
    from app.models import ProcessSnapshot

    doc = (ProcessSnapshot.__doc__ or "")
    assert "отстава" in doc or "отстаёт" in doc, (
        "Из докстринга снимка пропало предупреждение, что он может отставать")
