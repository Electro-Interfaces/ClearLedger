"""Фискальные итоги смены должны доехать до раздела «Касса».

Итог пишет сам кассовый аппарат при закрытии смены — это единственная выручка
станции, посчитанная не нами. Едет он вместе с чеками, поэтому разбор обязан
пережить и пакет старого агента, где итогов нет вовсе.
"""
from app.services.edge_service import разобрать_итоги_ккт


ПАКЕТ = {
    "Смена": {"НомерСменыВнутр": 7070, "Закрытие": "2026-08-08T23:49:22+03:00"},
    "Документы": [
        {"Тип": "fiscal_receipts", "Чеки": [{"Номер": 10}]},
        {"Тип": "kkt_shift", "НомерСменыВнутр": 7070, "Посты": [
            {"Пост": 1, "Оператор": "Куприянов А.А.", "МодельККТ": "АТОЛ 77Ф",
             "РНМ": "0010296026045975", "НомерСменыККТ": 66,
             "Наличными": 53562.53, "Картой": 193809.41,
             "ВозвратНаличными": 0, "ВозвратКартой": 1758.00,
             "ФискальныйИтог": 245613.94, "ПробитоПоСчётчику": 247371.94},
        ]},
    ],
}


def test_итог_поста_разбирается():
    посты = разобрать_итоги_ккт(ПАКЕТ)
    assert len(посты) == 1
    п = посты[0]
    assert п["Смена"] == 7070
    assert п["РНМ"] == "0010296026045975"
    # Номер смены аппарата идёт своим счётом и с номером смены станции не совпадает.
    assert п["НомерСменыККТ"] == 66
    assert п["Возвращено"] == 1758.00


def test_разница_счётчика_и_фиска_это_возврат():
    п = разобрать_итоги_ккт(ПАКЕТ)[0]
    assert round(п["ПробитоПоСчётчику"] - п["ФискальныйИтог"], 2) == п["Возвращено"]


def test_пакет_старого_агента_без_итогов():
    старый = {"Смена": {"НомерСменыВнутр": 7000},
              "Документы": [{"Тип": "fiscal_receipts", "Чеки": []}]}
    assert разобрать_итоги_ккт(старый) == []
    assert разобрать_итоги_ккт(None) == []
    assert разобрать_итоги_ккт({"Документы": [{"Тип": "kkt_shift"}]}) == []
