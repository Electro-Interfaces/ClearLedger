"""Артикул продавца — не штрихкод.

Пока артикул подставлялся вместо отсутствующего штрихкода, он шёл дальше на
сопоставление против `edge.barcode` и оседал в нашем реестре кодов: внутренние
номера чужой учётной системы становились «штрихкодами» товара.
"""
from app.services.edo_upd import parse_upd

ДОКУМЕНТ = """<?xml version="1.0" encoding="windows-1251"?>
<Файл><Документ><СвСчФакт НомерСчФ="А-42" ДатаСчФ="30.08.2026">
  <СвПрод><ИдСв><СвЮЛУч НаимОрг="ООО Поставщик" ИННЮЛ="7801234567"/></ИдСв></СвПрод>
</СвСчФакт><ТаблСчФакт>
  <СведТов НаимТов="Вода 0,5" КолТов="12" ЦенаТов="40" СтТовБезНДС="480"
           ШтрихКод="4607091380014" Артикул="ВД-500"/>
  <СведТов НаимТов="Салфетки" КолТов="3" ЦенаТов="70" СтТовБезНДС="210"
           Артикул="SLF-100"/>
  <СведТов НаимТов="Пакет" КолТов="50" ЦенаТов="2" СтТовБезНДС="100"/>
</ТаблСчФакт></Документ></Файл>"""


def test_artikul_prodavca_ne_popadaet_v_shtrihkod():
    строки = parse_upd(ДОКУМЕНТ.encode("cp1251"))["lines"]
    assert len(строки) == 3

    # Есть и штрихкод, и артикул — каждый в своём поле.
    assert строки[0]["barcode"] == "4607091380014"
    assert строки[0]["supplier_article"] == "ВД-500"

    # Штрихкода нет: поле остаётся пустым, артикул в него НЕ подставляется.
    assert строки[1]["barcode"] == ""
    assert строки[1]["supplier_article"] == "SLF-100"

    # Нет ни того ни другого — обе строки пусты, разбор не падает.
    assert строки[2]["barcode"] == ""
    assert строки[2]["supplier_article"] == ""
