"""Разбор условий ответственности из текста договора.

Текст выдуман, но собран из формулировок реальных договоров поставки ЭЗС.
Проверяется главное: не только найденные числа, но и НОМЕРА ПУНКТОВ — претензия
ссылается на пункт, и «30 дней» без «п. 7.3» в споре не стоит ничего.
"""
from datetime import date

from app.services.contract_liability import разобрать, санкция, следующий_шаг


def test_разбор_условий_и_санкции() -> None:
    ТЕКСТ = """
    7. ОТВЕТСТВЕННОСТЬ СТОРОН
    7.1. За неисполнение или ненадлежащее исполнение обязательств стороны несут
    ответственность в соответствии с законодательством РФ.
    7.2. Поставщик обязан приступить к реагированию на обращение Покупателя в течение
    24 часов с момента получения уведомления.
    7.3. Поставщик обязан устранить выявленные неисправности оборудования в течение
    30 календарных дней с даты получения уведомления Покупателя.
    7.4. В случае нарушения срока, указанного в п. 7.3, Поставщик уплачивает Покупателю
    пеню в размере 0,1 % от стоимости неисправного оборудования за каждый день просрочки.
    Общая сумма неустойки не может превышать 10 % от стоимости оборудования.
    8. ГАРАНТИЯ
    8.1. Гарантийный срок на оборудование составляет 36 месяцев с даты подписания акта.
    """

    r = разобрать(ТЕКСТ)
    assert r['fixDays'] == 30, r
    assert r['calendar'] == 'calendar', r
    assert r['responseHours'] == 24, r
    assert r['warrantyMonths'] == 36, r
    assert r['penaltyKind'] == 'per_day_pct' and r['penaltyValue'] == 0.1, r
    assert r['penaltyCap'] == 10.0, r
    пункты = {c['field']: c['code'] for c in r['clauses']}
    assert пункты['fixDays'] == '7.3', пункты
    assert пункты['penaltyValue'] == '7.4', пункты
    print('разбор:', {k: v for k, v in r.items() if k != 'clauses'})
    print('пункты:', пункты)

    s = санкция(r, 19, 2_500_000)
    assert s['amount'] == round(2_500_000 * 0.001 * 19, 2), s
    print('санкция за 19 дней:', s)

    s2 = санкция(r, 500, 2_500_000)   # упирается в потолок 10 %
    assert s2.get('capped') and s2['amount'] == 250_000.0, s2
    print('потолок:', s2['amount'], '₽')

    ш = следующий_шаг(r, date(2026, 9, 1), date(2026, 9, 19))
    assert ш['action'] == 'repeat_claim' and ш['daysLeft'] == 12, ш
    print('следующий шаг:', ш)

