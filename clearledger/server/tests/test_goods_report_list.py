"""Товарный отчёт в форме офиса: бумага и арифметика листа.

Лист сверяют глазами по расположению граф, поэтому проверяем именно состав
бумаги, а не только то, что ручка ответила. Расчёт по базе покрыт отдельно —
здесь чистая сборка листа из готовых данных.
"""
from app.services.store_goods_report_print import _деньги, лист_товарного_отчёта


ДАННЫЕ = {
    "period": {"from": "01.07.2026", "to": "31.07.2026"},
    "rows": [
        {"name": "Остаток на 01.07.2026 0:00:00", "date": "", "number": "",
         "purchase": None, "net": None, "vat": None, "margin": None,
         "retail": 829996.29, "kind": "остаток"},
        {"name": "Приход", "date": "", "number": "", "purchase": None,
         "net": None, "vat": None, "margin": None, "retail": None, "kind": "раздел"},
        {"name": 'ООО "Алиди ПРОФ"', "date": "02.07.2026",
         "number": "100026298062/79", "purchase": 9669.50, "net": 8284.75,
         "vat": 1384.75, "margin": 3500.50, "retail": 13170.00, "kind": "документ"},
        {"name": "Итого по счету 60", "date": "", "number": "",
         "purchase": 9669.50, "net": 8284.75, "vat": 1384.75, "margin": 3500.50,
         "retail": 13170.00, "kind": "итог"},
        {"name": "Итого по счету 71", "date": "", "number": "", "purchase": None,
         "net": None, "vat": None, "margin": None, "retail": None, "kind": "итог"},
        {"name": "Итого с остатком", "date": "", "number": "", "purchase": None,
         "net": None, "vat": None, "margin": None, "retail": 843166.29,
         "kind": "итог"},
    ],
}


def test_лист_повторяет_бумагу_офиса():
    лист = лист_товарного_отчёта(
        ДАННЫЕ, организация='ООО "Норд-Лайн"', подразделение="АЗС №8")
    for ждём in ("организация", "структурное подразделение", "Период с",
                 "0:00:00", "23:59:59", "Материально ответственное лицо",
                 "должность, фамилия, имя, отчество", "наименование", "документ",
                 "закупочная", "без НДС", "наценка", "розничная",
                 "Приложение", "документов",
                 "Отчёт с документами принял и проверил", "расшифровка подписи"):
        assert ждём in лист, f"на листе нет {ждём!r}"
    # Нумерация граф — как на бумаге: номер 4 стоит над тремя суммовыми
    # колонками сразу. Уедет она — бухгалтер перестанет узнавать лист.
    assert ("<td>1</td><td>2</td><td>3</td><td>4</td><td>4</td><td>4</td>"
            "<td>5</td><td>6</td>") in лист
    # Лист офиса печатают книжной ориентацией, и на экране он тоже бумага A4,
    # а не резиновая страница во всю ширину монитора.
    assert "@page{size:A4 portrait" in лист
    assert "width:210mm" in лист
    # Оговорки стоят на листе: его подписывают, и спорить будут по нему.
    assert "в розничных ценах" in лист
    assert "без топлива" in лист
    assert "В баланс товара расход не входит" in лист


def test_остатки_и_разделы_идут_курсивом_итоги_жирным():
    лист = лист_товарного_отчёта(
        ДАННЫЕ, организация="ООО", подразделение="АЗС №8")
    остаток = лист[lint := лист.index("Остаток на 01.07.2026")]
    assert остаток  # строка на месте
    # Служебные строки бумаги выделены, иначе лист читается сплошняком.
    assert '<tr class="курсив"><td>Остаток на 01.07.2026 0:00:00</td>' in лист
    assert '<tr class="курсив"><td>Приход</td>' in лист
    assert '<tr class="итог"><td>Итого по счету 60</td>' in лист
    # Документ — обычная строка, без класса.
    assert '<tr><td>ООО &quot;Алиди ПРОФ&quot;</td>' in лист


def test_ноль_печатается_пустой_графой():
    # У поставщика на упрощёнке НДС именно пуст, а «0,00» читается как
    # «посчитали и вышел ноль». Пустая графа — не косметика, а смысл.
    assert _деньги(0) == ""
    assert _деньги(None) == ""
    assert _деньги(1384.75) == "1 384,75"  # неразрывный пробел
    assert _деньги(829996.29) == "829 996,29"
    # «Итого по счету 71» на бумаге печатается пустым — строка есть, цифр нет.
    лист = лист_товарного_отчёта(ДАННЫЕ, организация="ООО", подразделение="АЗС")
    строка_71 = лист[лист.index("Итого по счету 71"):]
    строка_71 = строка_71[:строка_71.index("</tr>")]
    assert 'class="num"></td>' in строка_71, "счёт 71 напечатан нулями вместо пустых граф"
