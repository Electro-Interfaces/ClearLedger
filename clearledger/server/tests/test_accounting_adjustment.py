"""Корректировки перед выгрузкой: факт цел, правка помнит себя.

Проверяем то, что дороже всего сломать: оригинал не меняется, правка на
устаревшей версии факта не применяется молча, и править можно только то, что
разрешено — номенклатуру бухгалтерия правкой не переставляет.
"""
import uuid
from datetime import datetime, timezone

import pytest

from app.services.accounting_adjustment import (
    AdjustmentError,
    Корректировка,
    наложить,
    проверить_правку,
    хеш_документа,
)


def документ(**поля):
    основа = {
        "Тип": "retail_sale_sidegoods",
        "document_id": "doc-1",
        "Номер": "7085",
        "Дата": "2026-08-20T00:00:00+00:00",
        "Товары": [
            {"НомерСтроки": 1, "Наименование": "Кофе", "Номенклатура": "u-1",
             "Количество": 3, "Цена": 100.0, "Сумма": 300.0, "СуммаНДС": 54.1},
            {"НомерСтроки": 2, "Наименование": "Булка", "Номенклатура": "u-2",
             "Количество": 1, "Цена": 50.0, "Сумма": 50.0, "СуммаНДС": 9.0},
        ],
    }
    основа.update(поля)
    return основа


def пакет(док=None):
    return {"Документы": [док or документ()], "НСИ": []}


def правка(patch, *, хеш, автор="Жукова О.А.", причина="пересорт"):
    return Корректировка(
        id=uuid.uuid4(), doc_kind="retail_sale_sidegoods", document_id="doc-1",
        base_content_hash=хеш, patch=patch, reason=причина, author=автор,
        created_at=datetime(2026, 8, 23, 10, 0, tzinfo=timezone.utc),
    )


def test_правка_не_трогает_оригинал():
    исходный = пакет()
    хеш = хеш_документа(исходный["Документы"][0])
    итог = наложить(исходный, [правка(
        {"Строки": [{"НомерСтроки": 1, "Количество": 2, "Сумма": 200.0}]}, хеш=хеш)])

    # Оригинал остался ровно тем, чем был: его показывает «Магазин» и агент.
    assert исходный["Документы"][0]["Товары"][0]["Количество"] == 3
    assert исходный["Документы"][0]["Товары"][0]["Сумма"] == 300.0

    строка = итог.packet["Документы"][0]["Товары"][0]
    assert строка["Количество"] == 2 and строка["Сумма"] == 200.0
    # Вторая строка не тронута.
    assert итог.packet["Документы"][0]["Товары"][1]["Количество"] == 1
    assert итог.была_правка and not итог.устарели


def test_правка_помнит_автора_и_причину():
    п = пакет()
    хеш = хеш_документа(п["Документы"][0])
    итог = наложить(п, [правка(
        {"Строки": [{"НомерСтроки": 2, "Количество": 4}]},
        хеш=хеш, автор="Ирина Г.", причина="недовоз по накладной 258")])
    отметка = итог.packet["Документы"][0]["Корректировка"]
    assert отметка["Была"] is True
    assert отметка["Правки"][0]["Автор"] == "Ирина Г."
    assert "недовоз" in отметка["Правки"][0]["Причина"]


def test_устаревшая_правка_не_применяется_молча():
    """Смену пересчитали после правки — цифры другие, правка ждёт решения."""
    п = пакет()
    итог = наложить(п, [правка(
        {"Строки": [{"НомерСтроки": 1, "Количество": 2}]}, хеш="0" * 64)])
    assert not итог.применено and len(итог.устарели) == 1
    assert итог.packet["Документы"][0]["Товары"][0]["Количество"] == 3


def test_правки_ложатся_по_очереди():
    п = пакет()
    хеш = хеш_документа(п["Документы"][0])
    первая = правка({"Строки": [{"НомерСтроки": 1, "Количество": 2}]}, хеш=хеш)
    # Вторая сделана на той же версии факта: обе применяются в порядке правок.
    вторая = правка({"Строки": [{"НомерСтроки": 2, "Цена": 60.0}]}, хеш=хеш)
    итог = наложить(п, [первая, вторая])
    assert len(итог.применено) == 2
    assert итог.packet["Документы"][0]["Товары"][0]["Количество"] == 2
    assert итог.packet["Документы"][0]["Товары"][1]["Цена"] == 60.0
    assert len(итог.packet["Документы"][0]["Корректировка"]["Правки"]) == 2


def test_номенклатуру_правкой_не_переставить():
    with pytest.raises(AdjustmentError, match="Номенклатуру"):
        проверить_правку({"Строки": [{"НомерСтроки": 1, "Номенклатура": "u-чужой"}]})


def test_правка_обязана_быть_адресной():
    with pytest.raises(AdjustmentError):
        проверить_правку({})
    with pytest.raises(AdjustmentError, match="НомерСтроки"):
        проверить_правку({"Строки": [{"Количество": 2}]})
    with pytest.raises(AdjustmentError, match="без единого поля"):
        проверить_правку({"Строки": [{"НомерСтроки": 1}]})


def test_шапку_правим_только_разрешённое():
    проверить_правку({"Шапка": {"Комментарий": "уточнение по накладной"}})
    with pytest.raises(AdjustmentError, match="реквизиты шапки"):
        проверить_правку({"Шапка": {"BusinessShiftID": "чужой"}})


def test_хеш_документа_не_зависит_от_своей_отметки():
    """Иначе первая же правка сделала бы недействительной саму себя."""
    д = документ()
    было = хеш_документа(д)
    д["Корректировка"] = {"Была": True, "Правки": []}
    assert хеш_документа(д) == было


def test_снимок_прежних_значений_и_влияние_на_сумму():
    """Журнал за месяц не должен пересобирать пакеты, чтобы сказать «что было»."""
    from app.services.accounting_adjustment import снять_прежние

    прежние, дельта = снять_прежние(документ(), {
        "Строки": [{"НомерСтроки": 1, "Количество": 2, "Сумма": 200.0}],
    })
    было = прежние["Строки"]["1"]
    assert было["Количество"] == 3 and было["Сумма"] == 300.0
    # Наименование кладём всегда: через месяц «строка 1» ничего не значит.
    assert было["Наименование"] == "Кофе"
    # Документ стал дешевле на сотню — это и есть расхождение с фактом станции.
    assert дельта == -100.0


def test_влияние_считается_только_по_сумме():
    """Правка количества без суммы сумму документа не меняет."""
    from app.services.accounting_adjustment import снять_прежние

    _, дельта = снять_прежние(документ(), {"Строки": [{"НомерСтроки": 2, "Количество": 5}]})
    assert дельта == 0.0


def test_прежние_значения_шапки():
    from app.services.accounting_adjustment import снять_прежние

    прежние, _ = снять_прежние(документ(), {"Шапка": {"Комментарий": "уточнение"}})
    assert "Шапка" in прежние and прежние["Шапка"]["Комментарий"] is None
