# -*- coding: utf-8 -*-
"""Смена, приехавшая дважды, не считается дважды.

Пока агент не слал `НомерСменыВнутр`, ключом документа продаж был uuid пакета —
свой у каждой доставки. Та же смена, досланная позже уже с внутренним номером,
легла в реестр вторым документом, и выручка 11.06, 15.06 и 18.06 на АЗС 208
считалась дважды: 25 315 ₽ сверх факта.
"""
import inspect

from app.services import store_documents


def test_гашение_описано_в_адаптере():
    исходник = inspect.getsource(store_documents._edge_adapter)
    assert 'tail.startswith("смена:")' in исходник
    assert 'tail.startswith("пакет:")' in исходник


def test_ключ_гашения_учитывает_сумму():
    """11.06 под одним печатным номером стоят две смены — 897 ₽ и 0 ₽.

    Гасить их друг о друга нельзя: суммы разные, это разные смены. В ключ
    гашения обязана входить сумма, иначе нулевая смена съест денежную.
    """
    исходник = inspect.getsource(store_documents._edge_adapter)
    assert "c.station_id, c.document_kind, c.number, c.amount" in исходник


def test_номер_смены_остаётся_первым_ключом():
    исходник = inspect.getsource(store_documents._edge_document_identity)
    assert "НомерСменыВнутр" in исходник
    # Служебные пакеты с внутренним номером "0" не должны схлопнуться в один.
    assert 'internal != "0"' in исходник
