"""Переезд станции через две прокси не должен склеивать пути.

Ломалось так: агент отдаёт «/chain», хаб TradeLink подставляет свой внутренний
путь, а центр сверху вешал свой префикс — браузер получал адрес, которого нет
нигде, и ловил 404 на каждом «провёл документ → вернись к списку».
"""
from app.routers.station_console_router import нормализовать_переезд

ПРЕФИКС = "/api/store/station/208/console"


def test_путь_хаба_снимается_а_не_складывается():
    пришло = "/api/v1/integration/stations/208/console/chain?n=snap"
    assert нормализовать_переезд(пришло, ПРЕФИКС) == f"{ПРЕФИКС}/chain?n=snap"


def test_голый_путь_агента_получает_префикс():
    assert нормализовать_переезд("/receipts", ПРЕФИКС) == f"{ПРЕФИКС}/receipts"


def test_уже_наш_адрес_не_трогаем():
    assert нормализовать_переезд(f"{ПРЕФИКС}/receipts", ПРЕФИКС) is None


def test_корень_хаба_ведёт_в_корень_рабочей_области():
    пришло = "/api/v1/integration/stations/208/console"
    assert нормализовать_переезд(пришло, ПРЕФИКС) == f"{ПРЕФИКС}/"


def test_чужой_хост_остаётся_как_есть():
    assert нормализовать_переезд("https://ya.ru/", ПРЕФИКС) is None
