"""Станция сняла цену — центр закрывает её, а не пишет ноль.

«Цены нет» и «цена ноль» — разные состояния. Ноль назначить нельзя (нулевой
ценник на полке — ошибка ввода), а снятая цена законна: товар выведен из
продажи, либо станцию только подключили и цен ГИГ ещё нет.

05.09.2026 на АЗС 8 сняли 393 цены прежнего владельца — и все 393 приехали в
центр нулями, открытыми ценами станции. То есть сеть считала, что там продают
даром. Разбор направления: снятие едет без поля «ЦенаСтала», а ноль от старых
агентов трактуется так же — иначе дыра осталась бы до обновления всех станций.
"""


def решение(сырая_цена) -> tuple[bool, float]:
    """Повторяет ветвление из edge_nsi._применить_изменение_цены."""
    сняли = сырая_цена is None or float(сырая_цена) <= 0
    return сняли, 0.0 if сняли else float(сырая_цена)


def test_пустая_цена_это_снятие():
    сняли, цена = решение(None)
    assert сняли and цена == 0.0


def test_ноль_от_старого_агента_тоже_снятие():
    # Агенты до 1.300 шлют снятие нулём: не ждать обновления парка.
    assert решение(0)[0] is True
    assert решение("0.00")[0] is True


def test_обычная_цена_остаётся_ценой():
    сняли, цена = решение(285.5)
    assert not сняли and цена == 285.5
