# -*- coding: utf-8 -*-
"""Признание черновика и задание станции — одна транзакция.

Замечание ревизии 16.09.2026: `resolve_item_draft` фиксировала решение сама, а
задание вниз ставил роутер следующим шагом. В окне между ними карточка уже
заведена и черновик закрыт, а станция не знает ничего — и заводит товар заново
тем самым дублем, ради борьбы с которым очередь и существует.

Проверка идёт по РАЗБОРУ ИСХОДНИКА, а не по живой базе, и это не лень.
Таблицы `edge.item`, `edge.item_draft`, `edge.item_group` заводит инициализатор
базы пространства — вне приложения; `app.database.create_all` поднимает лишь
часть схемы `edge` (`item_code`, `mark_group`, `matrix_rule`, `nsi_proposal`).
Поднять их в фикстуре значило бы держать здесь копию чужого DDL, которая
разойдётся с боевой при первом же изменении и начнёт врать. Поэтому в этом
репозитории всё, что касается `edge`, проверяется исходником.
"""
import ast
import inspect

from app.routers import store_router
from app.services import edge_nsi


def _функция(модуль, имя):
    дерево = ast.parse(inspect.getsource(модуль))
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.AsyncFunctionDef, ast.FunctionDef)) and узел.name == имя:
            return узел
    raise AssertionError(f"функция {имя} не найдена")


def test_признание_не_коммитит_само():
    """Внутри сервиса не должно остаться ни одной фиксации."""
    узел = _функция(edge_nsi, "resolve_item_draft")
    коммиты = [
        у.lineno for у in ast.walk(узел)
        if isinstance(у, ast.Attribute) and у.attr == "commit"
    ]
    assert not коммиты, (
        "resolve_item_draft фиксирует решение сама (строки %s): станция не узнает "
        "о карточке, если роутер не дойдёт до постановки задания" % коммиты
    )


def test_роутер_коммитит_после_постановки_задания():
    """Признание: сперва задание станциям, потом фиксация. Оба в одном месте."""
    узел = _функция(store_router, "store_resolve_item_draft")
    задание = [
        у.lineno for у in ast.walk(узел)
        if isinstance(у, ast.Call) and isinstance(у.func, ast.Name)
        and у.func.id == "_queue_nsi_delta"
    ]
    коммиты = [
        у.lineno for у in ast.walk(узел)
        if isinstance(у, ast.Attribute) and у.attr == "commit"
    ]
    assert задание, "роутер не ставит задание станциям — признанная карточка не уедет вниз"
    assert коммиты, "роутер не фиксирует транзакцию — решение не сохранится"
    assert min(задание) < max(коммиты), (
        "фиксация раньше постановки задания: задание %s, commit %s" % (задание, коммиты)
    )


def test_отказ_тоже_доезжает_до_станции():
    """Иначе черновик уезжает наверх каждый такт до скончания времён."""
    исходник = inspect.getsource(store_router.store_resolve_item_draft)
    assert "item_draft_rejected" in исходник, "отказ не ставится заданием станции"
    assert "EdgeDownlink" in исходник


def test_близнецы_ищутся_в_ярусе_кода():
    """Короткий внутренний номер принадлежит своей станции, а не всей сети.

    «9233» с АЗС 8 не должен закрывать заявку 208, где под этим номером другой
    товар: станция осталась бы без карточки, считая её разобранной.
    """
    исходник = inspect.getsource(edge_nsi.resolve_item_draft)
    близнецы = исходник[исходник.index("близнецы"):]
    assert "d.station_id = :st" in близнецы, (
        "поиск заявок-близнецов не ограничен станцией для коротких кодов"
    )
