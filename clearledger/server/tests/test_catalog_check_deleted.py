"""Карточка, удалённая в центре, но живая на станции, — не «нет в центре».

На 208 такая карточка («Позиция без карточки (код кассы 516)») месяц горела
предупреждением «карточек нет в центре: 1», хотя сеть о ней прекрасно знала:
она была помечена удалённой 11.08, а станция удаления не получила. Диагноз
уводил в разбор несуществующей дыры вместо досылки дельты.
"""
import inspect

from app.services import edge_nsi


def test_сверка_отделяет_удалённые_от_неизвестных():
    исходник = inspect.getsource(edge_nsi)
    # Карточки центра читаются целиком, а фильтр «живых» — уже в Python:
    # запрос WHERE NOT deleted не давал отличить удалённую от неизвестной.
    assert "FROM edge.item\n        \"\"\"" in исходник or \
           "SELECT external_uuid::text AS uuid, coalesce(sku, '') AS sku, name,\n" in исходник
    assert "удаление_не_доехало" in исходник
    assert "deletions_resent" in исходник


def test_удаление_досылается_дельтой():
    """Заметили расхождение — сразу чиним, а не только сообщаем."""
    исходник = inspect.getsource(edge_nsi)
    хвост = исходник[исходник.index("удаление_не_доехало"):]
    assert "_queue_nsi_delta" in хвост
