COMMON_ARTICLES += [{**a, "category": PROJECTS_CATEGORY}
                    for a in PROJECT_ARTICLES if a.get("common")]
ARTICLES += [{**a, "category": PROJECTS_ENERGY_CATEGORY}
             for a in PROJECT_ARTICLES if not a.get("common")]


async def _seed_pack(db: AsyncSession, profile: str | None,
                     categories: list[dict[str, Any]],
                     articles: list[dict[str, Any]]) -> dict[str, int]:
    """Завести один пакет знания (общий или профильный). Идемпотентно."""
    # Пакет ищет своё по профилю, но общий слой дополнительно ПОДБИРАЕТ статью,
    # заведённую раньше под отраслью: три статьи про устройство пространства успели
    # уехать в пакет энергетики. Без подбора повторный сид создал бы вторую копию, и
    # пространство получило бы два ответа на один вопрос.
    def _own(model: Any):
        return model.profile_id.is_(None) if profile is None else model.profile_id == profile

    # Берём ПЕРВУЮ подходящую, а не «одну или ни одной»: сервер поднимается двумя
    # воркерами, и сид выполняется дважды одновременно. Гонка успевает завести две
    # одноимённые записи, после чего строгая выборка роняла весь сид целиком
    # («Multiple rows were found»), а вместе с ним и обновление всех текстов.
    def _norm(col: Any):
        """Заголовок без разницы «тире или дефис»."""
        return func.replace(func.replace(col, "—", "-"), "–", "-")

    async def _find(model: Any, title: str) -> tuple[Any, list[Any]]:
        rows = (await db.execute(select(model).where(
            model.company_id.is_(None), _own(model), model.title == title))).scalars().all()
        # Заголовок мог смениться только знаком (правка по навыку «хуманизатор»:
        # длинное тире ушло на дефис). Точное сравнение завело бы вторую статью, а
        # первая осталась бы висеть рядом с тем же текстом.
        if not rows:
            norm = title.replace("—", "-").replace("–", "-")
            rows = (await db.execute(select(model).where(
                model.company_id.is_(None), _own(model), _norm(model.title) == norm))).scalars().all()
        if not rows and profile is None:
            rows = (await db.execute(select(model).where(
                model.company_id.is_(None), _norm(model.title) == title.replace(
                    "—", "-").replace("–", "-")))).scalars().all()
        return (rows[0] if rows else None), list(rows[1:])

    cats: dict[str, InfoCategory] = {}
    for c in categories:
        row, twins = await _find(InfoCategory, c["title"])
        if row is not None:
            row.profile_id = profile
            row.sort_order = c["sort"]
            # Двойников схлопываем: статьи переезжают на оставшийся раздел, иначе в
            # дереве стоят два одинаковых раздела с разным составом.
            for dup in twins:
                await db.execute(text(
                    "update info_articles set category_id = :keep where category_id = :drop"),
                    {"keep": str(row.id), "drop": str(dup.id)})
                await db.delete(dup)
        if row is None:
            row = InfoCategory(company_id=None, profile_id=profile, title=c["title"],
                               sort_order=c["sort"])
            db.add(row)
            await db.flush()
        cats[c["title"]] = row

    # Родители проставляются вторым проходом: раздел может ссылаться на
    # приложение, объявленное ниже по списку, и порядок в файле не должен решать,
    # соберётся дерево или нет. Родитель ищется и среди уже заведённых разделов
    # других пакетов: «Проекты» объявлены в отраслевом пакете, а «Трек» в общем.
    for c in categories:
        title = c.get("parent")
        if not title:
            continue
        parent = cats.get(title)
        if parent is None:
            # Родителя ищем БЕЗ фильтра по профилю: приложения объявлены в общем
            # слое, а вкладываются в них и отраслевые разделы («Топливо»,
            # «Станция»). С фильтром профиля отраслевой пакет родителя не видел
            # и оставался плоским.
            parent = (await db.execute(select(InfoCategory).where(
                InfoCategory.company_id.is_(None),
                InfoCategory.title == title))).scalars().first()
        if parent is None or parent.id == cats[c["title"]].id:
            continue
        cats[c["title"]].parent_id = parent.id
    await db.flush()

    created = updated = renamed = 0
    for a in articles:
        row, twins = await _find(InfoArticle, a["title"])
        # Та же гонка двух воркеров, только на статьях: лишние копии удаляем, чтобы
        # в дереве не стояло два одинаковых заголовка.
        for dup in twins:
            await db.delete(dup)
        # Статью ищем по заголовку, поэтому переименование в сиде без подсказки
        # рождает вторую статью, а первая остаётся жить рядом — и пространство
        # получает два ответа на один вопрос. `renamed_from` переносит заголовок
        # на существующую статью вместе с её историей и привязками.
        if row is None and a.get("renamed_from"):
            row, _ = await _find(InfoArticle, a["renamed_from"])
            if row is not None:
                row.title = a["title"]
                renamed += 1
        if row is None:
            row = InfoArticle(company_id=None, profile_id=profile, title=a["title"])
            db.add(row)
            created += 1
        elif not a.get("renamed_from") or row.title == a["title"]:
            updated += 1
        row.kind = a["kind"]
        row.summary = a.get("summary")
        row.body_md = a["body"].strip()
        row.status = "published"
        row.doc_number = a.get("doc_number")
        row.source_url = a.get("source_url")
        row.effective_date = a.get("effective_date")
        # Документ, который ведёт процесс: рядом с кнопкой лежит первоисточник,
        # по которому эта кнопка появилась.
        row.process_ref = a.get("process_ref")
        row.sort_order = a.get("sort", 0)
        row.category_id = cats[a["category"]].id
        await db.flush()
        # Привязки задаём заново: сид — источник правды для платформенных статей.
        for b in (await db.execute(select(InfoBinding).where(
                InfoBinding.article_id == row.id))).scalars().all():
            await db.delete(b)
        for app_code, section, weight in a["bindings"]:
            db.add(InfoBinding(article_id=row.id, app_code=app_code,
                               section_key=section, weight=weight))
        row.profile_id = profile
    return {"created": created, "updated": updated, "renamed": renamed}


async def seed_info(db: AsyncSession) -> dict[str, int]:
    """Знание платформы: общий слой + пакеты отраслевых профилей.

    Общий слой (`profile_id IS NULL`) виден каждому пространству: как устроена сама
    система, роли, чаты, подключения. Профильные пакеты — только своей отрасли.
    Раньше общее лежало в пакете энергетики, и топливное пространство открывало
    «Инфо» пустым, хотя в базе было четыре десятка статей.
    """
    total = {"created": 0, "updated": 0, "renamed": 0}
    packs = [
        # «Трек» есть в каждом пространстве независимо от профиля, как «Чаты» и
        # «Управление», поэтому его знание лежит в общем слое, а не в отраслевом.
        # «Инфо» и «Трек» — приложения Ядра: их знание общее для всех профилей.
        (None, COMMON_CATEGORIES + TRACK_CATEGORIES + HELP_CATEGORIES
         + SUPPORT_CATEGORIES + PULSE_CATEGORIES,
         COMMON_ARTICLES + TRACK_ARTICLES + HELP_ARTICLES + SUPPORT_ARTICLES + PULSE_ARTICLES),
        (PROFILE, CATEGORIES, ARTICLES),
        # Топливный профиль ведёт «Топливо», «Магазин» и рабочее место АЗС. Пакеты
        # раздельные (их правят разные люди и в разное время), профиль один.
        (FUEL_PROFILE,
         FUEL_CATEGORIES + SHOP_CATEGORIES + STATION_CATEGORIES,
         FUEL_ARTICLES + SHOP_ARTICLES + STATION_ARTICLES),
        # Компания без объектов: знание по «Реализации». Пакет свой — вопросы у неё
        # другие: не «как принять топливо», а «откуда эта сумма и чему она равна в
        # бухгалтерии».
        (OFFICE_PROFILE, OFFICE_CATEGORIES, OFFICE_ARTICLES),
    ]
    for profile, cats, arts in packs:
        res = await _seed_pack(db, profile, cats, arts)
        for k in total:
            total[k] += res[k]
    return total
