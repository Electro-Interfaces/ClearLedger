ARTICLES += [{**a, "category": PROJECTS_CATEGORY} for a in PROJECT_ARTICLES]


async def seed_info(db: AsyncSession) -> dict[str, int]:
    """Завести платформенное знание отрасли. Идемпотентно."""
    cats: dict[str, InfoCategory] = {}
    for c in CATEGORIES:
        row = (await db.execute(select(InfoCategory).where(
            InfoCategory.company_id.is_(None), InfoCategory.profile_id == PROFILE,
            InfoCategory.title == c["title"]))).scalar_one_or_none()
        if row is None:
            row = InfoCategory(company_id=None, profile_id=PROFILE, title=c["title"],
                               sort_order=c["sort"])
            db.add(row)
            await db.flush()
        cats[c["title"]] = row

    created = updated = 0
    for a in ARTICLES:
        row = (await db.execute(select(InfoArticle).where(
            InfoArticle.company_id.is_(None), InfoArticle.profile_id == PROFILE,
            InfoArticle.title == a["title"]))).scalar_one_or_none()
        if row is None:
            row = InfoArticle(company_id=None, profile_id=PROFILE, title=a["title"])
            db.add(row)
            created += 1
        else:
            updated += 1
        row.kind = a["kind"]
        row.summary = a.get("summary")
        row.body_md = a["body"].strip()
        row.status = "published"
        row.doc_number = a.get("doc_number")
        row.source_url = a.get("source_url")
        row.sort_order = a.get("sort", 0)
        row.category_id = cats[a["category"]].id
        await db.flush()
        # Привязки задаём заново: сид — источник правды для платформенных статей.
        for b in (await db.execute(select(InfoBinding).where(
                InfoBinding.article_id == row.id))).scalars().all():
            await db.delete(b)
        for app_code, section, weight in a["bindings"]:
            db.add(InfoBinding(article_id=row.id, app_code=app_code,
                               section_key=section, weight=weight))
    return {"created": created, "updated": updated}
