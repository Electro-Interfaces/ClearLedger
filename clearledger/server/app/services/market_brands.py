"""Бренд владельца, спрятанный в названии точки.

Публичный реестр знает, под чьей ИТ-системой станция работает, но не знает, чья
она. Станции EvCar27 в Хабаровске приходят оператором «ItCharge» — это поставщик
платформы, — а само имя владельца остаётся внутри названия точки: «ТЦ ПОДСОЛНУХ
EvCar27 (тех. поддержка 8-909-851-77-77)». Пока роль была одна, такая сеть
числилась за платформой, а владельца в реестре не было вовсе — и разговаривать об
интеграции было не с кем (замечание РусГидро 14.09.2026).

Разбор здесь ничего не решает: он ПРЕДЛАГАЕТ. Повторяющееся в названиях слово —
сильный признак бренда, но слабое основание заводить компанию: так же выглядят
название торгового центра и фамилия подрядчика. Поэтому кандидат уходит человеку
списком, и владелец появляется только после подтверждения.
"""
from __future__ import annotations

import re
from collections import defaultdict

# Слова, которые встречаются в названиях станций повсеместно и брендом не являются:
# место установки, оснащение, положение поста. Без этого списка первым «брендом»
# рынка оказывается «парковка».
СТОП = {
    # место
    "парк", "парковка", "парковке", "отель", "гостиница", "торговый", "центр",
    "аэропорт", "вокзал", "автомойка", "мойка", "заправка", "азс", "офис",
    "стоянка", "площадь", "улица", "шоссе", "проспект", "переулок", "набережная",
    "корпус", "строение", "здание", "территория", "комплекс", "квартал",
    # оснащение и режим
    "зарядная", "зарядной", "станция", "станции", "эзс", "быстрая", "медленная",
    "быстрой", "медленной", "разъём", "разъем", "коннектор", "мощность", "квт",
    "круглосуточно", "работает", "временно", "закрыта", "тест", "тестовая",
    "поддержка", "телефон", "тел", "новое", "переведена",
    # положение
    "слева", "справа", "левая", "правая", "первая", "вторая", "третья",
    "верхняя", "нижняя", "дальняя", "ближняя", "въезд", "выезд", "подъезд",
    # латиница общего смысла
    "charge", "charger", "charging", "station", "power", "fast", "slow",
    "type", "plug", "connector", "mall", "hotel", "parking", "office", "shop",
}

# Куски, которые в названии стоят рядом с брендом и мешают его увидеть.
МУСОР = re.compile(
    r"\(([^)]*)\)"                 # всё в скобках: «(тех. поддержка …)»
    r"|\b\d[\d\-\s]{4,}\b"         # телефоны
    r"|\b(?:dc|ac|lv)\s*\d*\b"     # DC30, AC22
    r"|\b\d+\s*(?:квт|kw|kwt)\b",  # 150 кВт
    re.IGNORECASE)

ТОКЕН = re.compile(r"[A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё0-9]{2,}")

# Адрес: он проходит фильтр общих слов, но брендом не бывает.
СТОП |= {"трц", "тц", "жк", "мкрн", "стр", "корп", "пр", "ул", "пер", "наб", "мфц",
         "проезд", "тупик", "бульвар", "аллея", "магистраль", "километр", "дом", "дача"}


def _слова(название: str) -> list[str]:
    очищено = МУСОР.sub(" ", название or "")
    return [т for т in ТОКЕН.findall(очищено) if т.lower() not in СТОП]


def _корень(слово: str) -> str:
    """Начало слова без окончания — чтобы «Москва» и «Москвы» считались одним.

    Пяти букв достаточно, чтобы различить города между собой, и хватает, чтобы
    падежи сошлись. Полноценная нормализация здесь не нужна: сравниваем не смысл,
    а совпадение с названием города, в котором точка стоит.
    """
    return слово.lower()[:5]


def кандидаты_брендов(
    точки: list[tuple[str, str, str | None]],
    имя_оператора: str,
    порог: int = 3,
) -> list[dict]:
    """Слова из названий, похожие на бренд владельца.

    `точки` — тройки (id, название, город). Возвращает кандидатов от частого к
    редкому: слово, сколько точек его несут, города и сами точки.

    Порог в три точки — граница между сетью и совпадением: одна станция «у Артёма»
    брендом не делает, три одинаковых слова в разных городах — уже сеть. Слово,
    совпадающее с именем самого оператора, кандидатом не считается: это его
    собственные точки, а не чужие под его платформой.
    """
    свои = {с.lower() for с in _слова(имя_оператора)} | {имя_оператора.lower()}
    # Города, где стоят точки: «Вологда» в названии — это адрес, а не сеть. Без
    # этого отбора первыми «брендами» рынка выходят Москва, Иваново и Воронеж.
    города_сети = {_корень(г) for _, _, г in точки if г for г in г.split()}

    по_слову: dict[str, dict] = defaultdict(
        lambda: {"точки": [], "города": set(), "написания": defaultdict(int)})

    def учесть(ключ: str, написание: str, id_: str, город: str | None) -> None:
        группа = по_слову[ключ]
        группа["точки"].append(id_)
        группа["написания"][написание] += 1
        if город:
            группа["города"].add(город)

    for id_, название, город in точки:
        слова = _слова(название)
        # Бренд бывает из двух слов: «Скорость света», «GREEN DRIVE», «Энергия
        # Москвы». По одному слову они разваливаются на половинки, каждая из
        # которых сама по себе ничего не значит, — поэтому считаем и пары соседних.
        пары = [f"{a} {b}" for a, b in zip(слова, слова[1:])]
        # Одно и то же считается один раз на точку: «EvCar27 … EvCar27» в названии
        # не делает станцию двумя.
        for написание in {с.lower(): с for с in слова}.values():
            ключ = написание.lower()
            if ключ in свои or _корень(написание) in города_сети:
                continue
            учесть(ключ, написание, id_, город)
        for написание in {с.lower(): с for с in пары}.values():
            ключ = написание.lower()
            if ключ in свои:
                continue
            учесть(ключ, написание, id_, город)

    итог = []
    for ключ, группа in по_слову.items():
        if len(группа["точки"]) < порог:
            continue
        # Показываем то написание, которое встречается чаще: «EvCar27», а не «EVCAR27».
        бренд = max(группа["написания"].items(), key=lambda kv: kv[1])[0]
        итог.append({
            "brand": бренд,
            "key": ключ,
            "sites": len(группа["точки"]),
            "cities": sorted(группа["города"])[:6],
            "citiesTotal": len(группа["города"]),
            "siteIds": группа["точки"],
        })

    # Половинка двусловного бренда стоит ровно на тех же точках, что и пара целиком:
    # «Скорость» и «света» — это «Скорость света». Оставляем пару, половинки убираем,
    # иначе человек разбирает один и тот же бренд трижды.
    пары_ключи = [к for к in итог if " " in к["key"]]
    лишние = set()
    for пара in пары_ключи:
        for часть in пара["key"].split(" "):
            for к in итог:
                if к["key"] == часть and к["sites"] == пара["sites"]:
                    лишние.add(к["key"])
    итог = [к for к in итог if к["key"] not in лишние]
    итог.sort(key=lambda к: (-к["sites"], к["brand"]))
    return итог


if __name__ == "__main__":
    # Проверка на боевых названиях: разбор обязан вытащить EvCar27 и не принять
    # за бренд ни торговый центр, ни телефон поддержки.
    примеры = [
        ("1", "ТЦ ПОДСОЛНУХ EvCar27 (тех. поддержка 8-909-851-77-77)", "Хабаровск"),
        ("2", "БОЛЬШАЯ EvCar27 (тех. поддержка 8-909-851-77-77)", "Хабаровск"),
        ("3", "ЛИДОГА EvCar27 DC30 (тех. поддержка 8-909-851-77-77)", "Лидога"),
        ("4", "ТРЦ ЛИНКОР (AC) EvCar27", "Амурск"),
        ("5", "Технополис Печатники AC22 #09", "Москва"),
    ]
    вышло = кандидаты_брендов(примеры, "ItCharge")
    assert вышло, "бренд не найден"
    assert вышло[0]["brand"] == "EvCar27", вышло[0]
    assert вышло[0]["sites"] == 4, вышло[0]
    assert вышло[0]["citiesTotal"] == 3, вышло[0]
    ключи = {к["key"] for к in вышло}
    assert "поддержка" not in ключи, "служебное слово прошло как бренд"
    assert "дс30" not in ключи and "dc" not in ключи, "оснащение прошло как бренд"

    # Двусловный бренд не разваливается на половинки: в выдаче «Скорость света»,
    # а не «Скорость» и «света» по отдельности.
    двусловные = [("1", "Скорость света Красногорск", "Красногорск"),
                  ("2", "Скорость света Москва", "Москва"),
                  ("3", "Скорость света Немчиновка", "Немчиновка")]
    пары = кандидаты_брендов(двусловные, "ItCharge")
    assert пары and пары[0]["brand"] == "Скорость света", пары
    assert "скорость" not in {к["key"] for к in пары}, "половинка бренда осталась в списке"

    # Город, в котором стоит точка, брендом не считается — ни в каком падеже.
    городские = [("1", "Москва Ленинский", "Москва"), ("2", "Москвы север", "Москва"),
                 ("3", "Москва юг", "Москва")]
    assert not [к for к in кандидаты_брендов(городские, "ItCharge")
                if к["key"].startswith("москв")], "город прошёл как бренд"
    # Имя самого оператора кандидатом не становится.
    свои_точки = [("1", "ItCharge Пермь", None), ("2", "ItCharge Казань", None),
                  ("3", "ItCharge Сочи", None)]
    assert not кандидаты_брендов(свои_точки, "ItCharge"), "оператор предложен сам себе"
    print("market_brands: проверки прошли")
