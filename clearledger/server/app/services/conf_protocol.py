"""Черновик протокола по расшифровке конференции.

Языковой модели в пространстве нет, и отдавать разговор наружу ради протокола
нельзя: в нём персональные данные и коммерческая тайна. Поэтому черновик
собирается правилами — и это именно черновик: его читает и правит человек,
поручения уходят в «Трек» только после его нажатия.

Что ищем в каждой фразе:
- **решение** — «решили», «договорились», «утвердили», «итог»;
- **поручение** — глагол действия или обязанности («подготовить», «нужно»,
  «прошу») либо срок («до пятницы», «до 20.10»);
- **исполнителя** — участника встречи, чья фамилия или имя звучит в фразе;
  назван не один или никто — поле остаётся пустым, его ставит человек;
- **срок** — «завтра», «до пятницы», «через неделю», «до 20.10», «к 5 ноября».
"""
from __future__ import annotations

import re
from datetime import date, timedelta

_РЕШЕНИЕ = re.compile(
    r"\b(решил\w*|решени\w*|договорил\w*|приняли|принято|утверд\w*|итог\w*)", re.I)
_ПОРУЧЕНИЕ = re.compile(
    r"\b(поруч\w*|подготов\w*|сдела\w*|отправ\w*|направ\w*|провер\w*|соглас\w*|"
    r"организ\w*|выясн\w*|уточн\w*|созвон\w*|позвон\w*|напиш\w*|написать|"
    r"прош\w*|нужно|надо|необходимо|должн\w*|возьм\w*|займ\w*|сдела\w*)\b", re.I)
_ДНИ = ["понедельник", "вторник", "сред", "четверг", "пятниц", "суббот", "воскресень"]
_МЕСЯЦЫ = ["январ", "феврал", "март", "апрел", "ма", "июн", "июл", "август",
           "сентябр", "октябр", "ноябр", "декабр"]
_ПРЕДЕЛ = 40  # пунктов в черновике: дальше это пересказ, а не протокол


def _фразы(отрезки: list[dict]) -> list[tuple[float, str]]:
    """Фразы с временем начала отрезка, в котором они прозвучали."""
    out = []
    for o in отрезки:
        for часть in re.split(r"(?<=[.!?])\s+", (o.get("text") or "").strip()):
            if len(часть) >= 12:
                out.append((float(o.get("start") or 0), часть))
    return out


def _основы(имя: str) -> list[str]:
    """Основы для поиска человека в речи: фамилия и имя без окончания.

    «Марков Антон» звучит как «Маркову», «Антона», «Антон Александрович» —
    сравниваем по началу слова. Короткие основы не берём: «Ив» нашлось бы везде.
    """
    части = [ч for ч in re.split(r"[\s.]+", имя or "") if ч]
    основы = []
    for ч in части[:2]:
        основа = ч.lower()[: max(4, len(ч) - 2)]
        if len(основа) >= 4:
            основы.append(основа)
    return основы


def _исполнитель(фраза: str, люди: list[tuple[str, str]]) -> str | None:
    слова = re.findall(r"\w+", фраза.lower())
    найдены = {uid for uid, имя in люди
               if any(с.startswith(о) for о in _основы(имя) for с in слова)}
    return найдены.pop() if len(найдены) == 1 else None


def _срок(фраза: str, сегодня: date) -> date | None:
    ф = фраза.lower()
    if "послезавтра" in ф:
        return сегодня + timedelta(days=2)
    if "завтра" in ф:
        return сегодня + timedelta(days=1)
    if "через неделю" in ф:
        return сегодня + timedelta(days=7)
    if "конца недели" in ф:
        return сегодня + timedelta(days=(4 - сегодня.weekday()) % 7)
    m = re.search(r"\b(\d{1,2})\.(\d{1,2})(?:\.(\d{2,4}))?\b", ф)
    if m:
        год = int(m[3]) if m[3] else сегодня.year
        год += 2000 if год < 100 else 0
        try:
            d = date(год, int(m[2]), int(m[1]))
        except ValueError:
            d = None
        if d and not m[3] and d < сегодня:
            d = d.replace(year=d.year + 1)
        if d:
            return d
    m = re.search(r"\b(\d{1,2})\s+(" + "|".join(_МЕСЯЦЫ) + r")\w*", ф)
    if m:
        месяц = next(i for i, x in enumerate(_МЕСЯЦЫ, 1) if m[2].startswith(x))
        try:
            d = date(сегодня.year, месяц, int(m[1]))
            return d if d >= сегодня else d.replace(year=d.year + 1)
        except ValueError:
            pass
    for i, день in enumerate(_ДНИ):
        if re.search(r"\b(до|к|в|во)\s+" + день, ф):
            return сегодня + timedelta(days=(i - сегодня.weekday() - 1) % 7 + 1)
    return None


def черновик(отрезки: list[dict], люди: list[tuple[str, str]], сегодня: date) -> list[dict]:
    """Пункты протокола из расшифровки: решения и поручения по порядку разговора."""
    пункты: list[dict] = []
    виденные: set[str] = set()
    for at, фраза in _фразы(отрезки):
        ключ = фраза.lower()
        if ключ in виденные:
            continue
        срок = _срок(фраза, сегодня)
        if _РЕШЕНИЕ.search(фраза):
            вид = "decision"
        elif _ПОРУЧЕНИЕ.search(фраза) or срок:
            вид = "task"
        else:
            continue
        виденные.add(ключ)
        пункты.append({
            "kind": вид, "text": фраза, "at": at,
            "assignee_id": _исполнитель(фраза, люди) if вид == "task" else None,
            "due": срок.isoformat() if срок and вид == "task" else None,
            "task_id": None,
        })
        if len(пункты) >= _ПРЕДЕЛ:
            break
    return пункты


def текстом(пункты: list[dict], имена: dict[str, str]) -> str:
    """Протокол строками — для заметки встречи и для сообщения участникам."""
    решения = [п for п in пункты if п.get("kind") == "decision"]
    поручения = [п for п in пункты if п.get("kind") == "task"]
    строки: list[str] = []
    if решения:
        строки.append("Решения:")
        строки += [f"{i}. {п['text']}" for i, п in enumerate(решения, 1)]
    if поручения:
        строки.append("Поручения:")
        for i, п in enumerate(поручения, 1):
            кто = имена.get(п.get("assignee_id") or "", "исполнитель не назначен")
            срок = f", срок {date.fromisoformat(п['due']).strftime('%d.%m.%Y')}" if п.get("due") else ""
            строки.append(f"{i}. {п['text']} — {кто}{срок}")
    return "\n".join(строки)
