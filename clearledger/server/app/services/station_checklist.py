def checklist_meta() -> dict[str, Any]:
    """Регламент осмотра целиком — для экрана и подсказок в карточке."""
    return {
        "groups": [
            {**g, "items": [i for i in ITEMS if i["group"] == g["code"]]}
            for g in GROUPS
        ],
        "states": [{"code": c, "label": l} for c, l in STATES.items()],
        "total": len(ITEMS),
        "photo_required": sum(1 for i in ITEMS if i["photo"]),
    }
