"""Сопоставление реестра документов 1С с нашими сменами.

Реестр `accounting_docs` наполняется срезом боевой БП, но сам по себе он немой:
семьдесят тысяч записей со статусом «pending» не отвечают на вопрос «чей это
документ и к какой нашей смене он относится». Раньше сопоставление умел только
ИНН-матчинг под топливные смены STS — на розничных документах, у которых
контрагента нет вовсе, он не срабатывал никогда.

Связь берём из метки, которую канал ставит в комментарий документа (разбор —
`onec_accounting_read.метка_канала`, канон — `docs/Сопоставление_с_1С.md`):

    «TL|ЦБ|<пакет>|<UUID>»          сопутка: канал ЦБ, документы на день
    «TL|СМЕНА|15|208|7085|cards»    топливо: канал STS, документы на смену

UUID источника из метки на исторических документах нам не поможет: их заводил
прежний канал из базы ЦБ, и ссылки там её, а не наши. Поэтому сопутку вяжем по
станции и дню, топливо — по станции и внутреннему номеру смены. Как только наш
канал заработает, UUID начнёт совпадать — тогда связь станет подокументной, и
этот путь встанет первым.

Что не сопоставилось — не молчит: у каждого документа остаётся причина, по
которой связь не нашлась. Чаще всего она честная — станции нет в нашем контуре.
"""
from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from typing import Any

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

# Копейка: ниже неё расхождение сумм — округление, а не потеря.
ПОРОГ = 0.005

# Наш вид документа против их вида. Сравнивать в лоб можно только выручку: у
# розницы с обеих сторон один смысл и одна сумма, тогда как наша инвентаризация
# превращается в БП в два разных документа.
НАША_РОЗНИЦА = "retail_sale_sidegoods"
РОЗНИЦА_1С = "ОРП"


@dataclass
class Итог:
    """Что дал проход сопоставления."""

    рассмотрено: int = 0
    связано: int = 0
    расхождений: int = 0
    без_связи: int = 0
    по_методам: dict[str, int] = field(default_factory=dict)
    причины: dict[str, int] = field(default_factory=dict)

    def как_словарь(self) -> dict[str, Any]:
        return {
            "Рассмотрено": self.рассмотрено,
            "Связано": self.связано,
            "Расхождений": self.расхождений,
            "БезСвязи": self.без_связи,
            "ПоМетодам": self.по_методам,
            "Причины": self.причины,
        }


async def _наши_смены(
    session: AsyncSession, company_id: uuid.UUID,
) -> tuple[dict, dict, dict, dict]:
    """Индексы наших смен: по (станция, день), по (станция, номер) и по UUID.

    Три индекса потому, что каналы метят документы по-разному: сопутка знает
    день, топливо — номер смены, а наш собственный канал понесёт UUID источника.
    Внутри дня смен бывает три, поэтому в дневном индексе держим список.
    """
    # По дню и номеру ищем смену целиком — это записи розницы. По UUID ищем
    # конкретный документ, и здесь вид не важен: ссылку несут и выпуски блюд, и
    # приёмки, и списания. Ограничить индекс розницей значило бы объявить
    # «нашей записи нет» там, где она есть соседней строкой.
    строки = (await session.execute(text("""
        SELECT id, doc_type_id,
               metadata->'Смена'->>'КодАЗС'          AS станция,
               metadata->'Смена'->>'НомерСменыВнутр' AS номер,
               left(metadata->'Смена'->>'Закрытие', 10) AS день,
               metadata->'Документ'->>'ИсточникUUID'  AS источник,
               metadata->'Документ'->>'Номер'          AS номер_документа
          FROM data_entries
         WHERE company_id = :c
           AND (metadata->'Документ'->>'ИсточникUUID' IS NOT NULL
                OR metadata->'Смена'->>'КодАЗС' IS NOT NULL)
    """), {"c": str(company_id)})).mappings().all()

    по_дню: dict[tuple[str, str], list[uuid.UUID]] = {}
    по_смене: dict[tuple[str, str], uuid.UUID] = {}
    по_источнику: dict[str, uuid.UUID] = {}
    по_номеру: dict[str, uuid.UUID] = {}
    for р in строки:
        if р["источник"]:
            по_источнику[str(р["источник"])] = р["id"]
        if р["номер_документа"] and р["doc_type_id"] == НАША_РОЗНИЦА:
            по_номеру[str(р["номер_документа"])] = р["id"]
        станция = str(р["станция"] or "").strip()
        if not станция or р["doc_type_id"] != НАША_РОЗНИЦА:
            continue
        if р["день"]:
            по_дню.setdefault((станция, str(р["день"])), []).append(р["id"])
        if р["номер"]:
            по_смене[(станция, str(р["номер"]))] = р["id"]
    return по_дню, по_смене, по_источнику, по_номеру


async def _наша_выручка(
    session: AsyncSession, company_id: uuid.UUID, entry_id: uuid.UUID,
) -> float | None:
    """Розница нашей смены — для сравнения с суммой ОРП в 1С."""
    сумма = (await session.execute(text("""
        SELECT (metadata->'Документ'->>'СуммаДокумента')::numeric
          FROM data_entries WHERE company_id = :c AND id = :id
    """), {"c": str(company_id), "id": str(entry_id)})).scalar()
    return float(сумма) if сумма is not None else None


async def сопоставить_реестр(
    session: AsyncSession, company_id: uuid.UUID, *,
    только_свежие: bool = True,
) -> Итог:
    """Проставить связь и статус каждому документу 1С, у которого есть метка.

    `только_свежие` — работать по документам с меткой канала. Без метки связь
    искать нечем: это либо чужой контур, либо старый импорт, где комментарий не
    читался вовсе. Такие документы трогать не станем, чтобы не переписать чужие
    статусы своим «не нашёл».
    """
    итог = Итог()
    по_дню, по_смене, по_источнику, по_номеру = await _наши_смены(session, company_id)

    условие = "AND details->'Метка' IS NOT NULL" if только_свежие else ""
    документы = (await session.execute(text(f"""
        SELECT id, doc_type, number, left(date, 10) AS день, amount,
               warehouse_code,
               details->'Метка'->>'Канал'   AS канал,
               details->'Метка'->>'Станция' AS станция_метки,
               details->'Метка'->>'Ключ'    AS ключ,
               details->'Метка'->>'Источник' AS источник,
               details->'Метка'->>'НомерСмены' AS номер_смены
          FROM accounting_docs
         WHERE company_id = :c {условие}
    """), {"c": str(company_id)})).mappings().all()

    for д in документы:
        итог.рассмотрено += 1
        станция = str(д["станция_метки"] or д["warehouse_code"] or "").strip()
        канал = str(д["канал"] or "")
        entry_id: uuid.UUID | None = None
        метод = ""
        причина = ""

        # Первым — наш собственный канал: UUID источника ведёт ровно на нашу
        # запись. На исторических документах он не совпадёт (их заводил канал
        # ЦБ ссылками своей базы), но как только пойдут наши пакеты, связь
        # станет подокументной сама собой.
        if д["источник"] and д["источник"] in по_источнику:
            entry_id = по_источнику[str(д["источник"])]
            метод = "по UUID"
        elif д["номер_смены"] and д["номер_смены"] in по_номеру:
            # Составной номер смены из префикса комментария: у прежнего канала
            # ссылки чужие, а номер общий — по нему документ и находит свою смену.
            entry_id = по_номеру[str(д["номер_смены"])]
            метод = "номер смены"
        elif канал == "СМЕНА" and станция and д["ключ"]:
            entry_id = по_смене.get((станция, str(д["ключ"])))
            метод = "метка смены"
            причина = "" if entry_id else f"станции {станция} нет в нашем контуре"
        elif канал == "ЦБ" and станция and д["день"]:
            смены_дня = по_дню.get((станция, str(д["день"])), [])
            # Канал ЦБ собирал документы на день. Если смен в этом дне несколько,
            # однозначной связи нет — привязываем к первой и говорим об этом.
            entry_id = смены_дня[0] if смены_дня else None
            метод = "канал ЦБ" + (" (смен в дне несколько)" if len(смены_дня) > 1 else "")
            причина = "" if entry_id else f"станции {станция} нет в нашем контуре"
        elif канал == "ТТН":
            причина = "приёмка топлива: своего документа у нас нет"
        elif канал == "ВЫПУСКБЛЮД":
            причина = "выпуск блюда: нашей записи по этой ссылке нет"
        else:
            причина = (
                f"метка «{канал}»: связывать нечем" if канал else "метки канала нет"
            )

        if entry_id is None:
            итог.без_связи += 1
            итог.причины[причина] = итог.причины.get(причина, 0) + 1
            await session.execute(text("""
                UPDATE accounting_docs
                   SET match_status = 'unmatched', matched_entry_id = NULL,
                       match_details = cast(:д AS jsonb)
                 WHERE id = :id
            """), {"id": str(д["id"]),
                   "д": _json({"method": метод or "метка", "reason": причина})})
            continue

        # Выручку сравниваем только там, где документ и правда наш. Топливный
        # ОРП привязан к той же смене, но его сумма к нашей сопутке отношения
        # не имеет — сравнение дало бы расхождение в сотни тысяч на ровном месте.
        расхождение = None
        if д["doc_type"] == РОЗНИЦА_1С and метод.startswith(
                ("по UUID", "канал ЦБ", "номер смены")):
            наше = await _наша_выручка(session, company_id, entry_id)
            if наше is not None:
                разница = round(float(д["amount"] or 0) - наше, 2)
                if abs(разница) >= ПОРОГ:
                    расхождение = разница

        статус = "discrepancy" if расхождение is not None else "matched"
        итог.связано += 1
        итог.по_методам[метод] = итог.по_методам.get(метод, 0) + 1
        if расхождение is not None:
            итог.расхождений += 1

        await session.execute(text("""
            UPDATE accounting_docs
               SET match_status = :ст, matched_entry_id = :entry,
                   discrepancy_status = :расх,
                   match_details = cast(:д AS jsonb)
             WHERE id = :id
        """), {
            "id": str(д["id"]), "ст": статус, "entry": str(entry_id),
            "расх": "material" if расхождение is not None else "none",
            "д": _json({
                "method": метод,
                "station": станция,
                "shift": д["ключ"],
                "amountDiff": расхождение,
                "contour": "топливо" if метод == "метка смены" else "сопутка",
            }),
        })

    return итог


def _json(значение: dict) -> str:
    import json

    return json.dumps(значение, ensure_ascii=False)
