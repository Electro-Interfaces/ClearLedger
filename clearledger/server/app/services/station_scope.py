"""Что считается парком ЭЗС — одно определение на все экраны.

ЗАЧЕМ. На трёх экранах пространства станций оказалось три разных числа, и все
три были «правильные»: 619 в «Объектах» (все нетестовые объекты, включая офис и
склады), 607 в его же счётчике ЭЗС (только тип `ev_charging`), 612 в
«Мониторинге» (`ev_charging` + `ezs`) и 525 в «Обзоре» (без выведенных из
эксплуатации). Человек видит одну и ту же базу и разные цифры — и правильно
спрашивает, где правда (замечание МАГа 20.09.2026).

Правда в том, что вопросы разные, а слова одинаковые. Поэтому здесь заведены
ДВА явных понятия, и каждый экран обязан называть, какое из них показывает:

- **реестр** (`реестр()`) — все ЭЗС компании, кроме тестовых. Сюда входят и
  выведенные из эксплуатации: они были, по ним есть история сессий и договоры;
- **сеть** (`в_сети()`) — то, что сегодня должно работать: реестр минус
  выведенные из эксплуатации. База для денежных разрезов и продаж;
- **наш парк** (`обслуживаем()`) — сеть минус партнёрские станции. База для
  ЭКСПЛУАТАЦИИ: станции СНК мы не обслуживаем, и «молчит 16 дней», «никем не
  взята», «недобираем» по чужой станции — не наша работа и не наш убыток
  (решение МАГа 20.09.2026). Партнёрские остаются в продажах и деньгах: сессии
  по ним идут через нас.

Тип объекта: и `ev_charging`, и `ezs`. Второй остался от ранней загрузки (пять
объектов на пилоте) и означает ровно то же самое — считать его отдельно значит
терять пять станций на одних экранах и находить на других. Данные надо свести к
одному типу, но до тех пор оба учитываются везде одинаково.
"""
from __future__ import annotations

from typing import Any

from sqlalchemy.sql.elements import ColumnElement

from app.models import ServiceLocation

# Типы объектов, которые считаются зарядной станцией.
ВИДЫ_СТАНЦИЙ: tuple[str, ...] = ("ev_charging", "ezs")

# Состояние, означающее, что станции в сети больше нет.
ВЫВЕДЕНА = "decommissioned"


def реестр() -> list[ColumnElement[bool]]:
    """Условия «это ЭЗС компании, не тестовая». Выведенные входят."""
    return [
        ServiceLocation.type.in_(ВИДЫ_СТАНЦИЙ),
        ServiceLocation.is_test.is_(False),
    ]


def в_сети() -> list[ColumnElement[bool]]:
    """Условия «станция должна работать сегодня»: реестр минус выведенные."""
    return [
        *реестр(),
        ServiceLocation.operational_status.is_distinct_from(ВЫВЕДЕНА),
    ]


def обслуживаем(owner_raw: str | None) -> bool:
    """Наша ли это станция по обслуживанию.

    Канон владельца один — `station_owner.owner_canon`; здесь только правило
    эксплуатации: партнёрское железо в её списки не попадает. Владелец не
    распознан — считаем своим: пропустить свою станцию хуже, чем показать
    лишнюю, а мусор в графе владельца лечится данными.
    """
    from app.services.station_owner import owner_canon

    return owner_canon(owner_raw)[1] != "partner"


def кусок_sql(alias: str = "sl", scope: str = "network") -> str:
    """То же условие для запросов на сыром SQL (`overview_service` и прочие).

    `scope`: `network` — то, что должно работать; `registry` — весь реестр.
    """
    общее = (f"{alias}.type in ('ev_charging', 'ezs') "
             f"and coalesce({alias}.is_test, false) = false")
    if scope == "registry":
        return общее
    return f"{общее} and coalesce({alias}.operational_status, '') <> '{ВЫВЕДЕНА}'"


def подпись(scope: str = "network") -> dict[str, Any]:
    """Чем считали — рядом с числом. Экран обязан это показывать.

    Без подписи два верных числа выглядят как ошибка одного из экранов, и
    доверие теряется к обоим.
    """
    if scope == "registry":
        return {
            "scope": "registry",
            "label": "ЭЗС в реестре",
            "note": "все станции компании, кроме тестовых; выведенные из "
                    "эксплуатации включены",
        }
    if scope == "operated":
        return {
            "scope": "operated",
            "label": "Наши ЭЗС",
            "note": "станции, которые обслуживаем сами: без тестовых, без "
                    "выведенных из эксплуатации и без партнёрских",
        }
    return {
        "scope": "network",
        "label": "ЭЗС в сети",
        "note": "станции, которые должны работать: без тестовых и без "
                "выведенных из эксплуатации",
    }
