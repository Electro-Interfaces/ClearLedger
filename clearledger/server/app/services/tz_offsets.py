def offset_for(region_name: str | None) -> int:
    """Смещение региона от МСК (часов). Неизвестный/пустой → 0 (МСК)."""
    return _OFFSET_BY_SUBJECT.get(normalize_subject(region_name), 0)


async def backfill_region_offsets(db: AsyncSession, company_id=None) -> int:
    """Проставить `regions.msk_offset` по имени/federal_subject. Идемпотентно.

    Возвращает число обновлённых строк. Неизвестные субъекты → 0 (МСК)."""
    q = "SELECT id, name, federal_subject FROM regions"
    params: dict = {}
    if company_id is not None:
        q += " WHERE company_id = :cid"
        params["cid"] = str(company_id)
    rows = (await db.execute(text(q), params)).all()
    updated = 0
    for r in rows:
        off = offset_for(r.federal_subject or r.name)
        await db.execute(
            text("UPDATE regions SET msk_offset = :o WHERE id = :id"),
            {"o": off, "id": r.id})
        updated += 1
    await db.commit()
    return updated


def shifted_started_at(started_at, offset_expr, tz: str):
    """Timestamp сессии с учётом режима tz.

    tz='local' → `started_at + COALESCE(offset, 0) часов` (МСК→местное);
    иначе → `started_at` без изменений (МСК). `offset_expr` — колонка/выражение
    `regions.msk_offset` (после join региона)."""
    if tz != "local":
        return started_at
    return started_at + func.make_interval(0, 0, 0, 0, func.coalesce(offset_expr, 0))
