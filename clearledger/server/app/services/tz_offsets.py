"""Часовые пояса станций ЭЗС — смещение региона от Москвы.

Сессии `charge_sessions.started_at` хранятся в МСК (CPO РусГидро отдаёт по
Москве). Для анализа «по местному времени» час/день сдвигаются на смещение
региона станции: `local = started_at + msk_offset часов`.

Россия с 2014 — фиксированные пояса без перехода на летнее время, поэтому
смещение задаётся статической картой «субъект → часы от МСК». Значение
записывается в `regions.msk_offset` (backfill по нормализованному имени);
неизвестные/без региона → 0 = остаются в МСК.
"""
from __future__ import annotations

import re

from sqlalchemy import func, text
from sqlalchemy.ext.asyncio import AsyncSession

# Субъект РФ (нормализованное ядро имени) → смещение от Москвы, часов.
# Ядро = имя без слов «область/край/республика/…» (см. normalize_subject).
_OFFSET_BY_SUBJECT: dict[str, int] = {}


def _fill(offset: int, *subjects: str) -> None:
    for s in subjects:
        _OFFSET_BY_SUBJECT[normalize_subject(s)] = offset


def normalize_subject(name: str | None) -> str:
    """Ядро имени субъекта: нижний регистр, ё→е, без типовых слов и пунктуации.

    «Респ Хакасия» / «Республика Хакасия» → «хакасия»; «Смоленская область» /
    «Смоленская обл» / «Смоленская» → «смоленская»; «Еврейская автономная
    область» → «еврейская»."""
    if not name:
        return ""
    s = name.lower().replace("ё", "е")
    s = re.sub(r"[^\w\s-]", " ", s)                          # пунктуация → пробел
    # типовые слова-маркеры субъекта (как отдельные токены)
    s = re.sub(r"\b(область|обл|край|краю|республика|респ|автономн\w*|"
               r"округ|округа|ао|город|гор|г)\b", " ", s)
    s = re.sub(r"[-\s]+", " ", s).strip()
    return s


