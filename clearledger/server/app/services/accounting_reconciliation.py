"""Сквозная сверка слоёв: факт станции → пакет → бухгалтерия.

Вопрос, на который отвечает эта сверка, звучит просто: цифра в 1С отличается от
того, что продали на станции, — почему? Ответов ровно два, и различить их важнее,
чем найти саму разницу:

  L2 → L3   разницу делают наши правки. Она обязана сойтись с суммой правок
            до копейки: остаток означает, что где-то потеряли деньги молча.
  L3 → L4   разницы быть не должно вовсе. Она означает, что 1С приняла не то,
            что мы отправили, — и это уже поломка канала, а не решение человека.

Слои (`app/GLOSSARY.md`): L2 CLEAN — факт станции; L3 EXPORT — что отправили;
L4 1C_REF — что реально легло в БП. Здесь L4 читается из ответа приёмника: он
возвращает компоненты со ссылками на созданные документы и признаком проведения.

Канон корректировок: `docs/Корректировки_ОРП_перед_выгрузкой.md`.
"""
from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from typing import Any

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

# Копейка: ниже неё расхождение — округление, а не потеря.
ПОРОГ = 0.005

# Главная цифра смены — розница: она идёт в выручку и в НДС. У нас вид зовётся
# по-своему, в бухгалтерии — по-своему; сравнивать общие итоги смысла нет,
# потому что оприходование и списание сопоставляются иначе.
НАША_РОЗНИЦА = "retail_sale_sidegoods"
РОЗНИЦА_1С = "ОРП"


@dataclass
class СостояниеСлоя:
    """Один слой: сколько документов и на какую сумму."""

    есть: bool = False
    документов: int = 0
    сумма: float = 0.0
    подробности: dict[str, float] = field(default_factory=dict)
    # Откуда знаем: ответ приёмника («канал») или реестр боевой БП («реестр»).
    # Разница принципиальна — приёмник отвечает про наши документы, реестр
    # показывает всё, что в этот день легло на склад, включая чужое.
    источник: str = ""
    примечание: str = ""


@dataclass
class СверкаСмены:
    """Три слоя одной смены и объяснение разниц между ними."""

    shift_key: str
    факт: СостояниеСлоя
    отправлено: СостояниеСлоя
    в_бухгалтерии: СостояниеСлоя
    правок: int = 0
    сумма_правок: float = 0.0
    выводы: list[dict] = field(default_factory=list)

    @property
    def сошлось(self) -> bool:
        return all(в["ok"] for в in self.выводы)


def сумма_документов(документы: list[dict]) -> tuple[int, float, dict[str, float]]:
    """Итог по документам пакета: сколько их и на сколько.

    Считаем по строкам, а не по полю «СуммаДокумента»: у части видов его нет
    вовсе, и итог молча выходил бы нулевым.
    """
    всего = 0.0
    по_видам: dict[str, float] = {}
    for д in документы:
        вид = str(д.get("Тип") or "?")
        сумма = 0.0
        for т in (д.get("Товары") or []):
            try:
                сумма += float(т.get("Сумма") or 0)
            except (TypeError, ValueError):
                continue
        всего += сумма
        по_видам[вид] = round(по_видам.get(вид, 0.0) + сумма, 2)
    return len(документы), round(всего, 2), по_видам


async def сверить_смену(
    session: AsyncSession, company_id: uuid.UUID, shift_key: str,
) -> СверкаСмены:
    """Собрать три слоя и объяснить разницы между ними."""
    from app.services.accounting_adjustment import наложить, список_корректировок
    from app.services.bp_export import BpPackageEmitter

    факт = СостояниеСлоя()
    отправлено = СостояниеСлоя()
    в_бухгалтерии = СостояниеСлоя()

    emitter = BpPackageEmitter(session, company_id)
    оригинал: dict | None = None
    try:
        оригинал = await emitter.build_shift_package(shift_key)
    except Exception as e:
        факт.примечание = f"Факт смены не собрался: {e}"
    if оригинал is not None:
        n, s, по_видам = сумма_документов(оригинал.get("Документы") or [])
        факт = СостояниеСлоя(есть=True, документов=n, сумма=s, подробности=по_видам)

    правки = await список_корректировок(session, company_id, shift_key)
    сумма_правок = round(sum(п.amount_delta for п in правки), 2)

    # L3: что реально ушло. Берём последнюю ревизию пакета этой смены.
    пакет = (await session.execute(text("""
        SELECT payload, status, revision, content_hash, acked_at, component_result,
               error_code, error_detail
          FROM export_packets
         WHERE company_id = :c
           AND payload->'Смена'->>'Смена' = :s
         ORDER BY revision DESC, created_at DESC
         LIMIT 1
    """), {"c": str(company_id), "s": shift_key})).mappings().first()

    if пакет is None:
        # Пакета нет — покажем, каким он был бы: это ответ на вопрос «что уйдёт».
        if оригинал is not None:
            итог = наложить(оригинал, правки)
            n, s, по_видам = сумма_документов(итог.packet.get("Документы") or [])
            отправлено = СостояниеСлоя(
                есть=False, документов=n, сумма=s, подробности=по_видам,
                примечание="Пакет ещё не поставлен в очередь — показано, каким он соберётся",
            )
    else:
        документы = (пакет["payload"] or {}).get("Документы") or []
        n, s, по_видам = сумма_документов(документы)
        отправлено = СостояниеСлоя(
            есть=True, документов=n, сумма=s, подробности=по_видам,
            примечание=f"ревизия {пакет['revision']}, статус {пакет['status']}",
        )
        компоненты = пакет["component_result"] or []
        if пакет["acked_at"] and компоненты:
            принято = [к for к in компоненты if str(k_(к, "Результат")) == "accepted"]
            проведено = [к for к in принято if k_(к, "Проведен") is True]
            в_бухгалтерии = СостояниеСлоя(
                есть=True, документов=len(принято), сумма=s, источник="канал",
                примечание=(
                    f"принято {len(принято)} из {len(компоненты)}"
                    + (f", проведено {len(проведено)}" if проведено else ", не проведены")
                ),
            )
        elif пакет["error_code"]:
            в_бухгалтерии.примечание = (
                f"Отказ приёмника: {пакет['error_code']} — {пакет['error_detail'] or ''}"
            )
        else:
            в_бухгалтерии.примечание = "Ответа от 1С ещё не было"

    # Ответ приёмника — не единственный свидетель. Пока канал не открыт (а он
    # ждёт согласования cutover), документы в БП всё равно есть: их кладёт
    # бухгалтер расширением. Реестр 1С отвечает на тот же вопрос — что реально
    # лежит в бухгалтерии за этот день на этом складе.
    if not в_бухгалтерии.есть:
        смена = ((пакет["payload"] if пакет else оригинал) or {}).get("Смена") or {}
        документы_пакета = ((пакет["payload"] if пакет else оригинал) or {}).get(
            "Документы") or []
        из_реестра = await _из_реестра_1с(
            session, company_id,
            станция=str(смена.get("КодАЗС") or ""),
            номер_смены=str(смена.get("НомерСменыВнутр") or ""),
            день=str(смена.get("Закрытие") or смена.get("Открытие") or "")[:10],
            источники=[str(д.get("ИсточникUUID") or "") for д in документы_пакета],
        )
        if из_реестра is not None:
            прежнее = в_бухгалтерии.примечание
            в_бухгалтерии = из_реестра
            if прежнее:
                в_бухгалтерии.примечание = f"{прежнее}. {в_бухгалтерии.примечание}"

    сверка = СверкаСмены(
        shift_key=shift_key, факт=факт, отправлено=отправлено,
        в_бухгалтерии=в_бухгалтерии, правок=len(правки), сумма_правок=сумма_правок,
    )
    сверка.выводы = _выводы(сверка)
    return сверка


async def _из_реестра_1с(
    session: AsyncSession, company_id: uuid.UUID, станция: str,
    номер_смены: str, день: str, источники: list[str] | None = None,
) -> СостояниеСлоя | None:
    """Что лежит в боевой БП по этой смене — и насколько точно мы это знаем.

    Три пути, от точного к приблизительному, и каждый честно называет себя:

      «наши»    — по UUID источника из метки «TL|ЦБ|<пакет>|<UUID>». Это ровно
                  наши документы, поэтому видно и сколько не доехало.
      «канал ЦБ»— по станции и дню среди документов с меткой «TL|ЦБ». Сопутка,
                  которую доставил прежний канал: она на день, а не на смену.
      «метка»   — по номеру смены из метки «TL|СМЕНА|…». Так помечает документы
                  топливный канал STS: та же смена, но чужой контур.
      «реестр»  — по станции и дню. Приблизительно: в кучу попадает всё, что
                  легло на станцию в этот день, включая соседние смены.

    Оговорка про дату: сопутка датируется закрытием смены, топливо — открытием.
    """
    if not станция:
        return None

    свои = [и for и in (источники or []) if и]
    if свои:
        строки = (await session.execute(text("""
            SELECT doc_type, count(*) AS n,
                   coalesce(sum(amount), 0) AS сумма,
                   count(*) FILTER (WHERE status_1c = 'Проведён') AS проведено
              FROM accounting_docs
             WHERE company_id = :c
               AND details->'Метка'->>'Канал' = 'ЦБ'
               AND details->'Метка'->>'Источник' = ANY(:ист)
             GROUP BY doc_type
        """), {"c": str(company_id), "ист": свои})).mappings().all()
        if строки:
            всего = sum(int(р["n"]) for р in строки)
            проведено = sum(int(р["проведено"]) for р in строки)
            не_доехало = len(свои) - всего
            return СостояниеСлоя(
                есть=True, документов=всего, источник="наши",
                сумма=round(sum(float(р["сумма"]) for р in строки), 2),
                подробности={str(р["doc_type"]): round(float(р["сумма"]), 2)
                             for р in строки},
                примечание=(
                    f"в 1С нашлись по UUID: {всего} из {len(свои)}, "
                    f"проведено {проведено}"
                    + (f", не доехало {не_доехало}" if не_доехало > 0 else "")
                ),
            )

    if день:
        канал_цб = (await session.execute(text("""
            SELECT doc_type, count(*) AS n,
                   coalesce(sum(amount), 0) AS сумма,
                   count(*) FILTER (WHERE status_1c = 'Проведён') AS проведено
              FROM accounting_docs
             WHERE company_id = :c
               AND details->'Метка'->>'Канал' = 'ЦБ'
               AND warehouse_code = :ст AND left(date, 10) = :d
             GROUP BY doc_type
        """), {"c": str(company_id), "ст": станция, "d": день})).mappings().all()
        if канал_цб:
            всего = sum(int(р["n"]) for р in канал_цб)
            проведено = sum(int(р["проведено"]) for р in канал_цб)
            return СостояниеСлоя(
                есть=True, документов=всего, источник="канал ЦБ",
                сумма=round(sum(float(р["сумма"]) for р in канал_цб), 2),
                подробности={str(р["doc_type"]): round(float(р["сумма"]), 2)
                             for р in канал_цб},
                примечание=(
                    f"сопутка за {день} в 1С есть: {всего} документ(ов), "
                    f"проведено {проведено}. Доставил прежний канал ЦБ — "
                    f"документы собраны на день, а не на смену"
                ),
            )

    if номер_смены:
        по_метке = (await session.execute(text("""
            SELECT doc_type, count(*) AS n,
                   coalesce(sum(amount), 0) AS сумма,
                   count(*) FILTER (WHERE status_1c = 'Проведён') AS проведено
              FROM accounting_docs
             WHERE company_id = :c
               AND details->'Метка'->>'Канал' = 'СМЕНА'
               AND details->'Метка'->>'Станция' = :ст
               AND details->'Метка'->>'Ключ' = :см
             GROUP BY doc_type
        """), {"c": str(company_id), "ст": станция, "см": номер_смены})).mappings().all()
        if по_метке:
            всего = sum(int(р["n"]) for р in по_метке)
            проведено = sum(int(р["проведено"]) for р in по_метке)
            return СостояниеСлоя(
                есть=True, документов=всего, источник="метка",
                сумма=round(sum(float(р["сумма"]) for р in по_метке), 2),
                подробности={str(р["doc_type"]): round(float(р["сумма"]), 2)
                             for р in по_метке},
                примечание=(
                    f"по метке смены {номер_смены} в 1С {всего} документ(ов) "
                    f"топливного канала, проведено {проведено}"
                ),
            )

    if not день:
        return None
    строки = (await session.execute(text("""
        SELECT doc_type, count(*) AS n,
               coalesce(sum(amount), 0) AS сумма,
               count(*) FILTER (WHERE status_1c = 'Проведён') AS проведено
          FROM accounting_docs
         WHERE company_id = :c AND warehouse_code = :wh AND left(date, 10) = :d
         GROUP BY doc_type
    """), {"c": str(company_id), "wh": станция, "d": день})).mappings().all()
    if not строки:
        return СостояниеСлоя(
            есть=False,
            примечание=f"В реестре 1С за {день} по станции {станция} документов нет",
        )
    всего = sum(int(р["n"]) for р in строки)
    проведено = sum(int(р["проведено"]) for р in строки)
    return СостояниеСлоя(
        есть=True, документов=всего, источник="реестр",
        сумма=round(sum(float(р["сумма"]) for р in строки), 2),
        подробности={str(р["doc_type"]): round(float(р["сумма"]), 2) for р in строки},
        примечание=(
            f"из реестра 1С за {день}: проведено {проведено} из {всего}"
            + ("" if проведено == всего else " — остальные ждут бухгалтера")
        ),
    )


def k_(компонент: Any, ключ: str) -> Any:
    return компонент.get(ключ) if isinstance(компонент, dict) else None


def _выводы(с: СверкаСмены) -> list[dict]:
    """Разницы между слоями и то, чем каждая объясняется."""
    выводы: list[dict] = []

    if not с.факт.есть:
        выводы.append({
            "Слои": "L2 → L3", "ok": False,
            "Что": "Факт смены не собрался",
            "Почему": с.факт.примечание or "нет данных станции",
        })
        return выводы

    разница = round(с.отправлено.сумма - с.факт.сумма, 2)
    остаток = round(разница - с.сумма_правок, 2)
    if abs(разница) < ПОРОГ and с.правок == 0:
        выводы.append({
            "Слои": "L2 → L3", "ok": True,
            "Что": "Отправляем ровно то, что продали",
            "Почему": "правок не было, суммы совпадают",
        })
    elif abs(остаток) < ПОРОГ:
        выводы.append({
            "Слои": "L2 → L3", "ok": True,
            "Что": f"Разница {_денежно(разница)} — это наши правки",
            "Почему": f"{с.правок} правк(и) на {_денежно(с.сумма_правок)}, сходится до копейки",
        })
    else:
        выводы.append({
            "Слои": "L2 → L3", "ok": False,
            "Что": f"Разница {_денежно(разница)} правками не объясняется",
            "Почему": (
                f"правки дают {_денежно(с.сумма_правок)}, необъяснённый остаток "
                f"{_денежно(остаток)} — где-то потеряли молча"
            ),
        })

    if not с.отправлено.есть:
        выводы.append({
            "Слои": "L3 → L4", "ok": True,
            "Что": "В бухгалтерию ещё не отправляли",
            "Почему": с.отправлено.примечание or "пакета в очереди нет",
        })
        if с.в_бухгалтерии.источник == "канал ЦБ":
            выводы.append({
                "Слои": "L3 → L4", "ok": True,
                "Что": (
                    f"Сопутка этого дня в 1С уже есть: "
                    f"{с.в_бухгалтерии.документов} документ(ов) на "
                    f"{_денежно(с.в_бухгалтерии.сумма)}"
                ),
                "Почему": (
                    с.в_бухгалтерии.примечание
                    + ". Отправлять смену второй раз не нужно — сначала решить, "
                      "чей факт считаем верным"
                ),
            })
            if (в := _розница(с)):
                выводы.append(в)
        elif с.в_бухгалтерии.источник == "наши":
            выводы.append({
                "Слои": "L3 → L4", "ok": True,
                "Что": (
                    f"Но документы этой смены в 1С уже есть: "
                    f"{с.в_бухгалтерии.документов} на {_денежно(с.в_бухгалтерии.сумма)}"
                ),
                "Почему": (
                    с.в_бухгалтерии.примечание
                    + ". Их доставил прежний канал — через расширение. "
                      "Отправлять то же самое второй раз не нужно"
                ),
            })
            if (в := _розница(с)):
                выводы.append(в)
        elif с.в_бухгалтерии.источник == "метка":
            выводы.append({
                "Слои": "L3 → L4", "ok": True,
                "Что": (
                    f"Сопутки этой смены в 1С нет; топливо за неё проведено: "
                    f"{с.в_бухгалтерии.документов} документ(ов) на "
                    f"{_денежно(с.в_бухгалтерии.сумма)}"
                ),
                "Почему": (
                    с.в_бухгалтерии.примечание
                    + ". Топливо идёт своим каналом из STS и нашего пакета не ждёт"
                ),
            })
        elif с.в_бухгалтерии.есть:
            выводы.append({
                "Слои": "L3 → L4", "ok": True,
                "Что": (
                    f"Но в 1С за этот день уже есть документов: "
                    f"{с.в_бухгалтерии.документов} на {_денежно(с.в_бухгалтерии.сумма)}"
                ),
                "Почему": (
                    с.в_бухгалтерии.примечание
                    + ". Метки нашей смены на них нет, поэтому считается вся "
                      "станция за день — с нашей суммой сходиться не обязано"
                ),
            })
        elif с.в_бухгалтерии.примечание:
            выводы.append({
                "Слои": "L3 → L4", "ok": True,
                "Что": "В 1С за этот день по станции пусто",
                "Почему": с.в_бухгалтерии.примечание,
            })
        return выводы

    if not с.в_бухгалтерии.есть:
        выводы.append({
            "Слои": "L3 → L4", "ok": False,
            "Что": "1С пакет пока не приняла",
            "Почему": с.в_бухгалтерии.примечание or "ответа не было",
        })
        return выводы

    if с.в_бухгалтерии.источник == "наши":
        # UUID источника — точная связь: это ровно наши документы этой смены.
        не_доехало = с.отправлено.документов - с.в_бухгалтерии.документов
        выводы.append({
            "Слои": "L3 → L4", "ok": не_доехало <= 0,
            "Что": (
                "В 1С лежат все документы смены"
                if не_доехало <= 0 else
                f"В 1С не хватает документов смены: {не_доехало}"
            ),
            "Почему": с.в_бухгалтерии.примечание,
        })
        if (в := _розница(с)):
            выводы.append(в)
    elif с.в_бухгалтерии.источник in ("канал ЦБ", "метка", "реестр"):
        # Реестр показывает склад за день целиком, а не приём нашего пакета:
        # считать разницу поломкой канала здесь нельзя.
        выводы.append({
            "Слои": "L3 → L4", "ok": True,
            "Что": (
                f"Наших документов в 1С не нашлось; рядом по этой смене — "
                f"{с.в_бухгалтерии.документов} документ(ов) на "
                f"{_денежно(с.в_бухгалтерии.сумма)}"
            ),
            "Почему": с.в_бухгалтерии.примечание + ". Это чужой контур: сверять "
                      "с нашим пакетом построчно нельзя",
        })
    elif с.в_бухгалтерии.документов == с.отправлено.документов:
        выводы.append({
            "Слои": "L3 → L4", "ok": True,
            "Что": "Бухгалтерия приняла всё, что отправили",
            "Почему": с.в_бухгалтерии.примечание,
        })
    else:
        потеряно = с.отправлено.документов - с.в_бухгалтерии.документов
        выводы.append({
            "Слои": "L3 → L4", "ok": False,
            "Что": f"В 1С не легло документов: {потеряно}",
            "Почему": (
                с.в_бухгалтерии.примечание
                + ". Это поломка канала, а не решение человека: отправляли одно, "
                  "приняли другое"
            ),
        })
    return выводы


def _розница(с: СверкаСмены) -> dict | None:
    """Сошлась ли выручка смены с той, что стоит в 1С.

    Это единственная пара видов, которую можно сравнить в лоб: у розницы с обеих
    сторон один смысл и одна сумма. Оприходование и списание так не сравнить —
    одна наша инвентаризация превращается в 1С в два разных документа.
    """
    наше = float(с.отправлено.подробности.get(НАША_РОЗНИЦА, 0.0))
    в_1с = float(с.в_бухгалтерии.подробности.get(РОЗНИЦА_1С, 0.0))
    if not наше and not в_1с:
        return None
    разница = round(в_1с - наше, 2)
    сошлось = abs(разница) < ПОРОГ
    return {
        "Слои": "L3 → L4", "ok": сошлось,
        "Что": (
            f"Выручка сошлась: {_денежно(наше)}" if сошлось else
            f"Выручка разошлась на {_денежно(разница)}"
        ),
        "Почему": (
            "у нас и в 1С одна и та же сумма розницы"
            if сошлось else
            f"у нас {_денежно(наше)}, в 1С {_денежно(в_1с)}"
        ),
    }


def _денежно(значение: float) -> str:
    знак = "+" if значение > 0 else ""
    return f"{знак}{значение:,.2f} ₽".replace(",", " ").replace(".", ",")
