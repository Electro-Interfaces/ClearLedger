"""Артикул сети: девять цифр, которыми товар называют люди.

Решение МАГа 30.08.2026, разбор — `edge/docs/identifikatory-tovara.html`.

Что это и чем не является:

  · UUID карточки — машинный ключ, человеку не показывается никогда;
  · **артикул** — ключ для людей и бумаги: экран станции, ценник, накладная,
    разговор по телефону, поле «Артикул» в 1С;
  · штрихкод — атрибут, их у карточки бывает шесть (по одному на вкус), а у
    330 карточек нет ни одного, поэтому ключом он быть не может.

Почему именно так:

  · **смысла в номере нет** — ни категории, ни поставщика, ни станции. Значащий
    номер однажды становится ложью: сырьё у нас уже переезжало в добавки, а
    товар может переехать между точками. Диапазон, из которого номер выдан, —
    административный факт, парсить его запрещено;
  · **только цифры** — цифровой блок кассы, телефон, 1С, выгрузки; вопрос
    путаницы 0/O и 1/I не возникает;
  · **ровно девять знаков** — длина не совпадает ни с одной сканируемой: 6 у
    наших старых внутренних обозначений, 8 у EAN-8, 12 у UPC-A, 13 у EAN-13,
    14 у ITF-14. Значит единая строка поиска отличает скан от ручного ввода по
    одной только длине;
  · **контрольный разряд GS1 mod-10** — тот же, что в EAN: ловит все одиночные
    опечатки. Он же позволяет вывести из артикула внутренний штрихкод.

Тело — восемь цифр, начинается с 10000000: артикул никогда не имеет ведущих
нулей и всегда читается одинаково.
"""
from __future__ import annotations

import uuid as _uuid

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

ДЛИНА_ТЕЛА = 8
ДЛИНА_АРТИКУЛА = 9

# Границы пулов. Центр раздаёт свои номера сам, станциям нарезает блоки.
# Значения — административные, из номера ничего не выводится.
ЦЕНТР_ОТ = 10_000_000
ЦЕНТР_ДО = 49_999_999
СТАНЦИИ_ОТ = 50_000_000
СТАНЦИИ_ДО = 99_999_999

# Размер блока станции. Хватает надолго: на 208 за месяц боевой работы завели
# 13 карточек. Блок кончается — центр нарезает следующий, дыры в нумерации
# нормальны и ни на что не влияют.
РАЗМЕР_БЛОКА = 10_000


def контрольный_разряд(тело: str) -> int:
    """Контрольная цифра GS1 mod-10: справа налево веса 3 и 1."""
    сумма = 0
    for позиция, знак in enumerate(reversed(тело)):
        сумма += int(знак) * (3 if позиция % 2 == 0 else 1)
    return (10 - сумма % 10) % 10


def собрать(номер: int) -> str:
    """Номер тела → готовый артикул из девяти цифр."""
    if not ЦЕНТР_ОТ <= номер <= СТАНЦИИ_ДО:
        raise ValueError(f"номер {номер} вне диапазона артикулов")
    тело = f"{номер:0{ДЛИНА_ТЕЛА}d}"
    return тело + str(контрольный_разряд(тело))


def разобрать(артикул: str) -> int | None:
    """Артикул → номер тела. None, если это не наш артикул.

    Проверка нужна на каждом входе, где человек вводит номер руками: опечатка
    в одной цифре обязана отсеиваться здесь, а не всплывать документом на чужой
    товар.
    """
    код = (артикул or "").strip()
    if len(код) != ДЛИНА_АРТИКУЛА or not код.isdigit():
        return None
    тело, разряд = код[:-1], int(код[-1])
    if контрольный_разряд(тело) != разряд:
        return None
    номер = int(тело)
    if not ЦЕНТР_ОТ <= номер <= СТАНЦИИ_ДО:
        return None
    return номер


def это_артикул(строка: str) -> bool:
    """Похоже ли введённое на артикул сети.

    Отличает ввод артикула от скана штрихкода в общей строке поиска. Ровно для
    этого длина и выбрана так, чтобы не совпадать ни с одной сканируемой.
    """
    return разобрать(строка) is not None


# Внутренний штрихкод для позиций без кода производителя (общепит, фасовка).
#
# GS1 отдал под товар ограниченного обращения префиксы 20–29: такой код
# действует только внутри нашего контура, торговым партнёрам не отдаётся и
# GTIN не является. Берём 240 — он свободен, а 241–249 остаются про запас
# (весовому товару нужен свой префикс со своей раскладкой, смешивать нельзя:
# касса однажды разберёт штучный код как весовой и спишет «вес»).
ПРЕФИКС_ВНУТРЕННЕГО_ШК = "240"


def внутренний_штрихкод(артикул: str) -> str:
    """Артикул → внутренний EAN-13. Артикул читается из кода как есть."""
    if разобрать(артикул) is None:
        raise ValueError(f"«{артикул}» не артикул сети")
    тело = ПРЕФИКС_ВНУТРЕННЕГО_ШК + артикул          # 3 + 9 = 12 знаков
    return тело + str(контрольный_разряд(тело))


def артикул_из_штрихкода(штрихкод: str) -> str | None:
    """Обратный разбор: наш ли это внутренний код и чей."""
    код = (штрихкод or "").strip()
    if len(код) != 13 or not код.isdigit():
        return None
    if not код.startswith(ПРЕФИКС_ВНУТРЕННЕГО_ШК):
        return None
    if контрольный_разряд(код[:-1]) != int(код[-1]):
        return None
    артикул = код[3:12]
    return артикул if разобрать(артикул) is not None else None


def чужой_ограниченного_обращения(штрихкод: str) -> bool:
    """Штрихкод с упаковки из диапазона 20–29 — не наш и к карточке не крепится.

    Это код ограниченного обращения чужого контура: шелфовый код другой сети,
    код чужих весов, внутренний номер поставщика. Глобально он не уникален и
    завтра прилетит на другом товаре. Наши собственные коды (префикс 240)
    из этого правила исключены — они рождаются здесь и в приёмку не приходят.
    """
    код = (штрихкод or "").strip()
    if len(код) < 8 or not код.isdigit():
        return False
    if код.startswith(ПРЕФИКС_ВНУТРЕННЕГО_ШК) and артикул_из_штрихкода(код):
        return False
    return код[0] == "2"


# ────────────────────────────────────────────────────────────────────────────
#  Выдача номеров
# ────────────────────────────────────────────────────────────────────────────
#
# Два источника, и они не пересекаются:
#
#   · центр берёт номер из своего счётчика — карточка сети рождается здесь;
#   · станция чеканит номер внутри блока, который центр ей нарезал заранее.
#
# Блок нужен ровно для офлайна: связи нет, а накладная в руках, и карточку надо
# завести сейчас. Приём известен как Hi/Lo — сервер отдаёт «high», клиент сам
# раздаёт «low» внутри. Плата за него — дыры в нумерации; они безвредны,
# сплошной нумерации артикулов от нас никто не требует.


async def выдать_центральный(db: AsyncSession) -> str:
    """Следующий артикул центрального пула.

    Счётчик берётся `FOR UPDATE`: два одновременных заведения карточки обязаны
    получить разные номера. Именно этой блокировки не хватает выдаче кодов
    кассы на станции — там линейный перебор без транзакции, и два вызова
    возвращают один номер.
    """
    строка = (await db.execute(text("""
        SELECT next_value FROM edge_sku_counter WHERE scope = 'center' FOR UPDATE
    """))).first()
    if строка is None:
        raise RuntimeError("счётчик артикулов не заведён: не применена миграция")
    номер = int(строка.next_value)
    if номер > ЦЕНТР_ДО:
        raise RuntimeError(
            f"центральный пул артикулов исчерпан (дошли до {номер}, потолок {ЦЕНТР_ДО})")
    await db.execute(text("""
        UPDATE edge_sku_counter SET next_value = :n WHERE scope = 'center'
    """), {"n": номер + 1})
    return собрать(номер)


def границы_блока(последний_край: int | None) -> tuple[int, int]:
    """Границы следующего блока — от конца последнего выданного.

    Считается по ВСЕМ станциям сразу, а не по одной: диапазон общий, и
    пересечение блоков двух АЗС дало бы один артикул у разных товаров.
    """
    начало = int(последний_край) + 1 if последний_край else СТАНЦИИ_ОТ
    конец = начало + РАЗМЕР_БЛОКА - 1
    if конец > СТАНЦИИ_ДО:
        raise RuntimeError("станционный пул артикулов исчерпан")
    return начало, конец


async def нарезать_блок(db: AsyncSession, company_id, station_id: int) -> dict:
    """Выдать станции очередной блок номеров."""
    последний = (await db.execute(text("""
        SELECT max(block_to) AS край FROM edge_sku_block
    """))).scalar()
    начало, конец = границы_блока(последний)

    ident = _uuid.uuid4()
    await db.execute(text("""
        INSERT INTO edge_sku_block
               (id, company_id, station_id, block_from, block_to, next_value)
        VALUES (:id, :cid, :st, :ot, :do, :ot)
    """), {"id": ident, "cid": company_id, "st": station_id, "ot": начало, "do": конец})
    return {"block_id": str(ident), "from": начало, "to": конец,
            "from_sku": собрать(начало), "to_sku": собрать(конец),
            "size": РАЗМЕР_БЛОКА}


async def блоки_станции(db: AsyncSession, company_id, station_id: int) -> list[dict]:
    """Открытые блоки станции: что и когда ей нарезано.

    ⚠ `next_value` здесь — начало диапазона, а не курсор: номера внутри блока
    чеканит станция у себя, и сколько их осталось, знает только она. Центр
    узнаёт остаток из телеметрии (`sku_left`), поэтому решение «пора резать
    следующий» принимает `обеспечить_блок`, а не эта выборка.
    """
    строки = (await db.execute(text("""
        SELECT id::text AS id, block_from, block_to, next_value, issued_at
        FROM edge_sku_block
        WHERE company_id = :cid AND station_id = :st AND exhausted_at IS NULL
        ORDER BY block_from
    """), {"cid": company_id, "st": station_id})).mappings().all()
    return [{
        "block_id": r["id"],
        "from": int(r["block_from"]), "to": int(r["block_to"]),
        "size": int(r["block_to"]) - int(r["block_from"]) + 1,
        "issued_at": r["issued_at"].isoformat() if r["issued_at"] else None,
    } for r in строки]


# Ниже какого запаса номеров центр нарезает станции следующий блок.
# Станция предупреждает заранее — пока связь есть, а не когда номер понадобился.
ПОРОГ_ЗАПАСА = 0.2


async def обеспечить_блок(db: AsyncSession, company_id, station_id: int,
                          осталось: int | None) -> dict | None:
    """Нарезать станции блок, если номера подходят к концу. Иначе None.

    Расход внутри блока знает только станция — центр видит лишь то, что она
    сообщает телеметрией. Поэтому решение принимается по остатку из heartbeat,
    а не по нашей записи: `next_value` в `edge_sku_block` стоит на начале
    диапазона всегда, курсор двигается на той стороне.

    Гонка «нарезали, а станция ещё не получила» закрыта тем, что номера
    неподтверждённых заданий считаются уже выданными: иначе за минуту доставки
    центр нарезал бы блок на каждом такте телеметрии.

    Молчание агента (`осталось is None` — старая версия, про блоки не знает)
    впрок не режем: пустых блоков в нумерации и так хватит.
    """
    from app.models import EdgeDownlink            # локально: models тянет пол-приложения
    from sqlalchemy import select

    выдано_всего = (await db.execute(text("""
        SELECT count(*) FROM edge_sku_block
        WHERE company_id = :cid AND station_id = :st
    """), {"cid": company_id, "st": station_id})).scalar() or 0

    if выдано_всего == 0:
        return await нарезать_блок(db, company_id, station_id)
    if осталось is None:
        return None

    в_пути = 0
    задания = (await db.execute(select(EdgeDownlink).where(
        EdgeDownlink.company_id == company_id,
        EdgeDownlink.station_id == station_id,
        EdgeDownlink.kind == "sku_block",
        EdgeDownlink.acked_at.is_(None),
        EdgeDownlink.cancelled_at.is_(None),
    ))).scalars().all()
    for задание in задания:
        груз = задание.payload or {}
        try:
            в_пути += int(груз["to"]) - int(груз["from"]) + 1
        except (KeyError, TypeError, ValueError):
            continue

    if int(осталось) + в_пути > РАЗМЕР_БЛОКА * ПОРОГ_ЗАПАСА:
        return None
    return await нарезать_блок(db, company_id, station_id)
