"""Надзор: за кем человек смотрит и что вправе с этим сделать.

Раздел «Компания» до сих пор был информационным: он показывал всю видимую
работу и не давал ничего с ней сделать. Руководитель заходил, видел затык — и
шёл писать в чат. Это ровно то состояние, при котором раздел не нужен.

Здесь заведено недостающее понятие: **охват надзора** — круг людей, за работу
которых человек отвечает. Он берётся из штатной структуры, а не из отдельного
списка: структура уже описана (`org_departments` — дерево с руководителями), она
и есть правда о том, кто за кого спрашивает. Отдельный список разошёлся бы с ней
на первой же перестановке.

Три состояния охвата, и они не равны друг другу:

* **вся компания** — администратор пространства. Секретарь и делопроизводитель
  получают то же самое, назначаясь администратором: их работа и есть «видеть,
  где что висит»;
* **своё подразделение и всё, что ниже** — руководитель. Дерево обходится вниз
  целиком: начальник управления отвечает и за отделы внутри него;
* **пусто** — рядовой сотрудник. Раздела «Компания» он не видит вовсе, и это не
  сокрытие информации, а отсутствие работы: смотреть за чужой работой не входит
  в его обязанности, а окно, через которое ничего нельзя сделать, только мешает.

Полномочия надзирающего в его охвате — полные: переназначить, подтолкнуть,
перенести срок, закрыть. Решение принято сознательно (МАГ, 30.08.2026): раздел
существует затем, чтобы расшивать затыки, а расшить затык, ничего не меняя,
нельзя. Цена решения — след обязан называть, В КАКОМ КАЧЕСТВЕ действие сделано:
«срок перенёс руководитель» и «срок перенёс автор» это разные события, и
исполнительская дисциплина, не различающая их, врёт.
"""
from __future__ import annotations

import uuid
from dataclasses import dataclass, field

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Department, User, UserCompany


@dataclass(frozen=True)
class Охват:
    """За кем человек смотрит.

    `вся_компания` и `люди` не складываются: первое означает «все», второе —
    перечисление. Проверять надо `вся_компания or user_id in люди`, и для этого
    есть `входит()`.
    """

    вся_компания: bool = False
    #: Идентификаторы людей в охвате. Пусто при `вся_компания`.
    люди: frozenset[uuid.UUID] = field(default_factory=frozenset)
    #: Подразделения, которыми человек руководит (своё и всё, что ниже).
    подразделения: frozenset[uuid.UUID] = field(default_factory=frozenset)

    @property
    def есть(self) -> bool:
        """Смотрит ли человек хоть за кем-нибудь."""
        return self.вся_компания or bool(self.люди)

    def входит(self, user_id: uuid.UUID | None) -> bool:
        if user_id is None:
            # Работа без исполнителя — забота того, кто вообще надзирает: она и
            # висит именно потому, что её никто не взял.
            return self.есть
        return self.вся_компания or user_id in self.люди


async def _дерево_вниз(db: AsyncSession, cid: uuid.UUID,
                       корни: set[uuid.UUID]) -> set[uuid.UUID]:
    """Подразделения-потомки вместе с корнями.

    Обход в ширину по уровням, а не рекурсивный запрос: дерево штатной
    структуры мелкое (единицы уровней), а `WITH RECURSIVE` пришлось бы держать
    в двух диалектах ради тестов на sqlite.
    """
    все = set(корни)
    слой = set(корни)
    while слой:
        дети = set((await db.execute(select(Department.id).where(
            Department.company_id == cid,
            Department.parent_id.in_(слой)))).scalars().all())
        слой = дети - все
        все |= слой
    return все


async def охват(db: AsyncSession, cid: uuid.UUID, user: User) -> Охват:
    """Круг людей, за работу которых человек отвечает.

    Считается по штатной структуре и роли в пространстве. Ничего не кэшируется:
    структура меняется редко, а устаревший охват — это либо чужая работа на
    экране, либо своя, которой не видно.
    """
    if user.is_superadmin:
        return Охват(вся_компания=True)

    членство = await db.get(UserCompany, (user.id, cid))
    if членство is None:
        return Охват()
    if членство.role == "admin":
        return Охват(вся_компания=True)

    свои = set((await db.execute(select(Department.id).where(
        Department.company_id == cid,
        Department.head_user_id == user.id))).scalars().all())
    if not свои:
        return Охват()

    ветка = await _дерево_вниз(db, cid, свои)
    люди = set((await db.execute(select(UserCompany.user_id).where(
        UserCompany.company_id == cid,
        UserCompany.department_id.in_(ветка)))).scalars().all())
    # Себя руководитель тоже надзирает: его собственная работа стоит в тех же
    # сводках, и вычитать её значило бы показывать отделу неполную картину.
    люди.add(user.id)
    return Охват(люди=frozenset(люди), подразделения=frozenset(ветка))


async def надзирает(db: AsyncSession, cid: uuid.UUID, user: User) -> bool:
    """Показывать ли этому человеку раздел «Компания»."""
    return (await охват(db, cid, user)).есть
