# Этап документа по номеру задачи: «3.12» → «3».
PHASE_BY_TASK = {t["key"]: t["key"].split(".")[0] for t in TASKS}
PHASE_LABELS_DOC = {p["code"]: p["label"] for p in PHASES_DOC}


def gates_by_stage() -> dict[str, list[dict[str, Any]]]:
    """Чек-лист, разложенный по стадиям воронки — источник гейтов стадии."""
    out: dict[str, list[dict[str, Any]]] = {}
    for t in TASKS:
        item = {k: v for k, v in t.items() if k != "stage"}
        item["phase"] = PHASE_BY_TASK[t["key"]]
        out.setdefault(t["stage"], []).append(item)
    return out


def checklist_meta() -> dict[str, Any]:
    """Регламент целиком — для экрана процесса и подсказок в карточке."""
    return {
        "roles": [{"code": c, "label": l} for c, l in ROLES.items()],
        "phases": [
            {**p, "tasks": [{"key": t["key"], "label": t["label"], "role": t["role"],
                             "stage": t["stage"], "required": bool(t.get("required")),
                             "auto": not t.get("manual")}
                            for t in TASKS if PHASE_BY_TASK[t["key"]] == p["code"]]}
            for p in PHASES_DOC
        ],
        "total": len(TASKS),
    }
