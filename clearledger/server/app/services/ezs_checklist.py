DEFAULT_NORM_DAYS = 90


def norm_days(stage: str) -> int:
    return STAGE_NORM_DAYS.get(stage, DEFAULT_NORM_DAYS)


def gates_by_stage() -> dict[str, list[dict[str, Any]]]:
    """Чек-лист, разложенный по стадиям воронки — источник гейтов стадии."""
    out: dict[str, list[dict[str, Any]]] = {}
    for t in TASKS:
        item = {k: v for k, v in t.items() if k != "stage"}
        item["phase"] = PHASE_BY_TASK[t["key"]]
        out.setdefault(t["stage"], []).append(item)
    return out


def checklist_meta() -> dict[str, Any]:
    """Регламент целиком — для экрана процесса и подсказок в карточке."""
    return {
        "roles": [{"code": c, "label": l} for c, l in ROLES.items()],
        "phases": [
            {**p, "tasks": [{"key": t["key"], "label": t["label"], "role": t["role"],
                             "stage": t["stage"], "required": bool(t.get("required")),
                             "auto": not t.get("manual")}
                            for t in TASKS if PHASE_BY_TASK[t["key"]] == p["code"]]}
            for p in PHASES_DOC
        ],
        "total": len(TASKS),
    }


def doc_gate_keys() -> list[dict[str, str]]:
    """Пункты чек-листа, которые закрываются документом.

    Собирается из самого чек-листа, а не пишется вторым списком: разойдясь, они
    дали бы вид, объявленный закрывающим несуществующий пункт, — и человек искал
    бы причину, почему согласованный документ гейт не двигает.
    """
    seen: dict[str, str] = {}
    for item in TASKS:
        key = item.get("doc")
        if key and key not in seen:
            seen[key] = item.get("label") or item.get("title") or key
    return [{"key": k, "label": v} for k, v in seen.items()]
