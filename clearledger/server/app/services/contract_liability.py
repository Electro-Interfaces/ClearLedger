"""Условия ответственности по договору: срок устранения, санкция, гарантия.

ЗАЧЕМ. Претензия производителю стоит ровно столько, сколько стоит ссылка в ней:
«станция не работает 19 дней» — это жалоба, «нарушен п. 7.3 договора № ПС-2024/231
(срок устранения 30 календарных дней), пеня 0,1 % от стоимости за каждый день
просрочки, на 19.09.2026 сумма составляет 47 300 ₽» — это требование. Поэтому
условия хранятся не как число, а вместе с ЦИТАТОЙ пункта, из которого взяты.

РАЗБОР ИЗ ТЕКСТА. Условия вынимаются из самого договора: человек прикладывает
файл (или вставляет текст), разбор предлагает найденное с цитатами, человек
подтверждает или правит. Полностью доверять разбору нельзя — формулировки в
договорах разные, и «30 дней» может относиться к сроку поставки, а не к
устранению. Поэтому источник у каждого условия помечен: `parsed` до
подтверждения человеком, `manual` после.

Чего разбор НЕ делает: не читает сканы без текстового слоя (OCR в системе нет) и
не угадывает пункт, если формулировка нестандартная. В обоих случаях честно
говорит «не нашёл» и оставляет ручной ввод — молча подставленное число в
претензии хуже пустого поля.
"""
from __future__ import annotations

import io
import re
import uuid
from datetime import date, datetime, timedelta
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

# ── что умеем находить ────────────────────────────────────────────────────────
# Формулировки собраны по реальным договорам поставки и сервиса ЭЗС. Каждое
# правило ищет число И единицу, потому что «в течение 30» без «дней» встречается
# в сроках оплаты и к устранению отношения не имеет.

_ЧИСЛО = r"(\d{1,3})"
_ДНИ = r"(рабочих|календарных)?\s*(?:дн|сут)"

ПРАВИЛА: list[tuple[str, str, str]] = [
    # (поле, регулярное выражение, подсказка для человека)
    ("fixDays",
     rf"устран\w*[^.]{{0,120}}?в течение\s+{_ЧИСЛО}\s*{_ДНИ}",
     "срок устранения неисправности"),
    ("fixDays",
     rf"в течение\s+{_ЧИСЛО}\s*{_ДНИ}[^.]{{0,120}}?устран",
     "срок устранения неисправности"),
    ("responseHours",
     rf"реаг\w*[^.]{{0,100}}?в течение\s+{_ЧИСЛО}\s*час",
     "срок реакции на обращение"),
    ("warrantyMonths",
     rf"гарантийный срок[^.]{{0,80}}?{_ЧИСЛО}\s*(?:месяц|мес\.)",
     "гарантийный срок"),
    ("warrantyMonths",
     rf"гаранти\w*[^.]{{0,80}}?{_ЧИСЛО}\s*(?:месяц|мес\.)",
     "гарантийный срок"),
]

# Санкция: процент за день просрочки либо фиксированная сумма за день.
ПЕНЯ_ПРОЦЕНТ = re.compile(
    r"(?:пен[ияю]|неустойк\w+|штраф\w*)[^.]{0,160}?(\d+[.,]?\d*)\s*%"
    r"[^.]{0,80}?(?:за каждый день|в день|за день)", re.IGNORECASE)
ПЕНЯ_СУММА = re.compile(
    r"(?:пен[ияю]|неустойк\w+|штраф\w*)[^.]{0,160}?(\d[\d\s]{2,})\s*(?:руб|₽)"
    r"[^.]{0,80}?(?:за каждый день|в день|за день)", re.IGNORECASE)
ПОТОЛОК = re.compile(
    r"(?:не более|не может превышать|ограничен\w*)[^.]{0,60}?(\d+[.,]?\d*)\s*%",
    re.IGNORECASE)

# Номер пункта перед найденной формулировкой: «7.3.», «п. 5.2», «5.2.1».
ПУНКТ = re.compile(r"(?:п\.\s*)?(\d{1,2}(?:\.\d{1,2}){1,3})\.?\s*$")

# Лестница эскалации по умолчанию — не из договора, а наш порядок работы:
# сколько ждём после каждой претензии, прежде чем писать следующую.
ЛЕСТНИЦА_ПО_УМОЛЧАНИЮ = [
    {"afterDays": 30, "action": "repeat_claim"},
    {"afterDays": 60, "action": "pretrial"},
    {"afterDays": 90, "action": "replace"},
]

ДЕЙСТВИЯ = {
    "repeat_claim": "повторная претензия",
    "pretrial": "досудебная претензия с требованием неустойки",
    "replace": "требование замены станции",
    "dismantle": "требование демонтажа и возврата стоимости",
    "court": "исковое заявление",
}


def извлечь_текст(имя: str, данные: bytes) -> tuple[str, str | None]:
    """Текст договора из файла. Второй элемент — причина, если текста нет."""
    низ = (имя or "").lower()
    if низ.endswith(".txt"):
        return данные.decode("utf-8", errors="replace"), None
    if низ.endswith(".docx"):
        try:
            import docx  # python-docx
        except ImportError:
            return "", "разбор .docx недоступен: библиотека не установлена"
        d = docx.Document(io.BytesIO(данные))
        куски = [p.text for p in d.paragraphs]
        for t in d.tables:
            for row in t.rows:
                куски.extend(c.text for c in row.cells)
        return "\n".join(куски), None
    if низ.endswith(".pdf"):
        try:
            from pypdf import PdfReader
        except ImportError:
            return "", "разбор .pdf недоступен: библиотека не установлена"
        читатель = PdfReader(io.BytesIO(данные))
        текст = "\n".join((стр.extract_text() or "") for стр in читатель.pages)
        if len(текст.strip()) < 200:
            # Скан без текстового слоя: распознавания в системе нет, и делать
            # вид, что разобрали, нельзя.
            return текст, ("в файле нет текстового слоя — похоже, это скан; "
                           "условия придётся ввести руками")
        return текст, None
    return "", f"формат не поддержан: {имя}"


def _пункт_перед(текст: str, позиция: int) -> str | None:
    """Номер пункта, в котором стоит найденная формулировка."""
    начало = max(0, позиция - 200)
    кусок = текст[начало:позиция]
    # Ищем последний номер вида «7.3» в начале предложения перед совпадением.
    кандидаты = re.findall(r"(?:^|\n|\s)(\d{1,2}(?:\.\d{1,2}){1,3})\.?\s", кусок)
    return кандидаты[-1] if кандидаты else None


def _цитата(текст: str, начало: int, конец: int) -> str:
    """Фраза целиком: от начала предложения до его конца, но не длиннее 400."""
    л = текст.rfind(".", max(0, начало - 300), начало)
    п = текст.find(".", конец)
    кусок = текст[(л + 1 if л >= 0 else начало):(п + 1 if п > 0 else конец)]
    кусок = re.sub(r"\s+", " ", кусок).strip()
    return кусок[:400]


def разобрать(текст: str) -> dict[str, Any]:
    """Условия, найденные в тексте договора, с цитатами и номерами пунктов."""
    найдено: dict[str, Any] = {}
    цитаты: list[dict[str, str]] = []
    норм = re.sub(r"[ \t]+", " ", текст)

    def записать(поле: str, значение: Any, m: re.Match, подсказка: str) -> None:
        if поле in найдено:
            return
        найдено[поле] = значение
        цитаты.append({
            "field": поле,
            "code": _пункт_перед(норм, m.start()) or "",
            "text": _цитата(норм, m.start(), m.end()),
            "hint": подсказка,
        })

    for поле, шаблон, подсказка in ПРАВИЛА:
        m = re.search(шаблон, норм, re.IGNORECASE | re.DOTALL)
        if not m:
            continue
        число = int(m.group(1))
        if поле == "fixDays":
            записать("fixDays", число, m, подсказка)
            # Рабочие дни — это другой календарь, и в претензии срок считается
            # по нему: 30 рабочих дней это полтора месяца, а не месяц.
            вид = (m.group(2) or "").lower()
            if вид.startswith("рабоч"):
                найдено["calendar"] = "business"
            elif вид.startswith("календ"):
                найдено["calendar"] = "calendar"
        else:
            записать(поле, число, m, подсказка)

    m = ПЕНЯ_ПРОЦЕНТ.search(норм)
    if m:
        найдено["penaltyKind"] = "per_day_pct"
        найдено["penaltyValue"] = float(m.group(1).replace(",", "."))
        цитаты.append({"field": "penaltyValue", "code": _пункт_перед(норм, m.start()) or "",
                       "text": _цитата(норм, m.start(), m.end()),
                       "hint": "неустойка за день просрочки"})
    else:
        m = ПЕНЯ_СУММА.search(норм)
        if m:
            найдено["penaltyKind"] = "per_day_fixed"
            найдено["penaltyValue"] = float(re.sub(r"\s", "", m.group(1)))
            цитаты.append({"field": "penaltyValue", "code": _пункт_перед(норм, m.start()) or "",
                           "text": _цитата(норм, m.start(), m.end()),
                           "hint": "неустойка за день просрочки"})

    m = ПОТОЛОК.search(норм)
    if m:
        найдено["penaltyCap"] = float(m.group(1).replace(",", "."))
        цитаты.append({"field": "penaltyCap", "code": _пункт_перед(норм, m.start()) or "",
                       "text": _цитата(норм, m.start(), m.end()),
                       "hint": "предел неустойки"})

    найдено["clauses"] = цитаты
    найдено["source"] = "parsed"
    return найдено


def санкция(liability: dict[str, Any] | None, дней_просрочки: int,
            цена_станции: float | None) -> dict[str, Any]:
    """Сумма требования на сегодня — по условиям договора, а не «на глаз».

    Проценты считаются от стоимости станции; если её нет в реестре, сумму не
    выдумываем: в претензии останется формула, и её заполнит человек.
    """
    if not liability or дней_просрочки <= 0:
        return {"amount": None, "formula": None, "days": max(0, дней_просрочки)}
    вид = liability.get("penaltyKind")
    значение = liability.get("penaltyValue")
    if not вид or вид == "none" or not значение:
        return {"amount": None, "formula": None, "days": дней_просрочки}

    if вид == "per_day_fixed":
        сумма = float(значение) * дней_просрочки
        формула = f"{значение} ₽ × {дней_просрочки} дн"
    else:
        if not цена_станции:
            return {"amount": None, "days": дней_просрочки,
                    "formula": f"{значение} % от стоимости станции × {дней_просрочки} дн",
                    "note": "стоимость станции в реестре не указана — сумму проставить вручную"}
        сумма = цена_станции * float(значение) / 100.0 * дней_просрочки
        формула = f"{цена_станции:.2f} ₽ × {значение} % × {дней_просрочки} дн"

    потолок = liability.get("penaltyCap")
    if потолок and цена_станции:
        предел = цена_станции * float(потолок) / 100.0
        if сумма > предел:
            return {"amount": round(предел, 2), "days": дней_просрочки,
                    "formula": f"{формула} = {сумма:.2f} ₽, ограничено {потолок} % ({предел:.2f} ₽)",
                    "capped": True}
    return {"amount": round(сумма, 2), "formula": формула, "days": дней_просрочки}


def следующий_шаг(liability: dict[str, Any] | None, отправлено: date,
                  сегодня: date | None = None) -> dict[str, Any] | None:
    """Что делать дальше после отправленной претензии и когда.

    Лестница живёт в условиях договора, а если её не задали — берётся наш
    порядок работы: ждать вечно нельзя, а придумывать срок в момент разбора
    поздно.
    """
    сегодня = сегодня or date.today()
    лестница = (liability or {}).get("escalation") or ЛЕСТНИЦА_ПО_УМОЛЧАНИЮ
    прошло = (сегодня - отправлено).days
    for шаг in sorted(лестница, key=lambda s: s["afterDays"]):
        if прошло < шаг["afterDays"]:
            return {
                "action": шаг["action"],
                "label": ДЕЙСТВИЯ.get(шаг["action"], шаг["action"]),
                "dueOn": (отправлено + timedelta(days=шаг["afterDays"])).isoformat(),
                "daysLeft": шаг["afterDays"] - прошло,
                "ready": False,
            }
    последний = max(лестница, key=lambda s: s["afterDays"])
    return {
        "action": последний["action"],
        "label": ДЕЙСТВИЯ.get(последний["action"], последний["action"]),
        "dueOn": (отправлено + timedelta(days=последний["afterDays"])).isoformat(),
        "daysLeft": 0,
        "ready": True,
    }


async def set_liability(
    db: AsyncSession, company_id: uuid.UUID, contract_id: uuid.UUID,
    данные: dict[str, Any], автор: str | None = None,
) -> dict[str, Any]:
    """Сохранить условия ответственности договора."""
    # Импорт внутри: разбор текста — чистая функция, и тянуть ради неё модели с
    # настройками приложения незачем. Так его можно проверить без базы.
    from sqlalchemy import select

    from app.models import Contract

    c = (await db.execute(select(Contract).where(
        Contract.company_id == company_id,
        Contract.id == contract_id))).scalar_one_or_none()
    if c is None:
        raise ValueError("Договор не найден в этой компании")

    очищено = {k: v for k, v in данные.items() if v is not None}
    очищено.setdefault("escalation", ЛЕСТНИЦА_ПО_УМОЛЧАНИЮ)
    # Подтверждённое человеком перестаёт быть разбором: дальше по нему считают
    # деньги и пишут в претензии, и «машина так прочитала» уже не оправдание.
    очищено["source"] = "manual"
    очищено["updatedAt"] = datetime.now().isoformat(timespec="seconds")
    очищено["updatedBy"] = автор
    c.liability = очищено
    await db.commit()
    return очищено
