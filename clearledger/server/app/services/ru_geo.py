# Канонизация написаний субъекта живёт в `mapping.canon_region` — там же, где её
# используют паспорта станций. Второго словаря заводить не нужно: разойдутся.


def canon_region(raw: str | None) -> str | None:
    """Каноническое имя субъекта или None, если название не опознано."""
    if not raw or not str(raw).strip():
        return None
    named = _canon(raw)
    # `mapping.canon_region` возвращает незнакомое название как есть — для рынка
    # это неотличимо от «не знаем», поэтому неопознанное здесь становится None.
    return named if named in _KNOWN else None


# Субъекты, о которых мы вообще знаем: все, что встречаются в справочнике городов.
_KNOWN: frozenset[str] = frozenset(CITY_REGION.values())


def region_for_city(city: str | None) -> str | None:
    """Субъект по названию города. None — города нет в справочнике."""
    if not city or not city.strip():
        return None
    key = city.replace("ё", "е").lower().strip()
    # Источник пишет «Корсаковский р-н», «Всеволожский р-н», «поселение Сосенское»:
    # район называется по своему центру, и для географии этого достаточно.
    key = re.sub(r"^(г|город|пос|поселок|посёлок|поселение|с|село|пгт|мкр|р-н|район)\.?\s+",
                 "", key)
    key = re.sub(r"\s*(р-н|район|улус|городской округ|го)\.?$", "", key).strip()
    if key in CITY_REGION:
        return CITY_REGION[key]
    # Район назван по своему центру, но прилагательным: «Корсаковский» → Корсаков,
    # «Конаковский» → Конаково, «Анивский» → Анива, «Пермский» → Пермь, «Холмский»
    # → Холмск. Окончание центра из прилагательного не восстановить однозначно,
    # поэтому перебираем известные и берём первое, что есть в справочнике.
    if key.endswith("ский"):
        stem = key[:-4]
        for tail in ("", "о", "а", "ск", "ь", "е"):
            if stem + tail in CITY_REGION:
                return CITY_REGION[stem + tail]
    return None


def resolve(region: str | None, city: str | None) -> tuple[str | None, str]:
    """Регион точки и способ, которым он получен.

    Способ важнее удобства: «взят из адреса» и «выведен из города» — разная
    надёжность, и экран обязан их различать, а не показывать одинаково.
    """
    named = canon_region(region)
    if named:
        return named, "source"
    from_city = region_for_city(city)
    if from_city:
        return from_city, "city"
    return None, "unknown"


