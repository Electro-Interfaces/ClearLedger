def gates_by_stage() -> dict[str, list[dict[str, Any]]]:
    """Чек-лист, разложенный по стадиям воронки — источник гейтов стадии."""
    out: dict[str, list[dict[str, Any]]] = {}
    for t in TASKS:
        item = {k: v for k, v in t.items() if k != "stage"}
        item["phase"] = PHASE_BY_TASK[t["key"]]
        if item.get("doc"):
            item["document_state"] = "signed"
        out.setdefault(t["stage"], []).append(item)
    return out


def checklist_meta() -> dict[str, Any]:
    """Регламент целиком — для экрана процесса и подсказок в карточке."""
    return {
        "roles": [{"code": c, "label": l} for c, l in ROLES.items()],
        "phases": [
            {**p, "tasks": [{"key": t["key"], "label": t["label"], "role": t["role"],
                             "stage": t["stage"], "required": bool(t.get("required")),
                             "auto": not t.get("manual")}
                            for t in TASKS if PHASE_BY_TASK[t["key"]] == p["code"]]}
            for p in PHASES_DOC
        ],
        "total": len(TASKS),
        "afterLaunch": AFTER_LAUNCH,
    }


def demo() -> None:
    """Проверки, которые ловят разъезд чек-листа с воронкой."""
    stages = {t["stage"] for t in TASKS}
    известные = {"lead", "screening", "negotiation", "dd", "decision",
                 "contracting", "construction", "commissioning", "live"}
    assert stages <= известные, f"неизвестные стадии: {stages - известные}"

    keys = [t["key"] for t in TASKS]
    assert len(keys) == len(set(keys)), "номера пунктов повторяются"

    # Каждый этап документа должен иметь хотя бы одну задачу — иначе он немой.
    for p in PHASES_DOC:
        свои = [t for t in TASKS if PHASE_BY_TASK[t["key"]] == p["code"]]
        assert свои, f"этап {p['code']} без задач"

    # Стадии задачи обязаны лежать внутри стадий своего этапа.
    for t in TASKS:
        фаза = next(p for p in PHASES_DOC if p["code"] == PHASE_BY_TASK[t["key"]])
        assert t["stage"] in фаза["stages"], (
            f"{t['key']}: стадия {t['stage']} вне этапа {фаза['code']}")

    # Порядок, ради которого чек-лист и правился: доступы отдаются ПОСЛЕ того,
    # как подписано пилотное соглашение.
    соглашение = next(t for t in TASKS if t["key"] == "4.3")
    доступы = next(t for t in TASKS if t["key"] == "5.1")
    порядок = ["lead", "screening", "negotiation", "dd", "decision",
               "contracting", "construction", "commissioning", "live"]
    assert порядок.index(соглашение["stage"]) < порядок.index(доступы["stage"]), (
        "доступы выдаются раньше пилотного соглашения")

    gates = gates_by_stage()
    assert sum(len(v) for v in gates.values()) == len(TASKS)
    # Пустая стадия в маршруте — экран «пунктов нет» и лишний клик; подпись без
    # перевода — «Оформление земли» в проекте роуминга.
    рабочие = ["lead", "screening", "negotiation", "dd", "decision",
               "contracting", "construction", "commissioning", "live"]
    по_стадиям = gates_by_stage()
    пустые = [st for st in рабочие if not по_стадиям.get(st)]
    assert not пустые, f"стадии без единого пункта: {пустые}"
    нет_подписи = [st for st in рабочие if st not in STAGE_LABELS or st not in STAGE_HINTS]
    assert not нет_подписи, f"стадии без подписи: {нет_подписи}"
    покрыты = {st for p in PHASES for st in p["stages"]}
    assert not set(рабочие) - покрыты, f"стадии вне этапов: {set(рабочие) - покрыты}"
    print(f"чек-лист интеграции: {len(TASKS)} задач, {len(PHASES_DOC)} этапов — ok")


if __name__ == "__main__":
    demo()
