def _слова(имя: str) -> list[str]:
    return re.findall(r"[a-zа-яё0-9]+", имя)


def предложить_путь(наименование: str) -> str | None:
    """Путь группы по названию. None — правило не сработало, решает человек.

    Ключ ищется по НАЧАЛУ СЛОВА, а не подстрокой: «Провода прикуривателя»
    содержит «вода» внутри слова и уезжали в напитки (поймано на импорте
    справочника АЗС 8). Ключ с пробелом или точкой — фраза, её ищем как есть.
    """
    имя = (наименование or "").lower()
    if not имя.strip():
        return None
    слова_имени = _слова(имя)
    for ключи, путь in ПРАВИЛА:
        for ключ in ключи:
            if " " in ключ or "." in ключ or "/" in ключ:
                if ключ in имя:
                    return путь
            elif any(слово.startswith(ключ) for слово in слова_имени):
                return путь
    return None


async def предложить(db: AsyncSession, наименование: str) -> dict | None:
    """То же, но с идентификатором группы и отделом кассы — для формы и API."""
    путь = предложить_путь(наименование)
    if путь is None:
        return None
    строка = (await db.execute(text("""
        SELECT id, path, cash_section FROM edge.item_group WHERE path = :p
    """), {"p": путь})).mappings().first()
    if строка is None:
        return None
    return {"group_id": строка["id"], "path": строка["path"],
            "cash_section": строка["cash_section"]}
