"""Служебные участники пространства: «Процесс» и «Секретарь».

Это не сотрудники. Они заводятся лениво, с заведомо невалидным паролем, и
существуют затем, что у события должен быть автор: маршрут поручает работу, а
личное напоминание приходит в чат — и сообщение без отправителя выглядит сбоем,
а не напоминанием.

Проблема в том, что членство в пространстве у них настоящее (`UserCompany`), и
любой запрос «дай людей компании» отдавал их наравне с людьми. Отсюда две
поломки, найденные на стенде 30.08.2026:

* «Процесс» стоял исполнителем двух поручений — маршрут завёл работу, никого не
  назвали, и `launch_task` отдал её тому, кто завёл. Работа висела на роботе
  вместо того, чтобы уйти в «Разбор» к человеку;
* и получал за неё сводку: движок напоминаний берёт получателей из назначений и
  не отличает робота от сотрудника.

Опознаются по домену: `@space.local` — зарезервированная зона, настоящего адреса
в ней не бывает. Отдельного поля в `User` не заводим: колонка потребовала бы
миграции и заполнения, а домен уже есть и уже уникален.
"""
from sqlalchemy import ColumnElement

from app.models import User

#: Домен служебных участников. `.local` зарезервирован RFC 6762 — настоящая
#: почта в этой зоне невозможна, и совпадение с живым человеком исключено.
SERVICE_DOMAIN = "space.local"


def is_service_account(user: User | None) -> bool:
    """Служебный ли это участник."""
    return bool(user and user.email and user.email.endswith(f"@{SERVICE_DOMAIN}"))


def not_service() -> ColumnElement[bool]:
    """Условие «это живой человек» для запросов, перечисляющих людей.

    Ставится там, где список людей предлагают ВЫБРАТЬ: кому поручить, кого
    позвать, кого оповестить. Не ставится там, где показывают уже случившееся, —
    в истории документа «Процесс» обязан остаться видимым автором, иначе строка
    «поручено маршрутом» превращается в поручение от никого.
    """
    return User.email.notlike(f"%@{SERVICE_DOMAIN}")
