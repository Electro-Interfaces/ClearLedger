const { test, expect } = require(process.env.TEST_PW_MODULE || '@playwright/test')
const A = '11111111-1111-4111-8111-111111111111'
const sources = ['local', 'alpha', 'beta'].map(code => ({ code, name: 'QA ' + code, state: 'ok', fetched_at: '2026-10-24T12:00:00Z' }))
const secret = 'SECRET https://internal.test TOKEN=private'
async function setup(page, context) {
  const state = { revoked: false, status: 0, statusError: 0, partial: '', calls: [], errors: [], escaped: [] }
  page.on('pageerror', e => state.errors.push(e.message))
  await page.clock.setFixedTime(new Date('2026-10-24T12:00:00Z'))
  await context.routeWebSocket(/.*/, ws => ws.close())
  await context.addInitScript(() => {
    localStorage.setItem('clearledger-token', 'qa-fixture-only')
    localStorage.setItem('cl-install-dismissed-at:v3', String(Date.now()))
    sessionStorage.setItem('cl-booted', '1')
  })
  await context.route('**/api/**', async route => {
    const url = new URL(route.request().url()), p = url.pathname
    if (p === '/api/auth/me') return route.fulfill({ json: { id: 'qa-manager', name: 'QA руководитель', email: 'qa@example.test', role: 'admin', is_superadmin: true, companies: [{ id: A, name: 'QA организация', slug: 'qa', profile_id: 'office', role: 'admin', modules: null }] } })
    if (p === '/api/companies') return route.fulfill({ json: [{ id: A, name: 'QA организация', slug: 'qa', profile_id: 'office', role: 'admin' }] })
    if (p === '/api/management/status') return route.fulfill(state.statusError ? { status: state.statusError, json: { detail: secret } } : { json: { enabled: true } })
    if (p === '/api/management/overview') {
      const q = Object.fromEntries(url.searchParams); state.calls.push(q)
      const days = (Date.parse(q.date_to) - Date.parse(q.date_from)) / 86400000 + 1
      const invalid = [...q.query].length > 200 || (q.kind === 'calendar' && (days > 367 || days < 1))
      const denied = (q.space === 'beta' && q.kind !== 'chats') || (state.revoked && q.space === 'alpha')
      const status = state.status || (invalid ? 422 : denied ? 404 : 0)
      if (status) return route.fulfill({ status, json: { detail: secret } })
      const active = sources.filter(s => q.space === 'all' || q.space === s.code).filter(s => !(state.revoked && s.code === 'alpha')).filter(s => q.kind === 'chats' || s.code !== 'beta')
      return route.fulfill({ json: { enabled: true, fetched_at: '2026-10-24T12:00:00Z', truncated: false,
        sources: active.map(s => ({ ...s, state: s.code === 'alpha' && state.partial ? state.partial : 'ok', error: secret })),
        items: active.filter(s => !(s.code === 'alpha' && state.partial)).map(s => ({ id: s.code + ':' + q.kind, source_id: s.code, kind: q.kind, source: { code: s.code, name: s.name, company_id: A, company_name: 'QA организация' }, title: 'Запись ' + s.code + ' ' + q.kind, href: '/qa-original/' + s.code, status: q.kind === 'chats' ? 'group' : 'open', ...(q.kind === 'calendar' ? { starts_at: '2026-10-24T12:00:00Z' } : {}) })) } })
    }
    if (p.startsWith('/api/partner-space') || p.startsWith('/api/work-contexts')) return route.fulfill({ json: { items: [] } })
    return route.fulfill({ json: [] })
  })
  page.on('request', req => { if (req.url().includes('/api/') && new URL(req.url()).origin !== 'http://127.0.0.1:3823') state.escaped.push(req.url()) })
  await page.goto('/management')
  await expect(page.getByRole('link', { name: 'Запись local chats', exact: true })).toBeVisible({ timeout: 20000 })
  return state
}
const search = page => page.getByLabel('Поиск', { exact: true })
const find = page => page.getByRole('button', { name: 'Найти', exact: true })
const refresh = page => page.getByRole('button', { name: 'Обновить', exact: true })
const reset = page => page.getByRole('button', { name: 'Сбросить', exact: true })
async function select(page, code) {
  await page.getByRole('combobox', { name: 'Пространство', exact: true }).click()
  await page.getByRole('option', { name: 'QA ' + code, exact: true }).click()
}
async function evidence(page, info, name) {
  await page.getByRole('heading', { name: 'Управляющее пространство', exact: true }).scrollIntoViewIfNeeded()
  await info.attach(name, { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.locator('body').innerText()).not.toMatch(/SECRET|internal\.test|TOKEN=private|несовместим|в этой версии/)
}
test('ISSUE-002: 201 characters explain limit and block invalid request, edit recovers', async ({ page, context }, info) => {
  const s = await setup(page, context)
  const count = s.calls.length
  await search(page).fill('я'.repeat(201))
  await search(page).press('Enter')
  await evidence(page, info, 'search201')
  await expect(search(page)).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#management-search-note')).toContainText('200')
  await expect(find(page)).toBeDisabled()
  await search(page).press('Enter')
  expect(s.calls).toHaveLength(count)
  await search(page).fill('исправлено')
  await find(page).click()
  await expect.poll(() => s.calls.at(-1).query).toBe('исправлено')
  await expect(page.getByRole('link', { name: 'Запись local chats', exact: true })).toBeVisible()
  expect(s.errors).toEqual([]); expect(s.escaped).toEqual([])
})
test('ISSUE-002: long calendar explains limit, 367 inclusive days allowed, 368 blocked', async ({ page, context }, info) => {
  const s = await setup(page, context)
  await page.getByRole('tab', { name: 'Календарь', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Запись local calendar', exact: true })).toBeVisible()
  await page.getByLabel('С даты', { exact: true }).fill('2026-01-01')
  await page.getByLabel('По дату включительно', { exact: true }).fill('2028-01-01')
  await evidence(page, info, 'calendar-too-long')
  await expect(page.locator('#management-period-note')).toContainText('367')
  await expect(page.getByLabel('По дату включительно', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  expect(s.calls.some(q => q.date_to === '2028-01-01')).toBe(false)
  await page.getByLabel('По дату включительно', { exact: true }).fill('2027-01-02')
  await expect.poll(() => s.calls.at(-1).date_to).toBe('2027-01-02')
  await expect(page.getByRole('link', { name: 'Запись local calendar', exact: true })).toBeVisible()
  const count = s.calls.length
  await page.getByLabel('По дату включительно', { exact: true }).fill('2027-01-03')
  await expect(page.getByLabel('По дату включительно', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(refresh(page)).toBeDisabled()
  expect(s.calls).toHaveLength(count)
  await page.getByLabel('С даты', { exact: true }).fill('')
  await expect(page.locator('#management-period-note')).toContainText('обе даты')
  await page.getByLabel('С даты', { exact: true }).fill('2027-01-04')
  await expect(page.locator('#management-period-note')).toContainText('не раньше')
  await page.getByLabel('С даты', { exact: true }).fill('2027-01-03')
  await expect(page.getByRole('link', { name: 'Запись local calendar', exact: true })).toBeVisible()
  await evidence(page, info, 'calendar-recovered')
})
