/**
 * Шаблоны обращений в техподдержку — заготовки, по которым человек пишет нам.
 *
 * Замысел МАГа (04.09.2026): обращение с пустого места сотрудник пишет одной
 * строкой — «не работает», — и дальше начинается переписка ради сведений, которые
 * он мог назвать сразу. Шаблон эти сведения спрашивает: объект, время, что делали,
 * что увидели. Оператор получает разбираемое обращение, человек не думает, что
 * писать, а поддержка не тратит первый ход на уточнения.
 *
 * Поставка одна на всех: шаблоны — это наш опыт разбора, а не настройка клиента.
 * Отбор идёт по профилю компании, потому что аудиторской фирме «ТРК не наливает»
 * предлагать так же нелепо, как АЗС — «не сходится КУДиР».
 *
 * Заголовок шаблона становится темой обращения, тело — болванкой первого
 * сообщения: человек дописывает по строкам, а не сочиняет структуру.
 */
import type { ProfileId } from './profiles'

export interface SupportTemplate {
  code: string
  /** Тема обращения — её видит и оператор в очереди. */
  title: string
  /** Болванка сообщения: строки, которые человек дополняет. */
  body: string
  /** Профили, которым шаблон предлагается. Пусто — всем. */
  profiles?: ProfileId[]
}

