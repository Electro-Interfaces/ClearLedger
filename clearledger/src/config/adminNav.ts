/** Разделы по блокам, в порядке появления — для меню. */
export function sectionGroups(sections: AdminSection[]): { name: string; items: AdminSection[] }[] {
  const out: { name: string; items: AdminSection[] }[] = []
  for (const s of sections) {
    const name = s.group ?? ''
    const last = out[out.length - 1]
    if (last && last.name === name) last.items.push(s)
    else out.push({ name, items: [s] })
  }
  return out
}

export const adminPath = (scope: AdminScope, code: string) => `/admin/${scope}/${code}`

export function findSection(scope: AdminScope, code: string | undefined): AdminSection | undefined {
  const list = scope === 'eco' ? ecosystemSections : companySections
  return list.find((s) => s.code === code)
}
