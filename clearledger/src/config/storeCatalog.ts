/** Пункты раздела: порядок = порядок записей в STORE_VIEWS. */
export const storeMenu = (mode: StoreMode) =>
  STORE_VIEWS.filter((v) => v.section === mode)
    .map((v) => ({
      key: v.key, label: v.label,
      ...(v.group ? { group: v.group } : {}),
      // Неготовый пункт в меню обязан выглядеть неготовым. Иначе человек идёт
      // за отчётом, открывает экран и упирается в «панель ещё не собрана» —
      // а меню обещало рабочий инструмент.
      ...(v.status === 'ready' ? {} : { disabled: true }),
    }))

/** Все пункты разом — для карты прав и подписей; от раздела состав не зависит. */
export const STORE_MENU = STORE_VIEWS.map((v) => ({ key: v.key, label: v.label }))
export const STORE_KEYS = STORE_VIEWS.map((v) => v.key)
export const STORE_DEFAULT_KEY = 'overview'

/**
 * Прежние ключи пунктов → нынешние.
 *
 * Ключ живёт в адресе, а адрес попадает в закладки и в переписку. Переименование
 * без карты означает, что вчерашняя ссылка молча открывает не тот экран —
 * человек считает, что раздел сломался.
 */
export const STORE_KEY_ALIASES: Record<string, string> = {
  revaluation: 'price-plan',
}

/** Канонический ключ пункта: старый адрес приводится к нынешнему. */
export function storeCanonKey(key: string): string {
  return STORE_KEY_ALIASES[key] ?? key
}

/** Ключи, которые роутер обязан принять: нынешние плюс исторические. */
export const STORE_ROUTE_KEYS = [...STORE_KEYS, ...Object.keys(STORE_KEY_ALIASES)]

/** Раздел, которому принадлежит пункт: переход по старой ссылке меняет и `mode`, и `sub`. */
export function storeModeForKey(key: string): StoreMode {
  return STORE_VIEWS.find((v) => v.key === storeCanonKey(key))?.section ?? 'store'
}

/** Первый пункт раздела — куда падать при смене раздела. */
export const storeDefaultKey = (mode: StoreMode) => storeMenu(mode)[0]?.key ?? STORE_DEFAULT_KEY

export function getStoreView(key: string): StoreView | undefined {
  return STORE_VIEWS.find((v) => v.key === storeCanonKey(key))
}
