export type StoreStatus = 'ready' | 'wip' | 'planned'

/**
 * Разделы продукта — в левой рельсе, их пункты — во второй панели (решение МАГа 29.07.2026).
 *
 * Двадцать пять экранов одним списком с гармошкой заголовков читались как один длинный
 * свиток: чтобы после алерта по недостаче посмотреть маржу, менеджер трижды прокручивал
 * меню мимо приёма из 1С, техкарт и вывода из оборота. Делим по предмету, которым занят
 * товаровед: деньги и спрос · остаток и движение · карточка товара ·
 * что мы должны государству.
 *
 * `store` остаётся кодом первого раздела: по нему идут старые ссылки, подписи режимов и
 * ключ доступа. Раздел задаётся полем `section` записи — второго источника правды нет.
 */
export type StoreMode = 'store' | 'store_receipt' | 'store_stock' | 'store_catering' | 'store_reports' | 'store_catalog' | 'store_cash' | 'store_marking' | 'store_documents' | 'store_network' | 'store_1c'

/**
 * Порядок разделов — тот же, что на рабочем месте станции (решение МАГа 23.08.2026).
 *
 * Администратор АЗС работает в агенте, а в центр приходит за сетью: за парком
 * станций, чужими сменами, сводными отчётами. Если рельса в этих двух местах
 * разная, он каждый раз ищет заново — «Документы» у него девятые, а тут вторые.
 * Поэтому центр повторяет станцию, и отличается только тем, чем и должен:
 * разделом «Станции», которого на самой станции быть не может.
 *
 * Сверху — то, чем заняты каждый день: продажи, приёмка, склад, кухня. Под
 * чертой — то, к чему обращаются по поводу: отчёты, справочники, регуляторика,
 * документооборот, парк АЗС.
 */
