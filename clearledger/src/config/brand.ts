/**
 * Имена в интерфейсе: платформа — до входа, компания — после.
 *
 * До авторизации человек ещё не в чьём-то пространстве, поэтому виден продукт-платформа
 * («Рабочее пространство: Цифровой сотрудник») — без подписи автора: пространство
 * заказчика не рекламирует студию (решение МАГа 31.07.2026). После входа бренд платформы
 * уходит: на экране только имя компании, в чьём пространстве человек работает, а внутри —
 * продукты (Управление, Координатор, Учёт, …) без брендовых префиксов: компания названа
 * один раз в шапке, повторять её в каждой плитке незачем.
 *
 * Бренд компании бакается на сборке фронт-образа (`VITE_ECOSYSTEM_BRAND`), как VITE_API_URL:
 *   rushydro → «РусГидро», gig → «ГИГ», …
 */
export const ECOSYSTEM_BRAND: string =
  (import.meta.env.VITE_ECOSYSTEM_BRAND as string | undefined)?.trim() || 'ElsyPlus'

/**
 * Имя компании в шапках после авторизации. Раньше здесь было «Экосистема <бренд>» —
 * лишнее слово: человек и так внутри своего пространства, ему важно имя компании.
 */
export const ECOSYSTEM_TITLE = ECOSYSTEM_BRAND

/** Продукт-платформа — то, во что человек входит до выбора компании. */
export const PLATFORM_PRODUCT: string =
  (import.meta.env.VITE_PLATFORM_PRODUCT as string | undefined)?.trim() || 'Цифровой сотрудник'
