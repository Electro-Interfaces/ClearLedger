/** Страницы Ядра открыты каждому продукту, поэтому и адрес у них — внутри продукта. */
export const SHARED_PATHS = SPACE_PAGES

export function productPagePath(product: SpaceProduct, path: string): string {
  return SHARED_PATHS.includes(path) ? `${product.route}${path}` : path
}

/** Код страницы для прав и меню: сегмент пути (`/files` → `files`, `/1c/export` → `1c`). */
export const pageCode = (path: string) => path.replace(/^\//, '').split('/')[0]

/**
 * Код приложения по адресу — для контекстной подсказки «Инфо».
 *
 * Продуктами разреза дело не ограничивается: «Управление», «Данные», Чаты и сам
 * «Инфо» — тоже приложения реестра, и подсказка в них должна знать, где человек.
 * Без этого в «Управлении» контекст молча считался Учётом.
 */
const ROUTE_APPS: [string, string][] = [
  ['/admin', 'admin'], ['/data', 'data'], ['/messages', 'chat'],
  ['/info', 'info'], ['/workspace', 'ledger'], ['/pulse', 'pulse'],
  // «Заявки» жили без записи: экран открывался под шапкой «Учёт» с чужим меню,
  // хотя это самостоятельное приложение Ядра со своей витриной. Витрина осталась
  // за Поддержкой, а код `plan` уехал на «Задачи» (docs/TASKS.md).
  ['/tickets', 'support'], ['/tasks', 'plan'],
  // Аудитор — свой экран Ядра, как «Чаты»: панель сквозная, а по этому адресу живёт
  // страница агента (каталог навыков и разговор во всю ширину).
  ['/auditor', 'auditor'],
]

/**
 * Имена приложений Ядра для шапки. Продукты разреза называет `productLabel`, а эти
 * четыре — свои экраны Ядра, и шапка обязана называть их так же, как плитка на столе:
 * человек в «Чатах» видел «ElsyPlus Учёт» и справедливо не понимал, где он.
 */
const CORE_APP_TITLES: Record<string, string> = {
  chat: 'Чаты', admin: 'Управление', data: 'Данные', info: 'Инфо', pulse: 'Пульс',
  plan: 'Задачи', support: 'Заявки', auditor: 'Аудитор',
}

/** Имя приложения Ядра по адресу; null — адрес принадлежит Учёту или продукту. */
export function coreAppTitle(pathname: string): string | null {
  const code = appCodeForPath(pathname)
  return CORE_APP_TITLES[code] ?? null
}

export function appCodeForPath(pathname: string): string {
  const product = productForPath(pathname)
  if (product) return product.code
  for (const [prefix, code] of ROUTE_APPS) {
    if (pathname === prefix || pathname.startsWith(`${prefix}/`)) return code
  }
  return 'ledger'
}

/** Продукт по маршруту или странице (`/finance`, `/finance/files`, `/organization`). */
export function productForPath(pathname: string): SpaceProduct | null {
  for (const p of SPACE_PRODUCTS) {
    if (pathname === p.route || pathname.startsWith(`${p.route}/`)) return p
    if (p.paths.some((path) => pathname === path || pathname.startsWith(`${path}/`))) return p
  }
  // Голый ядровой путь (`/objects` из старой закладки) продукту не принадлежит — но и
  // меню Учёта показывать в разрезанном профиле нечего: отдаём первое рабочее место,
  // как было, пока эти страницы числились за каждым продуктом.
  if (SPACE_PAGES.some((path) => pathname === path || pathname.startsWith(`${path}/`))) {
    return SPACE_PRODUCTS[0]
  }
  return null
}

/**
 * СОБСТВЕННЫЕ страницы продукта для левого меню (в порядке `paths`).
 *
 * Пункта «Рабочий стол» здесь нет: рабочий стол — уровнем выше, у пространства.
 * Верхний уровень внутри продукта — его собственные разделы («Продажи», «Магазин»);
 * их подставляет `AppSidebar` из фактических секций рабочей области, а под-разделы
 * этой области остаются в гармошке `WorkspaceModeSidebar`. Функции Ядра сюда не входят —
 * они одни на все продукты (`spaceNav`).
 */
export function productNav(
  product: SpaceProduct,
  allowed?: PageGate,
  profileId?: string | null,
): NavItemDef[] {
  return navFor(product, [...product.paths, ...fuelOnlyPaths(product, profileId)], allowed)
}

/**
 * Контур 1С — рабочее место бухгалтера топливного профиля, и живёт он в «Бухгалтерском»
 * (`finance`). У энергетики эти маршруты закрыты гардом `RequireFuel`, поэтому пункт там
 * вёл бы в редирект — отсюда профильный фильтр, а не общий список страниц продукта.
 *
 * Две страницы из контура в меню НЕ выводятся (04.08.2026): они дублируют разделы, к
 * которым бухгалтерия теперь разложена по потокам, и человек читал в одном списке два
 * одинаковых слова.
 *
 *   `/1c/documents` — тот же реестр, что открывает раздел «Документы»;
 *   `/1c/export`    — очередь пакетов, которой не существует: расширение к ней не
 *                     обращается, а выгрузка стала стадией внутри потока.
 *
 * Сами маршруты живы: на них ведут кнопки из разделов и старые закладки.
 */
const ONEC_PRODUCT = 'finance'
const ONEC_HIDDEN = new Set(['/1c/documents', '/1c/export'])

function fuelOnlyPaths(product: SpaceProduct, profileId?: string | null): string[] {
  if (profileId !== 'fuel' || product.code !== ONEC_PRODUCT) return []
  return oneCItems.map((i) => i.to).filter((to) => !ONEC_HIDDEN.has(to))
}

/** Страница продукта из контура 1С — её место в свёрнутой группе «Обмен с 1С». */
export const isOneCPath = (to: string) => to.startsWith('/1c/')

/** Функции Ядра для левого меню продукта — один и тот же состав в каждом рабочем месте.
 *  Исключение — компания без объектов: реестр объектов у неё пуст по определению
 *  (единственный «объект» это её офис), и пункт вёл бы в заведомо пустой список. */
export function spaceNav(
  product: SpaceProduct, allowed?: PageGate, profileId?: string | null,
): NavItemDef[] {
  const pages = profileId === 'office' ? SPACE_PAGES.filter((p) => p !== '/objects') : SPACE_PAGES
  return navFor(product, pages, allowed)
}

/** Право на страницу проверяется по ИСХОДНОМУ пути: у `/sales/files` код `files`, не `sales`. */
type PageGate = (pageCode: string) => boolean

function navFor(product: SpaceProduct, paths: string[], allowed?: PageGate): NavItemDef[] {
  return paths
    .filter((path) => navByPath[path] && (!allowed || allowed(pageCode(path))))
    .map((path) => ({ ...navByPath[path], to: productPagePath(product, path) }))
}


/** Разделы, ушедшие из Учёта в отдельные продукты (при выключенном разрезе — пусто). */
export function carvedModes(profileId: string | null | undefined): Set<CoreMode> {
  if (!isCarvedProfile(profileId)) return new Set()
  return new Set(SPACE_PRODUCTS.flatMap((p) => p.modes))
}

/**
 * Пускать ли на путь. Страница продукта проверяется доступом к ПРОДУКТУ, а не к модулям
 * Учёта: у того, кому роль дала «Финансы», ключа `ledger:documents` нет, и старая проверка
 * закрыла бы ему собственные «Документы». Всё остальное — по-прежнему модулями Учёта.
 *
 * `pageAllowed` (необязательный) добавляет второй уровень: страница продукта — тоже
 * право (`finance:files`). Передаётся коллбэком, а не импортом `productAccess`, чтобы не
 * замкнуть модули: карта прав сама читает `SPACE_PRODUCTS`.
 */
export function pathAllowed(
  pathname: string,
  profileId: string | null | undefined,
  canApp: (code: string) => boolean,
  fallback: (pathname: string) => boolean,
  pageAllowed?: (appCode: string, pageCode: string) => boolean,
): boolean {
  if (isCarvedProfile(profileId)) {
    const product = productForPath(pathname)
    if (product) {
      if (!canApp(product.code)) return false
      if (!pageAllowed) return true
      // Корень продукта (`/operations`) — это его разделы, а не страница: права на
      // разделы проверяет меню, здесь достаточно доступа к самому продукту. Иначе
      // роль «только Обзор и Парк» не пускала бы человека в собственный продукт.
      if (pathname === product.route) return true
      // Страница внутри продукта — `/finance/objects` (SHARED_PATHS) либо собственный
      // путь (`/files`); в обоих случаях код = первый сегмент после корня продукта.
      const tail = pathname.startsWith(`${product.route}/`)
        ? pathname.slice(product.route.length) : pathname
      const code = pageCode(tail)
      return !code || pageAllowed(product.code, code)
    }
    // Путь вне карты продуктов у разрезанного профиля: legacy-гейт (fallback =
    // routeAllowed по ключам Учёта) не применяем. В наборах разрезанного профиля
    // legacy-ключей не бывает, поэтому fallback умел только ложно запрещать:
    // у человека с явным набором прав «вдруг пропадали» пункты, которые видны
    // админу с modules = NULL.
    return true
  }
  return fallback(pathname)
}

/** Куда возвращать при отказе: у разрезанного профиля рабочий стол пространства. */
export function homePath(profileId: string | null | undefined): string {
  return isCarvedProfile(profileId) ? '/' : '/workspace'
}
