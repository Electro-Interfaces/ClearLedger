  if (CHARGE_SESSIONS_KEYS.includes(key)) return salesModeForKey(key)
  if (OPS_KEYS.includes(key)) return opsModeForKey(key)
  if (SITES_KEYS.includes(key)) return sitesModeForKey(key)
