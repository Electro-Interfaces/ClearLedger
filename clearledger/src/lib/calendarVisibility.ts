/**
 * Кого календарь показывает из отменённых встреч.
 *
 * Правило пространства (`ecosystem-deploy/docs/TRACK.md`, «Календарь»):
 * отменённая встреча не исчезает, пока её день не прошёл, — зачёркнутой и с
 * причиной; прошедшие отменённые скрываются. Молча пропавшая встреча означает,
 * что кто-то придёт в пустую переговорную.
 *
 * Правило живёт отдельной функцией, потому что ломается молча: экран при любой
 * ошибке выглядит рабочим, просто одной строкой меньше.
 */
export type ОтменяемаяВстреча = {
  id: string
  status?: string | null
  /** Конец встречи: день считается по нему, а не по началу. */
  ends_at: string
}

export function видимаВКалендаре(
  встреча: ОтменяемаяВстреча,
  { сейчас, показыватьПрошедшие, открытая }: {
    сейчас: Date
    /** Галочка «Прошедшие отменённые» — только про те, чей день уже прошёл. */
    показыватьПрошедшие: boolean
    /** Открытая карточка остаётся на экране, даже если отбор её не берёт. */
    открытая?: string | null
  },
): boolean {
  if (встреча.status !== 'cancelled') return true
  if (встреча.id === открытая) return true
  if (показыватьПрошедшие) return true
  const началоДня = new Date(сейчас)
  началоДня.setHours(0, 0, 0, 0)
  return new Date(встреча.ends_at) >= началоДня
}
