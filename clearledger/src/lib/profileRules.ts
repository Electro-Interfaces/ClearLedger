/** Подпись пояса в списке: город и смещение, чтобы себя узнали оба типа людей. */
export const подписьПояса = (z: Пояс) => `${z.label} (UTC+${z.offset})`

/** Пояса по смещению — для группировки в списке выбора. */
export function поясаПоСмещению(): { offset: number; зоны: Пояс[] }[] {
  const карта = new Map<number, Пояс[]>()
  for (const z of ПОЯСА) {
    const группа = карта.get(z.offset) ?? []
    группа.push(z)
    карта.set(z.offset, группа)
  }
  return [...карта.entries()].sort((a, b) => a[0] - b[0]).map(([offset, зоны]) => ({ offset, зоны }))
}

/** Рабочий день: конец позже начала. То же правило, что на сервере. */
export const рабочийДеньВерен = (начало: string, конец: string) =>
  /^\d{2}:\d{2}$/.test(начало) && /^\d{2}:\d{2}$/.test(конец) && начало < конец

