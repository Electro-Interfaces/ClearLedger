/**
 * Что не так с новым паролем — или `null`, если всё в порядке.
 * Проверяем до отправки: иначе человек узнаёт о короткой длине от сервера,
 * уже введя всё трижды.
 */
export function ошибкаПароля(текущий: string, новый: string, повтор: string): string | null {
  if (!текущий) return 'Введите текущий пароль'
  if (новый.length < МИН_ДЛИНА_ПАРОЛЯ) return `Новый пароль — не короче ${МИН_ДЛИНА_ПАРОЛЯ} символов`
  if (новый === текущий) return 'Новый пароль должен отличаться от текущего'
  if (повтор !== новый) return 'Новый пароль и повтор не совпадают'
  return null
}

/** Что не так с выбранным файлом фото — или `null`. */
export function ошибкаФото(file: File): string | null {
  if (!file.type.startsWith('image/')) return 'Нужна картинка'
  if (file.size > ПРЕДЕЛ_ФОТО_МБ * 1024 * 1024) return `Файл больше ${ПРЕДЕЛ_ФОТО_МБ} МБ — выберите снимок полегче`
  return null
}

