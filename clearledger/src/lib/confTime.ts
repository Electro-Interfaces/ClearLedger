// Время до начала конференции: чистые функции отдельно от экрана, чтобы их
// проверял тест без React.

/** За сколько до начала конференция считается близкой: строка меняет вид и
 *  встаёт наверх. Четверть часа — время дойти до рабочего места и открыть
 *  материалы; раньше предупреждение превращается в фон. */
export const СКОРО_МС = 15 * 60_000

/** Назначенная конференция, до начала которой четверть часа или меньше, либо
 *  время которой уже идёт, а в неё ещё не вошли. */
export function скороНачало(в: { starts_at: string; ends_at: string; status: string; live: boolean },
                            сейчас: number) {
  return !в.live && в.status !== 'cancelled'
    && new Date(в.starts_at).getTime() - сейчас <= СКОРО_МС
    && new Date(в.ends_at).getTime() > сейчас
}

/** «через 6 дней», «через 3 ч 20 мин», «через 12 мин», «время пришло». */
export function доНачала(начало: string, сейчас: number) {
  const мс = new Date(начало).getTime() - сейчас
  if (мс <= 0) {
    const прошло = Math.floor(-мс / 60_000)
    return прошло < 1 ? 'начинается сейчас' : `должна идти уже ${прошло} мин`
  }
  const мин = Math.ceil(мс / 60_000)
  if (мин < 60) return `через ${мин} мин`
  if (мин < 24 * 60) {
    const ч = Math.floor(мин / 60)
    return `через ${ч} ч${мин % 60 ? ` ${мин % 60} мин` : ''}`
  }
  // Склонение дней отдаём браузеру: «через 1 день», «через 3 дня», «через 6 дней».
  return new Intl.RelativeTimeFormat('ru', { numeric: 'always' })
    .format(Math.floor(мин / (24 * 60)), 'day')
}
