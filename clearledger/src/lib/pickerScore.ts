/**
 * Насколько строка списка отвечает запросу поиска.
 *
 * Простая проверка «содержит подстроку» на людях не работает: по букве «м»
 * находятся Администратор, Бурмистрова, Верховцева Марина, Вишневский Дмитриевич,
 * Дёмина, Демьянова, Кашеваров Владимирович — «м» есть почти в каждом отчестве.
 * Человек видит весь справочник и решает, что поиск сломан (Чурилов, 12.09.2026).
 *
 * Поэтому вес считается по тому, ГДЕ нашлось совпадение: начало строки — лучше
 * начала слова, начало слова — лучше середины. А по одной-двум буквам середина
 * слова не в счёт вовсе: такой запрос всегда попадёт в половину списка и
 * превратит поиск в тот же справочник.
 */

/** С какой длины запроса середина слова тоже считается совпадением. */
const ОТ_СЕРЕДИНЫ = 3

export function pickerScore(value: string, search: string): number {
  const q = search.trim().toLowerCase()
  if (!q) return 1
  const v = value.toLowerCase()
  const at = v.indexOf(q)
  if (at < 0) return 0
  if (at === 0) return 1
  // Начало слова: перед совпадением — пробел или разделитель.
  if (/[\s.,·/\-—(]/.test(v[at - 1])) return 0.7
  return q.length >= ОТ_СЕРЕДИНЫ ? 0.3 : 0
}
