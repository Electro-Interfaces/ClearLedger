/**
 * Политика кеша вложений: ссылку, которую показывают, отзывать нельзя.
 *
 * Из-за обратного видео в чате «не подгружалось»: человек жал «показать», ролик
 * выкачивался, следующие снимки ленты вытесняли его из кеша, `revokeObjectURL` гасил
 * адрес — и плеер оставался с мёртвой ссылкой (жалоба РусГидро 14.09.2026).
 *
 * Прогон: node --test --experimental-strip-types src/lib/blobCache.test.ts
 */
import { strict as assert } from 'node:assert'
import { beforeEach, test } from 'node:test'

const отозванные: string[] = []
// В node объектных ссылок нет — подменяем ровно то, чем пользуется модуль.
;(URL as unknown as { revokeObjectURL: (u: string) => void }).revokeObjectURL =
  (u: string) => { отозванные.push(u) }

const { ПРЕДЕЛ_КЕША, взять, найти, отпустить, очистить, положить, состояние } =
  await import('./blobCache.ts')

beforeEach(() => {
  очистить()
  отозванные.length = 0
})

test('переполнение вытесняет старое и отзывает его ссылку', () => {
  for (let i = 0; i < ПРЕДЕЛ_КЕША + 3; i += 1) положить(`/f/${i}`, `blob:${i}`)
  assert.equal(состояние().length, ПРЕДЕЛ_КЕША)
  assert.deepEqual(отозванные, ['blob:0', 'blob:1', 'blob:2'])
  assert.equal(найти('/f/0'), null, 'вытесненное больше не отдаём')
})

test('показываемую ссылку вытеснение не трогает', () => {
  положить('/видео', 'blob:кино')
  взять('/видео')                       // плеер открыл ролик
  for (let i = 0; i < ПРЕДЕЛ_КЕША + 5; i += 1) положить(`/снимок/${i}`, `blob:s${i}`)
  assert.equal(найти('/видео'), 'blob:кино', 'ролик остался в кеше')
  assert.ok(!отозванные.includes('blob:кино'), 'ссылку из-под плеера отозвали')
})

test('после закрытия плеера ссылка снова вытесняется', () => {
  положить('/видео', 'blob:кино')
  взять('/видео')
  отпустить('/видео')                   // плеер закрыт
  for (let i = 0; i < ПРЕДЕЛ_КЕША + 5; i += 1) положить(`/снимок/${i}`, `blob:s${i}`)
  assert.equal(найти('/видео'), null)
  assert.ok(отозванные.includes('blob:кино'))
})

test('двое показывают одно и то же — отпускает последний', () => {
  положить('/кадр', 'blob:кадр')
  взять('/кадр'); взять('/кадр')        // лента и лайтбокс
  отпустить('/кадр')
  for (let i = 0; i < ПРЕДЕЛ_КЕША + 5; i += 1) положить(`/иное/${i}`, `blob:x${i}`)
  assert.equal(найти('/кадр'), 'blob:кадр', 'второй показ ещё держит ссылку')
})

test('повторная запись того же пути не гасит показываемую ссылку', () => {
  положить('/кадр', 'blob:первый')
  взять('/кадр')
  положить('/кадр', 'blob:второй')
  assert.deepEqual(отозванные, [], 'прежнюю ссылку держат — отзывать нельзя')
  assert.equal(найти('/кадр'), 'blob:второй')
})
