/**
 * Сколько дня уже занято и сколько осталось.
 *
 * Автопланировщика не делаем сознательно. Тормоза, которыми Reclaim обвешал
 * свой ради доверия — свои блоки не трогают встречи, блок «свободен», пока есть
 * запас до срока, замок от передвижения, — стоят дороже самого планировщика.
 * И планировать нечем: он живёт на оценке трудоёмкости, а в документообороте её
 * никто не заполнит.
 *
 * Взамен — одна строка, которая ничего не двигает и говорит только то, что
 * известно наверняка: часы встреч реальны, рабочее окно человек задал сам,
 * намеченных дел ровно столько, сколько он себе наметил. Про их длительность мы
 * молчим — врать про неё хуже, чем не знать.
 */

export interface Встреча {
  starts_at: string
  ends_at: string
  all_day?: boolean
  status?: string
}

export interface Нагрузка {
  /** Часы, занятые встречами. */
  занято: number
  /** Часы рабочего окна, оставшиеся свободными. Не бывает меньше нуля. */
  свободно: number
  /** Готовая строка или `null`, если говорить не о чем. */
  text: string | null
  /** Встречи уже перекрыли рабочее окно. */
  перегруз: boolean
}

const МИНУТА = 60 * 1000

/** «09:00» → минуты от полуночи. Нечитаемое значение — запасной вариант. */
export function minutesOf(hhmm: string | null | undefined, запас: number): number {
  const m = /^(\d{1,2}):(\d{2})$/.exec(hhmm ?? '')
  if (!m) return запас
  const ч = Number(m[1])
  const мин = Number(m[2])
  return ч > 23 || мин > 59 ? запас : ч * 60 + мин
}

/** Час с одним знаком после запятой и без хвоста: «4 ч», «4,5 ч». */
export function часы(минут: number): string {
  const ч = Math.round(минут / 6) / 10
  return `${String(ч).replace('.', ',')} ч`
}

/**
 * Нагрузка дня.
 *
 * Всёдневные встречи в часы не идут: «отпуск» занимает день, но не отнимает
 * четыре часа у совещания. Отменённые не идут тоже — они видны в календаре,
 * чтобы человек не пришёл в пустую переговорную, но времени не занимают.
 * Пересечения складываются один раз: две встречи, наложенные друг на друга,
 * не отнимают у дня двойное время — человек всё равно проживёт его однажды.
 */
export function dayLoad(встречи: Встреча[], намечено: number, day: Date,
                        workStart?: string | null,
                        workEnd?: string | null): Нагрузка {
  const начало = new Date(day)
  начало.setHours(0, 0, 0, 0)
  const окноОт = начало.getTime() + minutesOf(workStart, 9 * 60) * МИНУТА
  const окноДо = начало.getTime() + minutesOf(workEnd, 18 * 60) * МИНУТА
  const окно = Math.max(0, (окноДо - окноОт) / МИНУТА)

  // Слияние отрезков: пересечения не должны считаться дважды.
  const отрезки = встречи
    .filter((e) => !e.all_day && e.status !== 'cancelled')
    .map((e) => [Math.max(окноОт, new Date(e.starts_at).getTime()),
                 Math.min(окноДо, new Date(e.ends_at).getTime())] as const)
    .filter(([a, b]) => b > a)
    .sort((a, b) => a[0] - b[0])

  let занятоМин = 0
  let край = -Infinity
  for (const [a, b] of отрезки) {
    const от = Math.max(a, край)
    if (b > от) занятоМин += (b - от) / МИНУТА
    край = Math.max(край, b)
  }

  const свободноМин = Math.max(0, окно - занятоМин)
  const части: string[] = []
  if (занятоМин > 0) части.push(`встречи ${часы(занятоМин)}`)
  if (намечено > 0) части.push(`намечено дел: ${намечено}`)
  if (части.length === 0) return { занято: 0, свободно: свободноМин / 60, text: null, перегруз: false }

  части.push(свободноМин > 0 ? `свободно ${часы(свободноМин)}`
    : 'свободного времени не осталось')
  return {
    занято: занятоМин / 60,
    свободно: свободноМин / 60,
    text: части.join(' · '),
    перегруз: свободноМин === 0 && занятоМин > 0,
  }
}
