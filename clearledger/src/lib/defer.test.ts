/**
 * Граница сокрытия: клиент обязан думать то же, что сервер.
 *
 * Сервер (`placement.clamp_defer`) отказывает, когда срок наступил или прошёл:
 * `day <= today`. Витрина сначала гасила пункт только на ПРОСРОЧЕННОМ, то есть
 * на день позже, — и человек со сроком «сегодня» получал отказ уже после
 * нажатия. Ровно то, ради чего гашение и делалось.
 *
 * Правило простое, но у него есть край, на котором оно и разъехалось, поэтому
 * край проверяется отдельно.
 */
import test from 'node:test'
import assert from 'node:assert/strict'

import { todayKey } from './personalDay.ts'

/** Та же формула, что в `PlaceActions`. */
function нельзяПрятать(dueAt: string | null | undefined,
                       сегодня = todayKey()): boolean {
  return !!dueAt && todayKey(new Date(dueAt)) <= сегодня
}

const СЕГОДНЯ = '2026-08-30'
const в = (д: string, ч = 12) => new Date(`${д}T${String(ч).padStart(2, '0')}:00:00`)

test('без срока прятать можно', () => {
  assert.equal(нельзяПрятать(null, СЕГОДНЯ), false)
  assert.equal(нельзяПрятать(undefined, СЕГОДНЯ), false)
})

test('будущий срок прятать можно', () => {
  assert.equal(нельзяПрятать(в('2026-08-31').toISOString(), СЕГОДНЯ), false)
  assert.equal(нельзяПрятать(в('2026-12-01').toISOString(), СЕГОДНЯ), false)
})

test('срок СЕГОДНЯ — уже нельзя: тот самый день расхождения', () => {
  assert.equal(нельзяПрятать(в(СЕГОДНЯ, 9).toISOString(), СЕГОДНЯ), true,
    'сервер откажет, и витрина обязана знать это до нажатия')
  assert.equal(нельзяПрятать(в(СЕГОДНЯ, 23).toISOString(), СЕГОДНЯ), true,
    'вечер того же дня — всё ещё сегодня')
})

test('прошедший срок прятать нельзя', () => {
  assert.equal(нельзяПрятать(в('2026-08-29').toISOString(), СЕГОДНЯ), true)
  assert.equal(нельзяПрятать(в('2026-01-01').toISOString(), СЕГОДНЯ), true)
})

test('граница считается по местному дню, а не по UTC', () => {
  // Полночь местного времени 31-го — это ещё 30-е в UTC западнее Гринвича и
  // уже 31-е восточнее. Сравнивать надо календарные дни, иначе срок «завтра в
  // 00:30» у московского пользователя превращался бы в «сегодня».
  const завтраРано = new Date('2026-08-31T00:30:00')
  assert.equal(нельзяПрятать(завтраРано.toISOString(), СЕГОДНЯ), false,
    'ранний час завтрашнего дня — это завтра')
})
