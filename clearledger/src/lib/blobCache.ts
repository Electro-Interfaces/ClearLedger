/**
 * Кеш объектных ссылок на скачанные вложения — и правило, ради которого он написан:
 * **пока ссылку кто-то показывает, отзывать её нельзя.**
 *
 * `URL.revokeObjectURL` гасит адрес мгновенно и у всех сразу. Пока кеш держал
 * двенадцать записей и вытеснял их не глядя, открытая переписка ломала сама себя:
 * человек нажимал «показать видео», ролик выкачивался, следом подгружались снимки
 * ленты — ролик вытеснялся, ссылка отзывалась, и на его месте оставалась карточка,
 * которая «не подгружается» (жалоба РусГидро 14.09.2026).
 *
 * Поэтому запись считает, сколько компонентов её показывают: `взять` перед показом,
 * `отпустить` после. Вытесняется только то, что никому не нужно.
 */

type Запись = { url: string; держат: number }

const кеш = new Map<string, Запись>()

/** Лента легко показывает разом два десятка вложений: снимки, кадры видео, альбом. */
const ПРЕДЕЛ = 40

function отозвать(url: string): void {
  try {
    URL.revokeObjectURL(url)
  } catch {
    // Среда без объектных ссылок (тест, сервер) — отзывать нечего.
  }
}

/** Убрать самые старые записи, которые никто не показывает. */
function вытеснить(): void {
  if (кеш.size <= ПРЕДЕЛ) return
  for (const [path, запись] of [...кеш.entries()]) {
    if (кеш.size <= ПРЕДЕЛ) break
    if (запись.держат > 0) continue
    кеш.delete(path)
    отозвать(запись.url)
  }
}

export function положить(path: string, url: string): Запись {
  const прежняя = кеш.get(path)
  // Прежнюю ссылку отзываем, только если её никто не держит: иначе гасим то, что
  // прямо сейчас на экране.
  if (прежняя && прежняя.url !== url && прежняя.держат === 0) отозвать(прежняя.url)
  const запись: Запись = { url, держат: прежняя?.держат ?? 0 }
  кеш.delete(path)
  кеш.set(path, запись)
  вытеснить()
  return запись
}

export function найти(path: string): string | null {
  return кеш.get(path)?.url ?? null
}

/** Компонент начал показывать вложение: пока держит — ссылка живёт. */
export function взять(path: string): Запись | null {
  const запись = кеш.get(path)
  if (!запись) return null
  запись.держат += 1
  return запись
}

/** Компонент ушёл с экрана: ссылка снова может быть вытеснена. */
export function отпустить(path: string): void {
  const запись = кеш.get(path)
  if (!запись) return
  запись.держат = Math.max(0, запись.держат - 1)
  вытеснить()
}

export function очистить(): void {
  кеш.forEach((запись) => отозвать(запись.url))
  кеш.clear()
}

/** Состояние кеша — для проверок политики вытеснения. */
export function состояние(): { path: string; url: string; держат: number }[] {
  return [...кеш.entries()].map(([path, з]) => ({ path, url: з.url, держат: з.держат }))
}

export const ПРЕДЕЛ_КЕША = ПРЕДЕЛ
