/** Куда вернуть человека после входа: адрес, с которого его завернули на `/login`.
 *
 * Ссылку на работу (`/t/TF-42`) открывают из письма в свежей вкладке, поэтому
 * адрес обязан пережить логин — иначе ссылка приводит на главную и человек ищет
 * работу руками, ради чего ссылку и давали.
 *
 * Берём только внутренний путь: `//evil.example` браузер считает адресом чужого
 * сайта, и «возврат» увёл бы туда вместе со свежей сессией.
 */
export function safeBackTo(from: unknown): string {
  if (typeof from !== 'string') return '/'
  if (!from.startsWith('/') || from.startsWith('//')) return '/'
  if (from === '/login' || from.startsWith('/login?')) return '/'
  return from
}
