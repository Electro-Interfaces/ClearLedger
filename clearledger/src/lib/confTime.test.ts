import { test } from 'node:test'
import assert from 'node:assert/strict'
import { доНачала, скороНачало } from './confTime.ts'

const СЕЙЧАС = Date.parse('2026-10-14T10:00:00Z')
const через = (мин: number) => new Date(СЕЙЧАС + мин * 60_000).toISOString()

test('отсчёт до начала словами', () => {
  assert.equal(доНачала(через(12), СЕЙЧАС), 'через 12 мин')
  assert.equal(доНачала(через(0.5), СЕЙЧАС), 'через 1 мин')
  assert.equal(доНачала(через(60), СЕЙЧАС), 'через 1 ч')
  assert.equal(доНачала(через(200), СЕЙЧАС), 'через 3 ч 20 мин')
  assert.equal(доНачала(через(6 * 24 * 60 + 5), СЕЙЧАС), 'через 6 дней')
  assert.equal(доНачала(через(24 * 60), СЕЙЧАС), 'через 1 день')
  assert.equal(доНачала(через(0), СЕЙЧАС), 'начинается сейчас')
  assert.equal(доНачала(через(-7), СЕЙЧАС), 'должна идти уже 7 мин')
})

test('близкой конференция становится за четверть часа и остаётся до конца своего времени', () => {
  const встреча = (нач: number, кон: number, ещё = {}) =>
    ({ starts_at: через(нач), ends_at: через(кон), status: 'planned', live: false, ...ещё })
  assert.equal(скороНачало(встреча(16, 76), СЕЙЧАС), false)
  assert.equal(скороНачало(встреча(15, 75), СЕЙЧАС), true)
  assert.equal(скороНачало(встреча(-10, 50), СЕЙЧАС), true, 'время идёт, а в неё не вошли')
  assert.equal(скороНачало(встреча(-70, -10), СЕЙЧАС), false, 'время вышло')
  assert.equal(скороНачало(встреча(5, 65, { live: true }), СЕЙЧАС), false, 'идущая — в своём блоке')
  assert.equal(скороНачало(встреча(5, 65, { status: 'cancelled' }), СЕЙЧАС), false)
})
