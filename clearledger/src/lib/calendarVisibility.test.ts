import assert from 'node:assert/strict'
import { test } from 'node:test'

import { видимаВКалендаре } from './calendarVisibility.ts'

const сейчас = new Date('2026-10-25T14:00:00+03:00')
const встреча = (id: string, ends_at: string, status: string | null = 'cancelled') =>
  ({ id, ends_at, status })

test('отменённая сегодняшняя встреча видна без всяких галочек', () => {
  assert.equal(видимаВКалендаре(встреча('a', '2026-10-25T10:30:00+03:00'),
    { сейчас, показыватьПрошедшие: false }), true)
  assert.equal(видимаВКалендаре(встреча('b', '2026-10-28T10:30:00+03:00'),
    { сейчас, показыватьПрошедшие: false }), true)
})

test('прошедшая отменённая скрыта, пока её не попросят', () => {
  const вчерашняя = встреча('c', '2026-10-24T18:00:00+03:00')
  assert.equal(видимаВКалендаре(вчерашняя, { сейчас, показыватьПрошедшие: false }), false)
  assert.equal(видимаВКалендаре(вчерашняя, { сейчас, показыватьПрошедшие: true }), true)
})

test('открытая карточка не пропадает из-под руки', () => {
  assert.equal(видимаВКалендаре(встреча('c', '2026-10-24T18:00:00+03:00'),
    { сейчас, показыватьПрошедшие: false, открытая: 'c' }), true)
})

test('запланированную встречу правило не трогает', () => {
  assert.equal(видимаВКалендаре(встреча('d', '2026-10-01T10:00:00+03:00', 'planned'),
    { сейчас, показыватьПрошедшие: false }), true)
})
