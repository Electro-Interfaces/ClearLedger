/**
 * Открытие приложения экосистемы — общая механика лаунчера и рельса (Ядро).
 *
 * **Продукт открывается в новой вкладке** (решение МАГа 27.07.2026): рабочие места
 * держат открытыми параллельно — эксплуатация в одной вкладке, финансы в другой, — и
 * вызов продукта не должен выбрасывать из того, где человек уже работает.
 *
 * Исключение — сервисы со своей кнопкой рядом (Чат · Заявки · Конференция): они и так
 * под рукой, их вызов ведёт себя как раньше.
 */
import { useCallback, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { toast } from 'sonner'
import { authorizeApp, type SsoApp } from '@/services/ssoService'
import { useCompany } from '@/contexts/CompanyContext'
import { assignTop } from '@/lib/topNav'

function isSameOrigin(url: string) {
  try {
    return new URL(url, window.location.href).origin === window.location.origin
  } catch {
    return false
  }
}

export function useOpenApp() {
  const { companyId } = useCompany()
  const navigate = useNavigate()
  const [busy, setBusy] = useState<string | null>(null)

  const open = useCallback(async (code: string, newTab = false) => {
    if (busy) return
    setBusy(code)
    try {
      // «Конференции» — приложение пространства, а не одно действие: своя
      // страница с идущими созвонами, назначенными встречами и историей
      // (`pages/conf/ConfPage`). Раньше плитка сразу заводила комнату, и
      // человек не мог ни вернуться в свой созвон, ни найти вчерашний.
      if (code === 'conf') {
        assignTop('/conf')
        return
      }
      const url = await authorizeApp(code, companyId)
      // Чужой домен (мост) всегда уходит в новую вкладку: там своя сессия и свой «назад».
      if (newTab || !isSameOrigin(url)) window.open(url, '_blank', 'noopener,noreferrer')
      // Витрина пространства бывает открыта фреймом в чужом приложении — тогда
      // переход уводит верхнее окно, а не рамку панели (`lib/topNav`).
      else assignTop(url)
    } catch (e) {
      const msg = (e as Error).message || ''
      toast.error(/503|не настроен/i.test(msg) ? 'Единый вход не настроен' : 'Не удалось открыть приложение')
    } finally {
      setBusy(null)
    }
  }, [busy, companyId])

  /**
   * Внутренний продукт живёт в этом же SPA, но на десктопе открывается новой вкладкой —
   * как и всякий другой: рабочие места держат рядом, а не вместо друг друга. Токен ему
   * не нужен, сессия уже своя. Сервисы с кнопкой рядом (Чат) остаются навигацией: они
   * часть текущего экрана, а не отдельное рабочее место.
   *
   * На узком экране — всегда в текущей вкладке. Держать рабочие места параллельно в
   * телефоне не выходит: переключение стоит двух жестов через меню браузера, вкладки
   * копятся и теряются, «назад» перестаёт возвращать на стол. Плюс новая вкладка
   * открывается со своими настройками — в режиме эмуляции устройства она приходит
   * сразу в десктопном виде.
   */
  const openApp = useCallback(async (app: SsoApp) => {
    // Продукт пространства — страница, и открывается переходом в текущей вкладке
    // (решение МАГа 21.08.2026). Прежний порядок — каждое рабочее место в свою
    // вкладку — копил их десятками, ломал «назад» и размазывал одно пространство
    // по всему окну браузера. Понадобилось второе окно — браузер умеет открыть
    // ссылку в новой вкладке сам, и это выбор человека, а не приложения.
    if (app.mode === 'internal' && app.route) {
      navigate(app.route)
      return
    }
    // Приложение стека («Поддержка» на /support) живёт на ТОМ ЖЕ домене, и для
    // человека это такая же страница пространства, как внутренние продукты.
    // Принудительная новая вкладка здесь открывала его отдельным окном — из
    // установленного приложения пространства особенно заметно: рядом с окном
    // пространства появлялось второе, со своим заголовком и без пути назад.
    //
    // Решение о вкладке принимает `open`: свой домен — переход, чужой (мост) —
    // по-прежнему отдельная вкладка, там своя сессия и свой «назад».
    await open(app.code)
  }, [navigate, open])

  return { open, openApp, busy }
}
