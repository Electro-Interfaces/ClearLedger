/**
 * Иконка-подсказка ⓘ у метрики: наводишь/тапаешь — короткое пояснение «что это
 * значит и как считается». Самодостаточна (свой TooltipProvider), ставится
 * одной строкой рядом с подписью метрики: `<MetricHint text={HINTS.visitSuccess} />`.
 *
 * Зачем: часть метрик ЭЗС читается неоднозначно (успех сессий vs визитов —
 * 69% против 89,3%; idle только по DC; концентрация топ-X%→Y%). Пояснение прямо
 * у цифры снимает вопрос «это ошибка?» без ухода в документацию.
 */
import { HelpCircle } from 'lucide-react'
import { Tooltip, TooltipTrigger, TooltipContent, TooltipProvider } from '@/components/ui/tooltip'
import { cn } from '@/lib/utils'

export function MetricHint({ text, className }: { text: string; className?: string }) {
  return (
    <TooltipProvider delayDuration={100}>
      <Tooltip>
        <TooltipTrigger asChild>
          <button
            type="button"
            aria-label="Пояснение"
            onClick={(e) => e.stopPropagation()}
            className={cn(
              'inline-flex align-middle text-muted-foreground/70 hover:text-foreground transition-colors',
              className,
            )}
          >
            <HelpCircle className="h-3.5 w-3.5" />
          </button>
        </TooltipTrigger>
        <TooltipContent className="max-w-[280px] leading-snug">{text}</TooltipContent>
      </Tooltip>
    </TooltipProvider>
  )
}

