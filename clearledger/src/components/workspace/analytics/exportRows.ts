/**
 * Атрибуты на <table> с сырыми ЧИСЛАМИ для выгрузки в Excel.
 *
 * Экспортёр (`services/chargeExport.ts`) сначала ищет эти атрибуты и только потом
 * читает текст из ячеек. Разница видна в файле: на экране в клетке стоит
 * «12 ЭЗС (3)» или «1,2 млн ₽» — человеку так понятнее, а в Excel это текст,
 * который не складывается. С сырыми числами столбец суммируется и сортируется,
 * ради чего выгрузку и просят.
 *
 * `data-export-name` задаёт имя листа книги: без него листы называются
 * «Таблица 1», «Таблица 2», и в книге на пять вкладок уже не разобраться.
 */
export function exportRows(
  name: string,
  columns: string[],
  /** `undefined` допустим наравне с `null`: поле, которого в ответе нет, и поле с
   *  пустым значением — одно и то же пустое место в клетке. */
  rows: (string | number | null | undefined)[][],
) {
  return { 'data-export-name': name, 'data-export-rows': JSON.stringify({ columns, rows }) }
}
